#!/usr/bin/env python3
"""Writes 3ds/core/pd_shiny_gen.c: which ROMs get the SHINY marks and shiny icons, and their shiny check, from the app's
ShinyOdds.kt (RETAIL_SHA1S: every other-language / LeafGreen / Ruby / Sapphire retail cart, vanilla's 8; HACK_SHINY_BELOW:
each checked hack's own value). English FireRed / Emerald get 8 in pd_game.c once their retail hash checks out (Poller.kt).

    python3 3ds/tools/gen_shiny.py [--check]
"""
import os
import re
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
SRC = os.path.join(ROOT, "app/src/main/kotlin/com/pokedaisy/app/companion/data/ShinyOdds.kt")
OUT = os.path.join(ROOT, "3ds/core/pd_shiny_gen.c")


def block(text, decl):
    body = text[text.index(decl):]
    return body[:body.index("\n    )\n")]


def main():
    text = open(SRC, encoding="utf-8").read()
    retail = re.findall(r'"([0-9a-f]{40})", // (.*)', block(text, "val RETAIL_SHA1S"))
    hacks = re.findall(r'"([0-9a-f]{40})" to (\d+), // (.*)', block(text, "val HACK_SHINY_BELOW"))
    assert retail and hacks
    out = ["// Generated by 3ds/tools/gen_shiny.py from the app's ShinyOdds.kt - do not hand-edit.",
           '#include "pd_game.h"', "", "const struct pd_shiny_rom pd_shiny_roms[] = {"]
    out += [f'    {{"{h}", 8}}, // {c.strip()}' for h, c in retail]
    out += [f'    {{"{h}", {n}}}, // {c.strip()}' for h, n, c in hacks]
    out += ["    {NULL, 0},", "};", ""]
    data = "\n".join(out)
    if "--check" in sys.argv:
        if open(OUT, encoding="utf-8").read() != data:
            sys.exit("gen_shiny: pd_shiny_gen.c is stale")
        return
    open(OUT, "w", encoding="utf-8").write(data)
    print(f"wrote {os.path.relpath(OUT, ROOT)}: {len(retail)} retail, {len(hacks)} hacks")


if __name__ == "__main__":
    main()
