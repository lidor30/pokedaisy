#!/usr/bin/env python3
"""Writes 3ds/core/pd_save_tables_gen.c: what the SAVE EDITOR and TRADE SAVES need beyond the save itself, from the app's
SpeciesDexGen.kt (the species' National / Hoenn Dex numbers and the trade evolutions; numbers only).

    python3 3ds/tools/gen_save_tables.py [--check]
"""
import os
import re
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
SRC = os.path.join(ROOT, "app/src/main/kotlin/com/pokedaisy/app/companion/data/save/SpeciesDexGen.kt")
OUT = os.path.join(ROOT, "3ds/core/pd_save_tables_gen.c")


def ints(text, decl):
    body = text[text.index(decl):]
    body = body[body.index("(") + 1:body.index("\n)")]
    return [int(n) for n in re.findall(r"\d+", body)]


def main():
    text = open(SRC, encoding="utf-8").read()
    national = ints(text, "val speciesNationalDex")
    hoenn = ints(text, "val speciesHoennDex")
    evos = re.findall(r"TradeEvolution\((\d+), (\d+), (\d+)\), // (.*)", text)
    assert len(national) == len(hoenn) == 412 and evos
    out = ["// Generated by 3ds/tools/gen_save_tables.py from the app's SpeciesDexGen.kt - do not hand-edit.",
           '#include "pd_save.h"', "",
           "const uint16_t pd_species_national[PD_SAVE_SPECIES] = {"]
    for i in range(0, len(national), 20):
        out.append("    " + ", ".join(str(n) for n in national[i:i + 20]) + ",")
    out += ["};", "", "const uint16_t pd_species_hoenn[PD_SAVE_SPECIES] = {"]
    for i in range(0, len(hoenn), 20):
        out.append("    " + ", ".join(str(n) for n in hoenn[i:i + 20]) + ",")
    out += ["};", "", "const struct pd_trade_evolution pd_trade_evolutions[] = {"]
    out += [f"    {{ {s}, {i}, {t} }}, // {c.strip()}" for s, i, t, c in evos]
    out += ["};", "const int pd_trade_evolution_count = sizeof pd_trade_evolutions / sizeof pd_trade_evolutions[0];", ""]
    text = "\n".join(out)
    if "--check" in sys.argv:
        if open(OUT, encoding="utf-8").read() != text:
            sys.exit(f"{OUT} is stale: run python3 3ds/tools/gen_save_tables.py")
        return
    open(OUT, "w", encoding="utf-8").write(text)


if __name__ == "__main__":
    main()
