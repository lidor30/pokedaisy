#!/usr/bin/env python3
"""Writes 3ds/core/pd_save_tables_gen.c: what the SAVE EDITOR and TRADE SAVES need beyond the save itself, from the app's
generated Kotlin (numbers and the games' English ability names only):

- SpeciesDexGen.kt: the species' National / Hoenn Dex numbers and the trade evolutions.
- SaveSpeciesGen.kt: base stats, abilities, gender ratios, ability names.
- SaveTablesGen.kt (Gen3Legal's tables): pre-evolutions, gTMHMMoves, and per game family the bag's items by pocket, the
  level-up learnsets, the TM / HM and move tutor bits.
- MoveStatsGen.kt: each move's PP.

    python3 3ds/tools/gen_save_tables.py [--check]
"""
import os
import re
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
SAVE = os.path.join(ROOT, "app/src/main/kotlin/com/pokedaisy/app/companion/data/save")
DEX = os.path.join(SAVE, "SpeciesDexGen.kt")
SPECIES = os.path.join(SAVE, "SaveSpeciesGen.kt")
TABLES = os.path.join(SAVE, "SaveTablesGen.kt")
MOVES = os.path.join(ROOT, "app/src/main/kotlin/com/pokedaisy/app/companion/data/MoveStatsGen.kt")
OUT = os.path.join(ROOT, "3ds/core/pd_save_tables_gen.c")
FAMILIES = ("RS", "E", "FRLG")  # pd_save_kind's order: RUBY_SAPPHIRE, EMERALD, FIRERED_LEAFGREEN


def body(text, decl):
    """What's between the parentheses after [decl] (the Kotlin list's elements)."""
    at = text.index("(", text.index(decl))
    depth = 0
    for i in range(at, len(text)):
        depth += {"(": 1, ")": -1}.get(text[i], 0)
        if depth == 0:
            return text[at + 1:i]
    raise SystemExit(f"no end to {decl}")


def ints(text, decl):
    return [int(n) for n in re.findall(r"-?\d+", body(text, decl))]


def strings(text, decl):
    return re.findall(r'"([^"]*)"', body(text, decl))


def main():
    dex = open(DEX, encoding="utf-8").read()
    species = open(SPECIES, encoding="utf-8").read()
    tables = open(TABLES, encoding="utf-8").read()
    moves = open(MOVES, encoding="utf-8").read()
    national = ints(dex, "val speciesNationalDex")
    hoenn = ints(dex, "val speciesHoennDex")
    evos = re.findall(r"TradeEvolution\((\d+), (\d+), (\d+)\), // (.*)", dex)
    assert len(national) == len(hoenn) == 412 and evos
    base = ints(species, "val saveBaseStats")
    abilities = ints(species, "val saveAbilities")
    genders = ints(species, "val saveGenderRatios")
    ability_names = strings(species, "val saveAbilityNames")
    assert len(base) == 412 * 6 and len(abilities) == 412 * 2 and len(genders) == 412, (len(base), len(abilities), len(genders))
    pre = ints(tables, "val preEvolution")
    tmhm = ints(tables, "val tmHmMoves")
    assert len(pre) == 412 and len(tmhm) == 58
    pp = [int(m) for m in re.findall(r'MoveStats\("[A-Z_0-9]*", \d+, (\d+), \d+, -?\d+\)', moves)]
    assert len(pp) >= 355, len(pp)
    pp = pp[:355]

    out = ["// Generated by 3ds/tools/gen_save_tables.py from the app's SpeciesDexGen.kt, SaveSpeciesGen.kt, SaveTablesGen.kt",
           "// and MoveStatsGen.kt - do not hand-edit.",
           '#include "pd_save.h"', ""]
    out += ["const uint16_t pd_species_national[PD_SAVE_SPECIES] = {"]
    for i in range(0, len(national), 20):
        out.append("    " + ", ".join(str(n) for n in national[i:i + 20]) + ",")
    out += ["};", "", "const uint16_t pd_species_hoenn[PD_SAVE_SPECIES] = {"]
    for i in range(0, len(hoenn), 20):
        out.append("    " + ", ".join(str(n) for n in hoenn[i:i + 20]) + ",")
    out += ["};", "", "const struct pd_trade_evolution pd_trade_evolutions[] = {"]
    out += [f"    {{ {s}, {i}, {t} }}, // {c.strip()}" for s, i, t, c in evos]
    out += ["};", "const int pd_trade_evolution_count = sizeof pd_trade_evolutions / sizeof pd_trade_evolutions[0];", ""]

    out += ["// gSpeciesInfo: base stats (HP, Attack, Defense, Speed, Sp. Atk, Sp. Def), abilities, gender ratio.",
            "const uint8_t pd_save_base_stats[PD_SAVE_SPECIES][6] = {"]
    for s in range(412):
        out.append("    { " + ", ".join(str(v) for v in base[s * 6:s * 6 + 6]) + " },")
    out += ["};", "const uint8_t pd_save_abilities[PD_SAVE_SPECIES][2] = {"]
    for i in range(0, 412, 10):
        out.append("    " + " ".join(f"{{ {abilities[s * 2]}, {abilities[s * 2 + 1]} }}," for s in range(i, min(i + 10, 412))))
    out += ["};"]
    out += ["const uint8_t pd_save_gender_ratios[PD_SAVE_SPECIES] = {"]
    for i in range(0, 412, 20):
        out.append("    " + ", ".join(str(v) for v in genders[i:i + 20]) + ",")
    out += ["};", "const char* const pd_save_ability_names[] = {"]
    for i in range(0, len(ability_names), 6):
        out.append("    " + " ".join(f'"{n}",' for n in ability_names[i:i + 6]))
    out += ["};", f"const int pd_save_ability_names_count = {len(ability_names)};", ""]

    out += ["// Each species' pre-evolution (0 = none), gTMHMMoves (TM01..TM50, HM01..HM08), each move's PP."]
    out += ["const uint16_t pd_save_pre_evolution[PD_SAVE_SPECIES] = {"]
    for i in range(0, 412, 20):
        out.append("    " + ", ".join(str(v) for v in pre[i:i + 20]) + ",")
    out += ["};", "const uint16_t pd_save_tmhm_moves[PD_SAVE_TMHM] = {"]
    for i in range(0, 58, 20):
        out.append("    " + ", ".join(str(v) for v in tmhm[i:i + 20]) + ",")
    out += ["};", "const uint8_t pd_save_move_pp[PD_SAVE_LAST_MOVE + 1] = {"]
    for i in range(0, 355, 25):
        out.append("    " + ", ".join(str(v) for v in pp[i:i + 25]) + ",")
    out += ["};", ""]

    for fam in FAMILIES:
        items = ints(tables, f"val bagItems{fam} ")
        assert len(items) % 2 == 0 and items
        level_up = strings(tables, f"val levelUp{fam} ")
        tm = strings(tables, f"val tmHm{fam} ")
        tutor_moves = ints(tables, f"val tutorMoves{fam} ")
        tutors = strings(tables, f"val tutors{fam} ")
        assert len(level_up) == len(tm) == len(tutors) == 412, (fam, len(level_up), len(tm), len(tutors))
        assert len(tutor_moves) <= 32
        lo = fam.lower()
        out += [f"// {fam}: the bag's items (id, pocket: 1 items / 2 balls / 3 TMs & HMs / 4 berries).",
                f"static const uint16_t bag_{lo}[][2] = {{"]
        pairs = [(items[i], items[i + 1]) for i in range(0, len(items), 2)]
        for i in range(0, len(pairs), 10):
            out.append("    " + " ".join(f"{{ {a}, {b} }}," for a, b in pairs[i:i + 10]))
        out += ["};"]
        # Level-up moves packed as the decomps' LEVEL_UP_MOVE (level << 9 | move), every species' run from its start.
        packed, starts = [], []
        for s in level_up:
            starts.append(len(packed))
            for k in range(0, len(s), 5):
                lv, mv = int(s[k:k + 2], 16), int(s[k + 2:k + 5], 16)
                assert lv <= 100 and mv <= 354
                packed.append(lv << 9 | mv)
        starts.append(len(packed))
        out += [f"static const uint16_t level_up_{lo}[] = {{"]
        for i in range(0, len(packed), 16):
            out.append("    " + ", ".join(f"0x{v:04X}" for v in packed[i:i + 16]) + ",")
        out += ["};", f"static const uint16_t level_up_start_{lo}[PD_SAVE_SPECIES + 1] = {{"]
        for i in range(0, len(starts), 20):
            out.append("    " + ", ".join(str(v) for v in starts[i:i + 20]) + ",")
        out += ["};", f"static const uint64_t tmhm_{lo}[PD_SAVE_SPECIES] = {{"]
        for i in range(0, 412, 6):
            out.append("    " + " ".join(f"0x{int(t, 16):X}ull," for t in tm[i:i + 6]))
        out += ["};", f"static const uint32_t tutors_{lo}[PD_SAVE_SPECIES] = {{"]
        for i in range(0, 412, 10):
            out.append("    " + " ".join(f"0x{int(t, 16):X}u," for t in tutors[i:i + 10]))
        out += ["};"]
        if tutor_moves:
            out += [f"static const uint16_t tutor_moves_{lo}[] = {{ " + ", ".join(map(str, tutor_moves)) + " };"]
        out += [""]
    out += ["const struct pd_save_legal pd_save_legal[3] = {"]
    for fam in FAMILIES:
        lo = fam.lower()
        tm_count = len(ints(tables, f"val tutorMoves{fam} "))
        tutor = f"tutor_moves_{lo}" if tm_count else "NULL"
        out.append(f"    {{ bag_{lo}, sizeof bag_{lo} / sizeof bag_{lo}[0], level_up_{lo}, level_up_start_{lo}, tmhm_{lo}, tutors_{lo}, "
                   f"{tutor}, {tm_count} }},")
    out += ["};", ""]
    text = "\n".join(out)
    if "--check" in sys.argv:
        if open(OUT, encoding="utf-8").read() != text:
            sys.exit(f"{OUT} is stale: run python3 3ds/tools/gen_save_tables.py")
        return
    open(OUT, "w", encoding="utf-8").write(text)


if __name__ == "__main__":
    main()
