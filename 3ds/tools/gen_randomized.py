#!/usr/bin/env python3
"""Writes 3ds/core/pd_randomized_gen.c: the app's RANDOMIZED_RETAIL (RandomizedRetailGen.kt, from
scripts/gen_randomized_retail.py) as C - retail English FireRed rev 0 / 1 and Emerald as Universal Pokemon Randomizer ZX
leaves them: the bytes to hash, the masked sites, the species names to fold, the tables to read the randomizer's data from
and the GUIDE's item balls, trades and gifts. Offsets and hashes only, no ROM bytes. Rerun after the Kotlin changes:

    python3 3ds/tools/gen_randomized.py
"""
import os
import re

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
SRC = os.path.join(ROOT, "app/src/main/kotlin/com/pokedaisy/app/companion/data/RandomizedRetailGen.kt")
OUT = os.path.join(ROOT, "3ds/core/pd_randomized_gen.c")


def fields(block):
    """name -> value of one RandomizedRetailRom(...): strings joined across `+`, numbers as ints."""
    out = {}
    for m in re.finditer(r"(\w+) =\s*((?:\"[^\"]*\"\s*\+?\s*)+|0x[0-9A-Fa-f]+|\d+)", block):
        v = m.group(2)
        out[m.group(1)] = "".join(re.findall(r'"([^"]*)"', v)) if v.startswith('"') else int(v, 0)
    return out


def ranges(s):
    """RandomizedRetailRom.maskRanges: "start:len[:count:stride]" (hex) as merged [start, end) pairs."""
    raw = []
    for e in filter(None, s.split(",")):
        f = [int(x, 16) for x in e.split(":")]
        count, stride = (f[2], f[3]) if len(f) > 2 else (1, 0)
        raw += [(f[0] + i * stride, f[0] + i * stride + f[1]) for i in range(count)]
    out = []
    for a, z in sorted(raw):
        if out and a <= out[-1][1]:
            out[-1] = (out[-1][0], max(out[-1][1], z))
        else:
            out.append((a, z))
    return out


def pairs(s):
    return [e.split(":") for e in filter(None, s.split(","))]


def main():
    text = open(SRC, encoding="utf-8").read()
    blocks = re.findall(r"RandomizedRetailRom\((.*?)\n    \),", text, re.S)
    assert blocks, "no RandomizedRetailRom"
    out = ["// Generated by 3ds/tools/gen_randomized.py from the app's RandomizedRetailGen.kt - don't edit. Offsets and hashes",
           "// only: no ROM bytes.", '#include "pd_randomized.h"', ""]
    rows = []
    for i, b in enumerate(blocks):
        f = fields(b)
        mask, fold = ranges(f["mask"]), ranges(f["fold"])
        items = [(int(a, 16), int(o, 16)) for a, o in pairs(f["fieldItems"])]
        trades = [(int(k.split("/")[0]), int(k.split("/")[1]), int(r)) for k, r in pairs(f["tradeRows"])]
        statics = [(int(a, 16), int(o, 16)) for a, o in pairs(f["statics"])]
        def arr(name, ctype, cols, vals):
            out.append(f"static const {ctype} {name}_{i}[{max(len(vals), 1)}][{cols}] = {{")
            for k in range(0, len(vals), 6):
                out.append("    " + " ".join("{ " + ", ".join(f"0x{x:X}" for x in v) + " }," for v in vals[k:k + 6]))
            out.append("};")
        arr("mask", "uint32_t", 2, mask)
        arr("fold", "uint32_t", 2, fold)
        arr("items", "uint32_t", 2, items)
        arr("trades", "uint16_t", 3, trades)
        arr("statics", "uint32_t", 2, statics)
        out.append("")
        rows.append(f'    {{ "{f["code"]}", {f["rev"]}, 0x{f["end"]:X}, "{f["sha1"]}", "{f["retailSha1"]}", 0x{f["baseStats"]:X}, '
                    f'0x{f["battleMoves"]:X}, 0x{f["typeChart"]:X}, 0x{f["trades"]:X},\n'
                    f'      mask_{i}, {len(mask)}, fold_{i}, {len(fold)}, items_{i}, {len(items)}, trades_{i}, {len(trades)}, '
                    f'statics_{i}, {len(statics)} }},')
    out.append("const struct pd_randomized pd_randomized_roms[] = {")
    out += rows
    out.append("};")
    out.append(f"const int pd_randomized_rom_count = {len(rows)};")
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write("\n".join(out) + "\n")
    print(f"wrote {os.path.relpath(OUT, ROOT)}: {len(rows)} randomized retail ROMs")


if __name__ == "__main__":
    main()
