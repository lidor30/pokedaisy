#!/usr/bin/env python3
"""Writes 3ds/core/pd_gb_art_gen.c: Polished Crystal's font address per release build, from the app's
Gen2PolishedCrystalGen.kt (Gen2Art.POLISHED_CRYSTAL's font = at(0)). The other carts' font addresses are fixed per game
(pd_game.c, from Gen1Art.kt / Gen2Art.kt).

    python3 3ds/tools/gen_gb_art.py [--check]
"""
import os
import re
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
SRC = os.path.join(ROOT, "app/src/main/kotlin/com/pokedaisy/app/companion/data/Gen2PolishedCrystalGen.kt")
OUT = os.path.join(ROOT, "3ds/core/pd_gb_art_gen.c")


def main():
    src = open(SRC, encoding="utf-8").read()
    rows = re.findall(r'"([0-9a-f]{40})" to intArrayOf\((0x[0-9A-F]+),[^\n]*?// (\S+)', src)
    assert rows, "gen_gb_art: no builds read"
    out = ["// Generated by 3ds/tools/gen_gb_art.py from the app's Gen2PolishedCrystalGen.kt - do not hand-edit.",
           "// Polished Crystal's font (FontNormal) per release build, as Gen2Art.POLISHED_CRYSTAL's font = at(0).",
           '#include "pd_gb.h"', "", "const struct pd_gb_font_at pd_gb_polished_fonts[] = {"]
    for sha, a, name in rows:
        v = int(a, 16)
        bank, addr = v >> 16, v & 0xFFFF
        off = addr if bank == 0 else bank * 0x4000 + (addr - 0x4000)
        out.append(f'    {{"{sha}", 0x{off:X}}}, // {name}')
    out += ["    {NULL, 0},", "};", ""]
    data = "\n".join(out)
    if "--check" in sys.argv:
        if open(OUT, encoding="utf-8").read() != data:
            sys.exit("gen_gb_art: pd_gb_art_gen.c is stale")
        return
    open(OUT, "w", encoding="utf-8").write(data)
    print(f"wrote {os.path.relpath(OUT, ROOT)}: {len(rows)} builds")


if __name__ == "__main__":
    main()
