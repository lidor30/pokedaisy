#!/usr/bin/env python3
"""core/pd_icons_gen.c: the app's pixel icons, from PixelIcons.kt and TabIcons.kt, so both draw the same bitmaps.

    python3 3ds/tools/gen_icons.py
"""
import os
import re

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
UI = os.path.join(ROOT, "app/src/main/kotlin/com/pokedaisy/app/companion/ui")
OUT_C = os.path.join(ROOT, "3ds/core/pd_icons_gen.c")
OUT_H = os.path.join(ROOT, "3ds/core/pd_icons_gen.h")

# The PixelIcons the port draws.
MONO = ["gear", "more", "arrowUp", "back", "male", "female", "expand", "shrink", "filter", "arrowBack", "star",
        "sparkle", "clock", "itemAction", "inGame", "check", "trophy", "cursorLeft", "chevronRight", "disc", "info",
        "search", "lockClosed", "lockOpen", "zoomIn", "zoomOut"]
TAB_ORDER = ["party", "dex", "map", "bag", "boxes", "guide", "grave", "card", "states", "achievements"]


def rows_of(text, start):
    i = text.index("listOf(", start) + len("listOf(")
    depth, j = 1, i
    while depth:
        depth += {"(": 1, ")": -1}.get(text[j], 0)
        j += 1
    return re.findall(r'"([^"]*)"', text[i:j]), j


def tab_at(tabs, name):
    return re.search(r"val %s\b" % name, tabs).start()


def c_name(name):
    return re.sub(r"([A-Z])", r"_\1", name).upper()


def main():
    pixel = open(os.path.join(UI, "PixelIcons.kt")).read()
    tabs = open(os.path.join(UI, "TabIcons.kt")).read()
    header = ["// Generated by 3ds/tools/gen_icons.py from the app's PixelIcons.kt / TabIcons.kt - don't edit by hand.",
              "#ifndef PD_ICONS_GEN_H", "#define PD_ICONS_GEN_H", "", "#include <stdint.h>", ""]
    body = ["// Generated by 3ds/tools/gen_icons.py from the app's PixelIcons.kt / TabIcons.kt - don't edit by hand.",
            '#include "pd_icons_gen.h"', ""]
    header += ["// A one-colour icon: rows of '1' / '0'.", "struct pd_mono { int w, h; const char* const* rows; };", "",
               "// A coloured one: each character a colour of keys / colors, '.' see-through.",
               "struct pd_art { int w, h; const char* const* rows; const char* keys; const uint32_t* colors; };", ""]
    for name in MONO:
        m = re.search(r"val %s(: List<String>)? = listOf\(" % name, pixel)
        rows, _ = rows_of(pixel, m.start())
        body.append(f"static const char* const {name}Rows[] = {{")
        body += [f'    "{r}",' for r in rows]
        body += ["};", f"const struct pd_mono PD_ICON_{c_name(name)} = {{ {max(map(len, rows))}, {len(rows)}, {name}Rows }};", ""]
        header.append(f"extern const struct pd_mono PD_ICON_{c_name(name)};")
    header.append("")
    consts = dict(re.findall(r"private val (\w+) = Color\(0xFF([0-9A-Fa-f]{6})\)", tabs))
    for name in TAB_ORDER:
        start = tab_at(tabs, name)
        rows, end = rows_of(tabs, start)
        m = re.search(r"mapOf\((.*?)\n?\s*\),\n\s*\)", tabs[end:], re.S)
        pairs = re.findall(r"'(.)' to (?:Color\(0xFF([0-9A-Fa-f]{6})\)|(\w+))", tabs[end:end + m.end()])
        keys = "".join(p[0] for p in pairs)
        colors = ", ".join("0x" + (p[1] or consts[p[2]]).upper() for p in pairs)
        body.append(f"static const char* const tab_{name}[] = {{")
        body += [f'    "{r}",' for r in rows]
        body += ["};", f"static const uint32_t tab_{name}_colors[] = {{ {colors} }};", ""]
    body.append("const struct pd_art PD_TAB_ART[] = {")
    for name in TAB_ORDER:
        rows, _ = rows_of(tabs, tab_at(tabs, name))
        m = re.search(r"mapOf\((.*?)\n?\s*\),\n\s*\)", tabs[tab_at(tabs, name):], re.S)
        keys = "".join(re.findall(r"'(.)' to", m.group(0)))
        body.append(f'    {{ {len(rows[0])}, {len(rows)}, tab_{name}, "{keys}", tab_{name}_colors }},')
    body.append("};")
    # The PokeDaisy mark.
    logo = open(os.path.join(UI, "LogoGen.kt")).read()
    rows, _ = rows_of(logo, logo.index("val LOGO_ROWS"))
    pairs = re.findall(r"'(.)' to Color\(0xFF([0-9A-Fa-f]{6})\)", logo)
    body.append("static const char* const logoRows[] = {")
    body += [f'    "{r}",' for r in rows]
    body += ["};", "static const uint32_t logoColors[] = { " + ", ".join("0x" + c for _, c in pairs) + " };",
             f'const struct pd_art PD_LOGO = {{ {len(rows[0])}, {len(rows)}, logoRows, "{"".join(k for k, _ in pairs)}", logoColors }};']
    header += ["extern const struct pd_art PD_LOGO;"]
    header += ["// The MORE tiles, in this order: PARTY DEX MAP BAG BOXES GUIDE NUZLOCKE CARD STATES ACHIEVEMENTS.",
               "extern const struct pd_art PD_TAB_ART[];", "", "#endif"]
    open(OUT_C, "w").write("\n".join(body) + "\n")
    open(OUT_H, "w").write("\n".join(header) + "\n")
    print("wrote", os.path.relpath(OUT_C, ROOT))


if __name__ == "__main__":
    main()
