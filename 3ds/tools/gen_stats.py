#!/usr/bin/env python3
"""Generate summary names from Android MonStats.kt; --check detects drift."""
import argparse
from pathlib import Path
import re

root = Path(__file__).resolve().parents[2]
data = root / "app/src/main/kotlin/com/pokedaisy/app/companion/data"
source = (data / "MonStats.kt").read_text()

def names(decl, count):
    match = re.search(r"val " + decl + r" = listOf\((.*?)\n\)", source, re.S)
    if not match:
        raise SystemExit(f"Missing Android table: {decl}")
    result = re.findall(r'"([^"]*)"', match.group(1))
    if len(result) != count:
        raise SystemExit(f"Unexpected {decl} length: {len(result)}")
    return result

types = {name.lower(): int(i) for i, name in re.findall(
    r'(\d+) to "([^"]*)"', (data / "TypeChartUtil.kt").read_text())}
natures = names("natureNames", 25)
hidden = [types[n.lower()] for n in names("hiddenPowerTypes", 16)]
text = '// Generated by 3ds/tools/gen_stats.py from MonStats.kt / TypeChartUtil.kt.\n#include "pd_tables.h"\n'
text += 'const char* const pd_nature_names[] = {\n'
text += ''.join(f'    "{n.upper()}",\n' for n in natures)
text += '};\nconst int pd_nature_names_count = 25;\n'
text += 'const unsigned char pd_hidden_power_types[16] = {' + ', '.join(map(str, hidden)) + '};\n'
target = root / "3ds/core/pd_stats_gen.c"
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--check", action="store_true")
args = parser.parse_args()
if args.check:
    if not target.exists() or target.read_text() != text:
        raise SystemExit("Summary tables are stale: run python3 3ds/tools/gen_stats.py")
else:
    target.write_text(text)
