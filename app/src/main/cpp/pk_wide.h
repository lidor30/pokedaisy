// PokeDaisy — WIDE: the overworld past the GBA's 240 px, rebuilt from the game's memory (pk_wide.c).
#pragma once

#include <stdbool.h>
#include <stdint.h>

struct mCore;

#define PK_WIDE_W 240
#define PK_WIDE_H 160
/** Most GBA pixels drawn beside the game, per side (21:9 at 160 tall needs 67). */
#define PK_WIDE_MAX_MARGIN 96
/** The largest window pk_wide_view draws (ZOOM's farthest step: 640 x 360 on a 1080p screen, 360 x ~470 on a phone
 * held upright). */
#define PK_WIDE_MAX_VIEW_W 800
#define PK_WIDE_MAX_VIEW_H 800

/** Engines (the layouts below): FireRed / LeafGreen (and the CFRU hacks), Emerald, Ruby / Sapphire, every language and
 * revision, and pokeemerald-expansion. */
enum {
    PK_WIDE_FAMILY_FR = 1,
    PK_WIDE_FAMILY_EM = 2,
    PK_WIDE_FAMILY_RS = 3,
    PK_WIDE_FAMILY_RS_JA = 4,   // Japanese Ruby / Sapphire: gMain and subsprites as FireRed / Emerald have them
    PK_WIDE_FAMILY_EX = 5,      // pokeemerald-expansion (Lazarus, SoulGold): Emerald's map, ObjectEvent.spriteId moved
    PK_WIDE_FAMILY_FR_EX = 6,   // FireRed's map with expansion's objects (Recharged Yellow: a gcc pokefirered)
};

/** A game's config: its addresses (per release: pk_wide_games.h, generated by scripts/gen_wide_tables.py),
 * then its engine's layout (pk_wide.c's FAMILIES). */
enum {
    PK_WIDE_VMAP,              // struct BackupMapLayout { s32 width, height; u16 *map; }
    PK_WIDE_MAP_HEADER,        // gMapHeader: +0 mapLayout, +0xC connections
    PK_WIDE_MAP_GROUPS,        // gMapGroups (ROM): the connected maps' headers
    PK_WIDE_SAVE_BLOCK1_PTR,   // -> pos (s16 x, y); Ruby / Sapphire: the block itself (PK_WIDE_SAVE_STATIC)
    PK_WIDE_CAMERA_OFFSET,     // sFieldCameraOffset: u8 xPixelOffset, yPixelOffset, xTileOffset, yTileOffset
    PK_WIDE_OBJECT_EVENTS,     // gObjectEvents[16], 0x24 each
    PK_WIDE_SPRITES,           // gSprites[64], 0x44 each
    PK_WIDE_COORD_OFFSET,      // gSpriteCoordOffsetX (s16)
    PK_WIDE_COORD_OFFSET_Y,    // gSpriteCoordOffsetY (s16): right after X, but not in Ruby / Sapphire
    PK_WIDE_SPRITE_ORDER,      // u8[64], BuildOamBuffer's order
    PK_WIDE_GMAIN,             // gMain: inBattle is bit 1 of +PK_WIDE_INBATTLE_OFF
    PK_WIDE_CONTROLS_LOCKED,   // ArePlayerFieldControlsLocked's u8 (FireRed's sScriptContext2Enabled); 0 = unknown
    // The objects the game hasn't spawned (far off, ZOOM shows them), drawn from the map's templates; 0 = not drawn:
    PK_WIDE_OBJ_GFX_INFO,      // gObjectEventGraphicsInfoPointers (ROM)
    PK_WIDE_OBJ_PALETTES,      // sObjectEventSpritePalettes { const u16 *data; u16 tag; } (ROM)
    PK_WIDE_OBJ_FACING,        // gInitialMovementTypeFacingDirections (ROM, u8 per movement type)
    PK_WIDE_SPRITE_PAL_TAGS,   // sSpritePaletteTags (u16[16]: which OBJ palette slot holds which tag)
    PK_WIDE_ELEVATION_PRIO,    // sElevationToPriority (ROM, u8[16])
    PK_WIDE_MAP_GROUPS_XOR,    // not an address: what gMapGroups' entries are XORed with (Unbound), else 0
    PK_WIDE_NORMAL_BG3,        // not an address: what DrawMetatile puts on BG3 under a NORMAL metatile (0x3014; Unbound 0)
    PK_WIDE_METATILE_SIZE,     // not an address: 16 (two layers), 24 (triple-layer: BG3, BG2, BG1 - Lazarus)
    PK_WIDE_METATILE_MASK,     // not an address: a map cell's metatile id bits - 0x3FF, SoulGold 0x7FF (all ones = none)
    PK_WIDE_PRIMARY_OVERRIDE,  // not an address: the primary tileset's metatiles where a hack changed them (SoulGold 1024), else 0
    PK_WIDE_PAN_OFF,           // not an address: where sHorizontal / sVerticalCameraPan sit from sFieldCameraOffset - 8
                               // after it (agbcc pads the struct to 8 bytes); a gcc build places them as it likes
    // CFRU's 16-bit object graphics ids (a template's byte 3 picks a table, byte 1 the entry):
    PK_WIDE_OBJ_GFX_TABLES,    // its table of tables (ROM, a pointer per table; 0 = vanilla's 8-bit ids)
    PK_WIDE_OBJ_GFX_TABLE_MAX, // not an address: the last table it looks in (past it: table 0)
    PK_WIDE_OBJ_GFX_VAR_FROM,  // not an address: the first of the 16 ids read from VAR_OBJ_GFX_ID_* (240, Lazarus 0x1ED;
                               // Unbound 256 = none) - and the end of the table (an id past those 16 isn't drawn)
    PK_WIDE_OBJ_GFX_FF_VAR,    // not an address: the var table 0xFF's ids come from (Unbound 0x4080); 0 = not drawn
    PK_WIDE_SB1_OFFSETS,       // not an address: a hack's SaveBlock1.objectEventTemplates, its flags and vars 0x600 / its
                               // vars further on: templates | vars << 16 (0 = the engine's, PK_WIDE_SB1_TEMPLATES ...)
    PK_WIDE_SB1_POS,           // not an address: where SaveBlock1's pos and location sit (0; Quetzal 0x470)
    PK_WIDE_LAYOUT_VERSIONED,  // not an address: 1 = MapLayout's byte 0x18 is a version, and a 0 (an Emerald layout) keeps
                               // the engine's primary split instead of PRIMARY_OVERRIDE (Heart and Soul)
    PK_WIDE_OBJ_GFX_COUNT,     // not an address: the graphics table's length - an id past it (a follower, another table's
                               // data) isn't drawn; 0 = the table ends 16 past OBJ_GFX_VAR_FROM
    PK_WIDE_TEMPLATE_KIND_AT,  // not an address: a hack's own template layout - its kind byte, 1 (Rogue: graphicsId a u16 at
                               // +2); 0 = the engine's (PK_WIDE_TEMPLATE_KIND)
    PK_WIDE_SB1_FLAGS_AT,      // not an address: a hack's SaveBlock1.flags where they don't follow its templates (Recharged
                               // Yellow 0xEFB); 0 = SB1_OFFSETS' templates + 0x600
    PK_WIDE_TRANSITION_PTR,    // battle_transition.c's sTransitionData: non-null from the battle's first flash to its wipe's
                               // end (pk_wide_scene says BATTLE_START before anything shows); 0 = unknown
    PK_WIDE_QUEST_LOG,         // FireRed's gQuestLogState: 2 / 3 while "Previously on your quest" replays the field
                               // (pk_wide_scene says OFF: the camera stays at 1x through it); 0 = unknown / none
    PK_WIDE_EXPANDED_FLAGS,    // CFRU's gExpandedFlags: its GetFlagPointer keeps flags 0x900-0x18FF there, not in SaveBlock1
                               // (an object hidden by one was drawn past the edges); 0 = the engine's flags only
    PK_WIDE_ADDRS,
    PK_WIDE_PRIMARY_METATILES = PK_WIDE_ADDRS,   // 640 FireRed, 512 Emerald
    PK_WIDE_ATTR_OFFSET,       // struct Tileset's metatileAttributes: 0x14 FireRed, 0x10 Emerald
    PK_WIDE_ATTR_SIZE,         // 4 (u32, FireRed) or 2 (u16, Emerald)
    PK_WIDE_LAYER_SHIFT,       // the layer type's bits: 29 (FireRed) / 12 (Emerald)
    PK_WIDE_LAYER_MASK,        // 3 / 0xF
    PK_WIDE_BORDER_SIZED,      // 1: MapLayout.borderWidth / Height at +0x18 / +0x19 (FireRed); 0: Emerald's 2x2
    PK_WIDE_SAVE_STATIC,       // 1: SaveBlock1 sits at PK_WIDE_SAVE_BLOCK1_PTR (Ruby / Sapphire: no pointer)
    PK_WIDE_INBATTLE_OFF,      // gMain's inBattle byte: 0x439, Ruby / Sapphire 0x43D
    PK_WIDE_SUBSPRITE_SIZE,    // struct Subsprite: 4 (s8 x, y), Ruby / Sapphire 8 (u16 x, y; agbcc pads it to 4 bytes)
    PK_WIDE_SPRITE_ID_OFF,     // ObjectEvent.spriteId: 4, expansion 0x23 (its graphicsId is a u16)
    PK_WIDE_SB1_TEMPLATES,     // SaveBlock1.objectEventTemplates (the map's, as the save keeps them); 0 = no ghosts
    PK_WIDE_SB1_FLAGS,         // SaveBlock1.flags
    PK_WIDE_SB1_VARS,          // SaveBlock1.vars (VAR_OBJ_GFX_ID_*)
    PK_WIDE_PRIMARY_PALS,      // BG palettes a primary tileset has: 7 FireRed, 6 Emerald (the rest are the secondary's)
    PK_WIDE_TEMPLATE_KIND,     // ObjectEventTemplate's kind byte (clone or not): 2; expansion 3, its graphicsId a u16 at +1
    PK_WIDE_CONFIG_SIZE
};

/** Sets the running game by its ROM's CRC32 (pk_wide_games.h); 0 or an unknown one switches WIDE off.
 * Returns whether WIDE knows it. */
int pk_wide_configure(uint32_t crc);

/** Whether WIDE has the ROM with this CRC32 (no core needed). */
int pk_wide_knows(uint32_t crc);

/** SCENE SPEEDS / AUTO-RUN / RUN INDOORS: load this game's addresses for [pk_field_state] (0 = none: it says nothing). */
int pk_field_configure(uint32_t crc);

/** Whether [pk_field_state] can read the field of the ROM with this CRC32: WIDE's table or a pending hack's, with its
 * CONTROLS_LOCKED known. Any thread. */
int pk_field_knows(uint32_t crc);

enum {
    PK_FIELD_KNOWN = 1,      // the game is in the table: the other bits mean something
    PK_FIELD_LOCKED = 2,     // a script holds the field's controls (a text box, the START menu, a cutscene)
    PK_FIELD_BATTLE = 4,     // gMain.inBattle
    PK_FIELD_TEXT = 8,       // a text box (or the START menu) up while locked, outside battles: TEXT SPEED's
    PK_FIELD_BIKE = 16,      // the player on a bike (AUTO-RUN leaves B alone: the Acro Bike's wheelie)
    PK_FIELD_WILD_HELD = 32, // WILD ENCOUNTERS set the game's switch: keep calling until it's put back
    PK_FIELD_SURF = 64,      // surfing (or diving)
    PK_FIELD_AVATAR = 128,   // the bike / surf bits are the game's own player state (FIELD SPEED can trust them)
};

/** WILD ENCOUNTERS: the game's sWildEncountersDisabled (EWRAM, found in the ROM by WildEncounters.kt; 0 = none). Call
 * after [pk_field_configure], which forgets it. [wasOff]: WILD ENCOUNTERS is OFF already, so a switch found on is ours
 * (a resume state taken while OFF) and ON puts it back. */
void pk_field_wild(uint32_t addr, bool wasOff);

/** This frame's PK_FIELD_* bits; with [runIndoors], also lets the player run on the current map (gMapHeader); with
 * [wildKeep] < 100, leaves about that share of wild encounters (0 = none). */
int pk_field_state(struct mCore* core, int runIndoors, int wildKeep);

/** Forgets what earlier frames left (a state load, a new core, a rewind). */
void pk_wide_reset(void);

/**
 * Emu thread, after each frame: `out` ((240 + 2 * margin) x 160) gets `frame` (the core's
 * 240 x 160) in the middle and the rebuilt overworld beside it - or, wherever that can't be
 * checked (title, battles, menus, transitions), a glow spread from the frame's own edges,
 * crossfaded. With `centre` set (headless checks), the
 * rebuild of the middle 240 x 160 goes there too, sprites included. Returns how much of the
 * strips is the map, 0..256 (the rest is the glow).
 */
int pk_wide_frame(struct mCore* core, const uint32_t* frame, uint32_t* out, int margin, uint32_t* centre);

/** A window onto the scene in the game frame's pixels ((0, 0) is its top-left corner, the frame 240 x 160): ZOOM and
 * the look-around draw any such window, beside, around or away from the frame. */
struct PkWideView {
    int x, y, w, h;
};

/**
 * pk_wide_frame for any window: `out` (view.w x view.h, at most PK_WIDE_MAX_VIEW_W x _H) gets the frame where the window
 * covers it and the rebuilt scene everywhere else - or, off the map, the glow from the frame's edges, crossfaded.
 */
int pk_wide_view(struct mCore* core, const uint32_t* frame, uint32_t* out, struct PkWideView view, uint32_t* centre);

/** Instead of pk_wide_view, for a frame that won't be shown (fast-forward runs several per screen refresh): keeps the
 * game's RAM after it, as the next frame drawn needs, without drawing anything - most of WIDE's cost. */
void pk_wide_skip(struct mCore* core, const uint32_t* frame);

/** pk_wide_skip for a fast-forwarded frame that IS shown: the RAM history kept, and `out` (view.w x view.h) gets the frame
 * with the ambient glow (the blur rewind and the menus show) around it instead of the rebuilt scene - cheap, no map read.
 * Returns 0 and draws nothing for an unconfigured game. A Game Boy game's glow is the bars its menus have. */
int pk_wide_glow(struct mCore* core, const uint32_t* frame, uint32_t* out, struct PkWideView view);
// A Game Boy game configured with nothing to draw (EXPAND off): its scene only (pk_wide_scene), for the FIELD HUD -
// pk_wide_gb.c's match run on a 1 x 1 window; `skip` (a fast-forwarded frame nobody sees) only notes its RAM.
void pk_wide_probe(struct mCore* core, const uint32_t* frame, int skip);

/** Whether the last frame wants the game seen close up (ZOOM steps back in): anything but the plain overworld - a
 * battle, a menu screen, or the field with its controls locked (a script) and a text box or a screen effect up. */
int pk_wide_wants_close(void);

/** What the last frame is, for ZOOM's camera (one pull-in per event, started before anything shows):
 * FIELD the plain overworld; TEXT the field with its controls locked and a text box / line effect up; OVERLAY a
 * picture on BG0 over most of the field (FireRed's map preview entering a forest or cave - the map around it is
 * dimmed); BATTLE_START a battle's transition has begun (the flashes, then the wipe ~50 frames on); OFF anything
 * else (a battle, the title); FADE a black / white frame between two maps or screens (the camera holds whatever it
 * was doing); MENU a menu screen (party, bag, summary...: PK_WIDE_MODE_MENU). */
enum { PK_WIDE_SCENE_FIELD, PK_WIDE_SCENE_TEXT, PK_WIDE_SCENE_OVERLAY, PK_WIDE_SCENE_BATTLE_START, PK_WIDE_SCENE_OFF,
       PK_WIDE_SCENE_FADE, PK_WIDE_SCENE_MENU };
int pk_wide_scene(void);

/** DAY AND NIGHT: tints the map's BG palettes (0-12) and the sprites' by r / g / b (256 = as is) from the next frame
 * drawn on, in the renderer only (palette RAM untouched). GBA only; emu thread. */
void pk_tint_set(struct mCore* core, int r, int g, int b);

/** PLAYER LOOK: the player's sprite set up again from its graphics record (after the ROM's look changed), and [pal]
 * (32 bytes; NULL = leave the colours) put over its palette slot (the game's two palette buffers and palette RAM, only
 * while they agree: never mid-fade). 1 = done, 0 = not now (ask again on a later frame). */
int pk_look_refresh(struct mCore* core, const uint8_t* pal);

/** FOLLOWER: the Pokémon's six 32x32 frames (south, south step, north, north step, west, west step: 3072 bytes) and its
 * palette (32 bytes); NULL = none. Any thread before the frame, emu thread in practice. */
void pk_follower_set(const uint8_t* frames, const uint8_t* pal);

/** FOLLOWER: drawn from the next frame on (the field), or not (it disappears, and after it comes back appears only once
 * the player steps). */
void pk_follower_show(struct mCore* core, int on);

/** FOLLOWER: its state as text (mgba_dump's followinfo). */
void pk_follower_info(char* out, int n);

/** A game closed: FOLLOWER (its sprite, shown or not) and DAY AND NIGHT's tint go back to none, so the next game starts
 * without the last one's (they live here, not in the core, and the next game's engine starts from none). */
void pk_wide_extras_reset(void);

/** The signal (SIGSEGV...) that made pk_wide_view switch WIDE off for this game, or 0. A fault while drawing never
 * takes the app down: the frame is shown plain until the game is configured again. */
int pk_wide_fault(void);

/** What the last frame's strips showed: nothing drawn (the glow), the map, a battle, or a menu screen's back layer. */
enum { PK_WIDE_MODE_NONE, PK_WIDE_MODE_MAP, PK_WIDE_MODE_BATTLE, PK_WIDE_MODE_MENU };
int pk_wide_last_mode(void);

/** How the last battle frame's strips were drawn past the edges (scripts/wide_battle_shots.py labels its shots with
 * it): any strip at all, mirrored in because BG3 is one 256 px picture repeated, because BG1 / BG2 draw scenery at
 * the edge, or because BG3 doesn't go on past the left / right edge. 0 outside battles. */
enum {
    PK_WIDE_BATTLE_DRAWN = 1, PK_WIDE_BATTLE_REPEATS = 2, PK_WIDE_BATTLE_OFF_BG3 = 4,
    PK_WIDE_BATTLE_BROKEN_LEFT = 8, PK_WIDE_BATTLE_BROKEN_RIGHT = 16,
};
int pk_wide_last_battle_ways(void);

/** The Game Boy's EXPAND (pk_wide_gb.c: Pokémon Yellow's overworld past its 160 x 144 screen). Every pk_wide_* call
 * above hands over to these while a Game Boy game is configured; the frame is then 160 x 144 and the views are in its
 * pixels. */
#define PK_WIDE_GB_W 160
#define PK_WIDE_GB_H 144
int pk_wide_gb_knows(uint32_t crc);
int pk_wide_gb_configure(uint32_t crc);
void pk_wide_gb_reset(void);
/** pk_wide_view's twin; `out` NULL = pk_wide_skip's (only the RAM after the frame is kept). */
int pk_wide_gb_view(struct mCore* core, const uint32_t* frame, uint32_t* out, struct PkWideView view, uint32_t* centre);
/** pk_wide_glow's twin for a Game Boy game: the frame over its menus' bars. */
int pk_wide_gb_glow(struct mCore* core, const uint32_t* frame, uint32_t* out, struct PkWideView view);
int pk_wide_gb_scene(void);
int pk_wide_gb_wants_close(void);
int pk_wide_gb_last_mode(void);
int pk_wide_gb_last_score(void);
/** 1 if a palette was written while the last frame was drawn (its top lines show the old colours). */
int pk_wide_gb_last_torn(void);

/** The frame pk_wide_view expects for the configured game: 240 x 160, or a Game Boy's 160 x 144. */
int pk_wide_frame_w(void);
int pk_wide_frame_h(void);

/** How the last frame went, for logs and mgba_dump: tilemap match 0..1000, -1 if none was tried. */
int pk_wide_last_score(void);
/** 1 if the last frame's sprites came from an earlier snapshot (the RAM was mid-update). */
int pk_wide_last_torn(void);
/** 1 if VRAM was written while the last frame was being drawn: its lines show two sets of tiles, which nothing taken
 * after the frame can redraw (the headless checks don't count such a frame against the rebuild). */
int pk_wide_last_vram_torn(void);
