void pk_wide_gb_reset(void);
void pk_wide_gb_snap(void);   // pk_wide_jump's: the next drawn scene at full strength
/** pk_wide_view's twin; `out` NULL = pk_wide_skip's (only the RAM after the frame is kept). */
