// --- memory -----------------------------------------------------------------------------------

static struct GBA* G;
static bool badRead;   // a pointer led outside RAM / ROM: the frame's rebuild isn't trusted

static const uint8_t* mem(uint32_t a, uint32_t n) {
    switch (a >> 24) {
    case 2:
        a &= 0x3FFFF;
        if (a + n <= 0x40000) return (const uint8_t*) G->memory.wram + a;
        break;
    case 3:
        a &= 0x7FFF;
        if (a + n <= 0x8000) return (const uint8_t*) G->memory.iwram + a;
        break;
    case 8:
    case 9:
        a -= 0x08000000;
        if ((size_t) a + n <= G->memory.romSize) return (const uint8_t*) G->memory.rom + a;
        break;
    }
    badRead = true;
    return NULL;
}

static uint32_t r8(uint32_t a) { const uint8_t* p = mem(a, 1); return p ? p[0] : 0; }
static uint32_t r16(uint32_t a) { const uint8_t* p = mem(a, 2); return p ? (uint32_t) (p[0] | p[1] << 8) : 0; }
static int32_t s16(uint32_t a) { return (int16_t) r16(a); }
static uint32_t r32(uint32_t a) {
    const uint8_t* p = mem(a, 4);
    return p ? (uint32_t) p[0] | (uint32_t) p[1] << 8 | (uint32_t) p[2] << 16 | (uint32_t) p[3] << 24 : 0;
}
static int32_t s32(uint32_t a) { return (int32_t) r32(a); }

static inline uint32_t le16(const uint8_t* p) { return (uint32_t) (p[0] | p[1] << 8); }
static inline uint32_t le32(const uint8_t* p) { return le16(p) | le16(p + 2) << 16; }

// --- snapshots ----------------------------------------------------------------------------------

struct Conn {
    int ox, oy;                    // VMap position of the connected map's (0, 0)
    int w, h;
    uint32_t data;                 // its map cells (ROM)
    int dir;                       // 1 SOUTH 2 NORTH 3 WEST 4 EAST
    uint32_t primary, secondary;   // its tilesets (often not the current map's: Fuchsia City <-> Route 18)
    uint32_t header;               // its map header (its object templates)
    int group, num;
    int degree;                    // 1: beside the current map; 2: beside one of those (Route 20 from Fuchsia City)
    uint32_t border;               // its border metatiles, and (FireRed) their block's size
    int bw, bh;
};
#define MAX_CONNS 8

/** An object on the map the game hasn't spawned - it only spawns those near its own screen - drawn where it would
 * appear from its template: a cuttable tree, a boulder, an item ball, an NPC at its home tile. */
struct Ghost {
    int x, y, w, h;      // its box, in VMap pixels
    uint32_t pixels;     // its frame's 4bpp tiles (ROM)
    bool hflip;
    int prio;            // OAM priority, from its elevation
    uint32_t palTag;
};
#define MAX_GHOSTS 256

struct Snap {
    bool ok;
    int posX, posY, xTile, yTile;
    int href, vref;                // BG1-3's scroll as the camera sets it (field_camera.c), before any line effect
    int group, num;                // the current map
    int vw, vh;
    int width, height;             // the map itself
    uint32_t border, primary, secondary;
    int split;                     // metatiles in the primary tileset (the engine's, or the hack's for this layout)
    int bw, bh;
    struct Conn conn[MAX_CONNS];
    int nconn;
    uint16_t vmap[MAX_MAP_DATA];
    uint8_t sprites[64 * 0x44];
    uint8_t order[64];
    uint8_t objects[16 * 0x24];
    int coordX, coordY;
    struct Ghost ghosts[MAX_GHOSTS];   // the map's objects the game hasn't spawned (far off), front first
    int nghosts;
};

static struct Snap snaps[2];
