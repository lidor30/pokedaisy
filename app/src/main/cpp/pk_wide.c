/** FlagGet as the game has it. Flags past SaveBlock1's own array read on into it (the engine doesn't stop there, so
 * a hack that uses them - Odyssey, Glazed - keeps them there); CFRU's GetFlagPointer (PK_WIDE_EXPANDED_FLAGS) puts
 * 0x900-0x18FF in a bank of its own and 0x1900-0x3FFF on one shared byte (FireRed's gSpecialVar_0x8000). The special
 * flags (0x4000 on) aren't the save's: such an object counts as hidden rather than drawn on a guess. */
static bool flagSet(uint32_t sb1, int flag) {
    if (flag >= 0x4000) return true;
    uint32_t at = sb1 + (uint32_t) C[PK_WIDE_SB1_FLAGS] + (uint32_t) (flag >> 3);
    if (C[PK_WIDE_EXPANDED_FLAGS] && flag >= 0x900)
        at = flag < 0x1900 ? (uint32_t) C[PK_WIDE_EXPANDED_FLAGS] + (uint32_t) ((flag - 0x900) >> 3) : 0x020370B8;
    return (r8(at) >> (flag & 7)) & 1;
}

/** A var's value (0x4000 on, the ones SaveBlock1 keeps); 0 for any other. */
static int varGet(uint32_t sb1, int var) {
    return var >= 0x4000 && var < 0x4100 ? (int) r16(sb1 + (uint32_t) C[PK_WIDE_SB1_VARS] + 2 * (uint32_t) (var - 0x4000)) : 0;
}

/** An object's ObjectEventGraphicsInfo, as GetObjectEventGraphicsInfo finds it: an id past the table's own (240 on)
 * from VAR_OBJ_GFX_ID_*. CFRU's ids are 16-bit, a table and an entry: table 0xFF's from a var, tables past the last
 * from table 0, an empty entry is table 0's 16th. 0 = none. */
static uint32_t ghostInfo(uint32_t sb1, int gfx) {
    uint32_t base = (uint32_t) C[PK_WIDE_OBJ_GFX_INFO], tables = (uint32_t) C[PK_WIDE_OBJ_GFX_TABLES];
    int from = C[PK_WIDE_OBJ_GFX_VAR_FROM] ? C[PK_WIDE_OBJ_GFX_VAR_FROM] : 240;
    for (int hop = 0; hop < 2; hop++) {   // a var's id is looked up once more (never a var again)
        int table = gfx >> 8 & 0xFF, entry = gfx & 0xFF;
        if (tables && table == 0xFF) {
            if (hop || !C[PK_WIDE_OBJ_GFX_FF_VAR] || entry > 0xF) return 0;
            gfx = varGet(sb1, C[PK_WIDE_OBJ_GFX_FF_VAR] + entry);
            continue;
        }
        int id = tables ? entry : gfx;   // CFRU: table 0's entry; else the whole id
        if (table == 0 || !tables) {
            bool isVar = id >= from && id < from + 16;
            int count = C[PK_WIDE_OBJ_GFX_COUNT] ? C[PK_WIDE_OBJ_GFX_COUNT] : from + 16;
            if (!isVar && id >= count) return 0;   // past the table (expansion's overworld Pokémon: their own graphics)
            if (isVar) {
                if (hop) return 0;
                gfx = varGet(sb1, 0x4010 + id - from);   // VAR_OBJ_GFX_ID_*
                continue;
            }
        }
        if (!tables) return r32(base + 4 * (uint32_t) id);
        uint32_t list = table && table <= C[PK_WIDE_OBJ_GFX_TABLE_MAX] ? r32(tables + 4 * (uint32_t) table) : 0;
        if (!list) list = base;
        uint32_t info = r32(list + 4 * (uint32_t) entry);
        return info ? info : r32(base + 0x40);
    }
    return 0;
}

/** Where an object was last seen live: the game removes one once both its tile and its home are ~2 tiles past its own
 * view, and spawns it again at its home (the template) once that comes back into view. Zoomed out, that's on screen:
 * drawn from its template, a wandering NPC jumped home the moment it was removed. So it's drawn where it was, facing
 * the way it faced, until the game spawns it again. In its own map's coordinates; forgotten once its map is neither
 * the current one nor beside it (a warp: the game puts everyone home), and on a reset (a state load). */
struct Seen {
    int group, num, localId;
    int x, y, dir;
    bool used;
};
#define MAX_SEEN 64
static struct Seen seenObjects[MAX_SEEN];

static const struct Seen* seenFind(int group, int num, int localId) {
    for (int i = 0; i < MAX_SEEN; i++)
        if (seenObjects[i].used && seenObjects[i].group == group && seenObjects[i].num == num && seenObjects[i].localId == localId)
            return &seenObjects[i];
    return NULL;
}

/** Each live object's tile and facing, in its map's coordinates (the current map, or one beside it whose VMap position
 * is known); entries for maps no longer around are dropped. */
static void rememberObjects(const struct Snap* s) {
    for (int i = 0; i < MAX_SEEN; i++) {
        struct Seen* e = &seenObjects[i];
        if (!e->used || (e->group == s->group && e->num == s->num)) continue;
        bool near = false;
        for (int c = 0; c < s->nconn && !near; c++) near = s->conn[c].group == e->group && s->conn[c].num == e->num;
        if (!near) e->used = false;
    }
    for (int k = 0; k < 16; k++) {
        const uint8_t* oe = s->objects + 0x24 * k;
        int localId = oe[8], num = oe[9], group = oe[10];
        if (!(oe[0] & 1) || localId == 0xFF) continue;   // not active, or the player
        int ox, oy;
        if (group == s->group && num == s->num) {
            ox = MAP_OFFSET;
            oy = MAP_OFFSET;
        } else {
            int c = 0;
            while (c < s->nconn && !(s->conn[c].group == group && s->conn[c].num == num)) c++;
            if (c == s->nconn) continue;
            ox = s->conn[c].ox;
            oy = s->conn[c].oy;
        }
        struct Seen* e = (struct Seen*) seenFind(group, num, localId);
        for (int i = 0; i < MAX_SEEN && !e; i++)
            if (!seenObjects[i].used) e = &seenObjects[i];
        if (!e) continue;
        e->group = group;
        e->num = num;
        e->localId = localId;
        e->x = (int16_t) (oe[0x10] | oe[0x11] << 8) - ox;   // currentCoords
        e->y = (int16_t) (oe[0x12] | oe[0x13] << 8) - oy;
        e->dir = oe[0x18] & 0xF;                         // facingDirection
        e->used = true;
    }
}

/** One object template (at `t`, its x / y relative to a map whose (0, 0) is VMap cell (ox, oy)) as a ghost, unless
 * it's hidden by its flag: its sprite where SpawnObjectEvent would put it - the frame of the movement type's first
 * facing, the bottom of the box on the tile's bottom, centred on it. */
static void addGhost(struct Snap* s, uint32_t sb1, uint32_t t, int ox, int oy, int mw, int mh, const struct Seen* seen) {
    if (s->nghosts >= MAX_GHOSTS) return;
    int flag = (int) r16(t + 0x14);
    if (flag && flagSet(sb1, flag)) return;   // hidden (picked up, beaten, moved on)
    // graphicsId: a u8 at +1 (CFRU: its table at +3); a u16 at +1 with the kind at +3 (expansion), at +2 with the kind
    // at +1 (Rogue).
    int kind = C[PK_WIDE_TEMPLATE_KIND];
    int gfx = kind == 1 ? (int) r16(t + 2) : (int) (r8(t + 1) | (kind == 3 ? r8(t + 2) << 8 : C[PK_WIDE_OBJ_GFX_TABLES] ? r8(t + 3) << 8 : 0));
    uint32_t info = ghostInfo(sb1, gfx);
    int w = s16(info + 8), h = s16(info + 0xA);
    if (!info || w <= 0 || h <= 0 || w > 64 || h > 64 || (w & 7) || (h & 7)) return;
    bool inanimate = r8(info + 0xC) & 0x40;
    uint32_t images = r32(info + 0x1C);
    int dir = seen ? seen->dir : C[PK_WIDE_OBJ_FACING] ? (int) r8((uint32_t) C[PK_WIDE_OBJ_FACING] + r8(t + 9)) : 1;   // 1 S 2 N 3 W 4 E
    if (dir < 1 || dir > 4) dir = 1;
    int frame = inanimate ? 0 : dir == 2 ? 1 : dir == 3 || dir == 4 ? 2 : 0;   // the walking sheet's standing frames
    uint32_t bytes = (uint32_t) (w * h / 2);
    uint32_t img = r32(images + 8 * (uint32_t) frame);
    bool hflip = frame == 2 && dir == 4;
    if (r16(images + 8 * (uint32_t) frame + 4) != bytes || !mem(img, bytes)) {
        img = r32(images);   // a sheet without that frame: its first
        hflip = false;
        if (r16(images + 4) != bytes || !mem(img, bytes)) return;
    }
    // Only inside its own map (mw x mh): objects parked off it are a script's (Too Many Types 2's moving trucks at y -1).
    int x = seen ? seen->x : s16(t + 4), y = seen ? seen->y : s16(t + 6);
    if (x < 0 || y < 0 || x >= mw || y >= mh) return;
    struct Ghost* g = &s->ghosts[s->nghosts++];
    int cellX = x + ox, cellY = y + oy;
    g->x = cellX * 16 + 8 - w / 2;
    g->y = cellY * 16 + 16 - h;
    g->w = w;
    g->h = h;
    g->pixels = img;
    g->hflip = hflip;
    g->prio = C[PK_WIDE_ELEVATION_PRIO] ? (int) (r8((uint32_t) C[PK_WIDE_ELEVATION_PRIO] + (r8(t + 8) & 15)) & 3) : 2;
    g->palTag = r16(info + 2);
}

/** The objects the game hasn't spawned: the current map's templates (SaveBlock1 keeps them, positions as the game
 * last saved them) that aren't spawned, then each connected map's from its header (the game never spawns those; the
 * ones it shows across the border are the current map's clones of them, spawned like any other). */
static void takeGhosts(struct Snap* s, uint32_t sb1, uint32_t hdr) {
    s->nghosts = 0;
    if (!C[PK_WIDE_OBJ_GFX_INFO] || !C[PK_WIDE_SB1_TEMPLATES] || !sb1) return;
    uint32_t events = r32(hdr + 4);
    int count = events ? (int) r8(events) : 0;
    if (count > 64) count = 64;
    int mapGroup = s->group, mapNum = s->num;
    uint32_t base = sb1 + (uint32_t) C[PK_WIDE_SB1_TEMPLATES];
    rememberObjects(s);
    for (int i = 0; i < count; i++) {
        uint32_t t = base + 0x18 * (uint32_t) i;
        int localId = (int) r8(t);
        if (r8(t + (uint32_t) C[PK_WIDE_TEMPLATE_KIND]) != 0) continue;   // a clone of a connected map's object: spawned when near, else that map's own
        bool live = false;
        for (int k = 0; k < 16 && !live; k++) {
            const uint8_t* oe = s->objects + 0x24 * k;
            live = (oe[0] & 1) && oe[8] == localId && oe[9] == mapNum && oe[10] == mapGroup;
        }
        if (!live) addGhost(s, sb1, t, MAP_OFFSET, MAP_OFFSET, s->width, s->height, seenFind(mapGroup, mapNum, localId));
    }
    for (int c = 0; c < s->nconn; c++) {
        const struct Conn* k = &s->conn[c];
        uint32_t ev = r32(k->header + 4), arr = ev ? r32(ev + 4) : 0;
        int n = ev ? (int) r8(ev) : 0;
        if (n > 64) n = 64;
        for (int i = 0; i < n; i++) {
            uint32_t t = arr + 0x18 * (uint32_t) i;
            if (r8(t + (uint32_t) C[PK_WIDE_TEMPLATE_KIND]) != 0) continue;
            int localId = (int) r8(t);
            bool cloned = false;   // the current map has a clone of it (shown, or a ghost of its own)
            for (int m = 0; m < count && !cloned; m++) {
                uint32_t ct = base + 0x18 * (uint32_t) m;
                cloned = r8(ct + (uint32_t) C[PK_WIDE_TEMPLATE_KIND]) == 1 && (int) r8(ct + 8) == localId && (int) r16(ct + 0xC) == k->num && (int) r16(ct + 0xE) == k->group;
            }
            // Still live from when that map was the current one (you just crossed over): the game draws it.
            for (int m = 0; m < 16 && !cloned; m++) {
                const uint8_t* oe = s->objects + 0x24 * m;
                cloned = (oe[0] & 1) && oe[8] == localId && oe[9] == k->num && oe[10] == k->group;
            }
            if (!cloned) addGhost(s, sb1, t, k->ox, k->oy, k->w, k->h, seenFind(k->group, k->num, localId));
        }
    }
    // Front first, as the sprites' order has it: the lower on the map, the nearer.
    for (int i = 1; i < s->nghosts; i++)
        for (int j = i; j > 0 && s->ghosts[j].y + s->ghosts[j].h > s->ghosts[j - 1].y + s->ghosts[j - 1].h; j--) {
            struct Ghost tmp = s->ghosts[j];
            s->ghosts[j] = s->ghosts[j - 1];
            s->ghosts[j - 1] = tmp;
        }
}

/** A map's connections (its header `hdr`, w x h, its (0, 0) at VMap cell (mx, my)) added to s->conn - as fieldmap.c's
 * Fill*Connection places them: SOUTH (offset, h), NORTH (offset, -cHeight), WEST (-cWidth, offset), EAST (w, offset). */
static void readConnections(struct Snap* s, uint32_t hdr, int w, int h, int mx, int my, int degree) {
    uint32_t conns = r32(hdr + 0xC);
    int count = conns ? s32(conns) : 0;
    uint32_t arr = conns ? r32(conns + 4) : 0;
    for (int i = 0; i < count && i < 8 && s->nconn < MAX_CONNS; i++) {
        uint32_t c = arr + 12 * (uint32_t) i;   // struct MapConnection { u8 direction; s32 offset; u8 mapGroup, mapNum; }
        int dir = (int) r8(c), off = s32(c + 4);
        if (dir < 1 || dir > 4) continue;       // DIVE / EMERGE aren't beside the map
        if (off < -MAX_MAP_DATA || off > MAX_MAP_DATA) continue;
        int group = (int) r8(c + 8), num = (int) r8(c + 9);
        if (degree > 1) {   // not the current map again, nor one already here
            bool known = group == s->group && num == s->num;
            for (int k = 0; k < s->nconn && !known; k++) known = s->conn[k].group == group && s->conn[k].num == num;
            if (known) continue;
        }
        uint32_t groupArr = r32((uint32_t) C[PK_WIDE_MAP_GROUPS] + 4 * (uint32_t) group) ^ (uint32_t) C[PK_WIDE_MAP_GROUPS_XOR];
        uint32_t chdr = r32(groupArr + 4 * (uint32_t) num);
        uint32_t clay = r32(chdr);
        struct Conn* k = &s->conn[s->nconn];
        k->w = s32(clay);
        k->h = s32(clay + 4);
        if (k->w <= 0 || k->h <= 0 || k->w > 0x400 || k->h > 0x400) continue;
        k->data = r32(clay + 0xC);
        k->primary = r32(clay + 0x10);
        k->secondary = r32(clay + 0x14);
        k->border = r32(clay + 8);
        k->bw = C[PK_WIDE_BORDER_SIZED] ? (int) r8(clay + 0x18) : 2;
        k->bh = C[PK_WIDE_BORDER_SIZED] ? (int) r8(clay + 0x19) : 2;
        if (k->bw <= 0 || k->bh <= 0) k->border = 0;
        k->header = chdr;
        k->group = group;
        k->num = num;
        k->dir = dir;
        k->degree = degree;
        switch (dir) {
        case 1: k->ox = mx + off; k->oy = my + h; break;
        case 2: k->ox = mx + off; k->oy = my - k->h; break;
        case 3: k->ox = mx - k->w; k->oy = my + off; break;
        default: k->ox = mx + w; k->oy = my + off; break;
        }
        if (k->w * k->h <= 0x10000 && mem(k->data, (uint32_t) (k->w * k->h * 2))) s->nconn++;
    }
}

static void take(struct Snap* s) {
    badRead = false;
    s->ok = false;
    uint32_t sb1 = C[PK_WIDE_SAVE_STATIC] ? (uint32_t) C[PK_WIDE_SAVE_BLOCK1_PTR] : r32((uint32_t) C[PK_WIDE_SAVE_BLOCK1_PTR]);
    uint32_t pos = sb1 + (uint32_t) C[PK_WIDE_SB1_POS];
    s->posX = s16(pos);
    s->posY = s16(pos + 2);
    s->group = (int) r8(pos + 4);
    s->num = (int) r8(pos + 5);
    uint32_t co = (uint32_t) C[PK_WIDE_CAMERA_OFFSET];
    s->xTile = (int) r8(co + 2);
    s->yTile = (int) r8(co + 3);
    // FieldUpdateBgTilemapScroll: HOFS = xPixelOffset + sHorizontalCameraPan, VOFS = yPixelOffset +
    // sVerticalCameraPan + 8 (the pans follow the offset struct).
    uint32_t pan = (uint32_t) ((int32_t) co + C[PK_WIDE_PAN_OFF]);
    s->href = ((int) r8(co) + s16(pan)) & 0x1FF;
    s->vref = ((int) r8(co + 1) + s16(pan + 2) + 8) & 0x1FF;
    uint32_t vm = (uint32_t) C[PK_WIDE_VMAP];
    s->vw = s32(vm);
    s->vh = s32(vm + 4);
    if (s->vw <= 0 || s->vh <= 0 || s->vw > MAX_MAP_DATA || s->vh > MAX_MAP_DATA || s->vw * s->vh > MAX_MAP_DATA) return;
    const uint8_t* cells = mem(r32(vm + 8), (uint32_t) (s->vw * s->vh * 2));
    if (!cells) return;
    memcpy(s->vmap, cells, (size_t) (s->vw * s->vh * 2));

    uint32_t hdr = (uint32_t) C[PK_WIDE_MAP_HEADER];
    uint32_t layout = r32(hdr);
    s->width = s32(layout);
    s->height = s32(layout + 4);
    s->border = r32(layout + 8);
    s->primary = r32(layout + 0x10);
    s->secondary = r32(layout + 0x14);
    bool emeraldLayout = C[PK_WIDE_LAYOUT_VERSIONED] && r8(layout + 0x18) == 0;
    s->split = C[PK_WIDE_PRIMARY_OVERRIDE] && !emeraldLayout ? C[PK_WIDE_PRIMARY_OVERRIDE] : C[PK_WIDE_PRIMARY_METATILES];
    // Sizes from memory are only trusted within reason: nothing below multiplies a garbage one.
    if (s->width <= 0 || s->height <= 0 || s->width > MAX_MAP_DATA || s->height > MAX_MAP_DATA) return;
    if (C[PK_WIDE_BORDER_SIZED]) {
        s->bw = (int) r8(layout + 0x18);
        s->bh = (int) r8(layout + 0x19);
        if (s->bw <= 0 || s->bh <= 0) return;
    }
    // Where fieldmap.c's Fill*Connection puts a connected map's cell (cx, cy) in VMap:
    // SOUTH (offset + 7 + cx, height + 7 + cy), NORTH (offset + 7 + cx, 7 - cHeight + cy),
    // WEST (7 - cWidth + cx, offset + 7 + cy), EAST (width + 7 + cx, offset + 7 + cy).
    s->nconn = 0;
    readConnections(s, hdr, s->width, s->height, MAP_OFFSET, MAP_OFFSET, 1);
    // One step further (zoomed out, the sea past Route 19 is Route 20's): their own neighbours, the current map aside.
    for (int i = 0, n = s->nconn; i < n; i++)
        readConnections(s, s->conn[i].header, s->conn[i].w, s->conn[i].h, s->conn[i].ox, s->conn[i].oy, 2);

    const uint8_t* p;
    if ((p = mem((uint32_t) C[PK_WIDE_SPRITES], sizeof(s->sprites)))) memcpy(s->sprites, p, sizeof(s->sprites));
    if ((p = mem((uint32_t) C[PK_WIDE_SPRITE_ORDER], sizeof(s->order)))) memcpy(s->order, p, sizeof(s->order));
    if ((p = mem((uint32_t) C[PK_WIDE_OBJECT_EVENTS], sizeof(s->objects)))) memcpy(s->objects, p, sizeof(s->objects));
    s->coordX = s16((uint32_t) C[PK_WIDE_COORD_OFFSET]);
    s->coordY = s16((uint32_t) C[PK_WIDE_COORD_OFFSET_Y]);
    bool ok = !badRead;
    takeGhosts(s, sb1, hdr);
    s->ok = ok;   // the ghosts are extras: a bad read among them doesn't sink the map
}

// --- the map, as DrawMetatile draws it ------------------------------------------------------------

// Metatile id -> each BG's 2x2 tile entries (BG1 top, over sprites; BG2 middle; BG3 bottom), for one tileset pair
// at a time - the current map's (it only changes with the map), and one per connected map with tilesets of its own.
struct Tilesets {
    uint32_t primary, secondary;
    uint16_t mt[NUM_METATILES_TOTAL + 1][3][4];
    uint8_t done[NUM_METATILES_TOTAL + 1];
};
static struct Tilesets cur;
static uint32_t mtPrimary, mtSecondary;   // what `cur` holds
static int split = 512;                   // metatiles in the primary tileset of what's being drawn (metatile() sets it)

static const uint16_t* metatileIn(struct Tilesets* t, int mid, int bg) {
    uint16_t (*mtTiles)[3][4] = t->mt;
    uint8_t* mtDone = t->done;
    if (mid > NUM_METATILES_TOTAL) mid = 0;     // DrawMetatileAt's own clamp
    if (!mtDone[mid]) {
        uint32_t ts = mid < split ? t->primary : t->secondary;
        int i = mid < split ? mid : mid - split;
        uint32_t attrs = r32(ts + (uint32_t) C[PK_WIDE_ATTR_OFFSET]);
        uint32_t attr = C[PK_WIDE_ATTR_SIZE] == 4 ? r32(attrs + 4 * (uint32_t) i) : r16(attrs + 2 * (uint32_t) i);
        int layer = (int) ((attr >> C[PK_WIDE_LAYER_SHIFT]) & (uint32_t) C[PK_WIDE_LAYER_MASK]);
        uint32_t tiles = r32(ts + 0xC) + (uint32_t) C[PK_WIDE_METATILE_SIZE] * (uint32_t) i;
        if (C[PK_WIDE_METATILE_SIZE] == 24) {   // triple-layer: every metatile has all three BGs' tiles
            for (int k = 0; k < 4; k++)
                for (int b = 0; b < 3; b++) mtTiles[mid][b][k] = (uint16_t) r16(tiles + 2 * (uint32_t) (4 * (2 - b) + k));
            mtDone[mid] = 1;
            return mtTiles[mid][bg - 1];
        }
        uint16_t lo[4], hi[4];
        for (int k = 0; k < 4; k++) {
            lo[k] = (uint16_t) r16(tiles + 2 * (uint32_t) k);
            hi[k] = (uint16_t) r16(tiles + 8 + 2 * (uint32_t) k);
        }
        for (int k = 0; k < 4; k++) {
            if (layer == LAYER_SPLIT) {
                mtTiles[mid][0][k] = hi[k]; mtTiles[mid][1][k] = 0; mtTiles[mid][2][k] = lo[k];
            } else if (layer == LAYER_COVERED) {
                mtTiles[mid][0][k] = 0; mtTiles[mid][1][k] = hi[k]; mtTiles[mid][2][k] = lo[k];
            } else {   // NORMAL; BG3 gets the game's own "garbage" entry
                mtTiles[mid][0][k] = hi[k]; mtTiles[mid][1][k] = lo[k]; mtTiles[mid][2][k] = (uint16_t) C[PK_WIDE_NORMAL_BG3];
            }
        }
        mtDone[mid] = 1;
    }
    return mtTiles[mid][bg - 1];
}

static void syncSplit(const struct Snap* s);

static const uint16_t* metatile(const struct Snap* s, int mid, int bg) {
    syncSplit(s);
    if (s->primary != mtPrimary || s->secondary != mtSecondary) {
        memset(cur.done, 0, sizeof(cur.done));
        cur.primary = mtPrimary = s->primary;
        cur.secondary = mtSecondary = s->secondary;
    }
    return metatileIn(&cur, mid, bg);
}

// --- a connected map's own tilesets ------------------------------------------------------------------
//
// The game copies 7 metatiles of each connected map into VMap and draws them with the current map's tilesets (its
// maps are made so that strip looks right). Past that strip WIDE draws the connected map itself, which may have
// tilesets of its own (Route 18 is Celadon's, Fuchsia City its own): its metatiles, its tiles - not in VRAM, so
// decompressed from the ROM - and its palettes from the ROM. Whatever it shares with the current map (usually the
// primary tileset) still comes from VRAM / palette RAM, fades and tints with it.

#define LZ77_MAX 0x8000

struct Foreign {
    struct Tilesets t;
    bool ownPrimary;                 // its primary differs from the current map's too
    uint8_t tiles[1024 * 32];        // 4bpp tiles by tile number (its own ones only)
    uint16_t pal[16 * 16];
    uint32_t used;                   // last frame used (the least recent is replaced)
};
#define FOREIGN_SLOTS 4
static struct Foreign foreign[FOREIGN_SLOTS];

/** Draws with the snapshot's primary split from now on (the caches were filled for the other one: emptied). */
static void syncSplit(const struct Snap* s) {
    if (s->split == split) return;
    split = s->split;
    mtPrimary = mtSecondary = 0;
    for (int i = 0; i < FOREIGN_SLOTS; i++) foreign[i].t.primary = foreign[i].t.secondary = 0;
}

static uint32_t foreignFrame;   // drawRegion calls so far: a slot used in this one is never replaced (no reloading per frame)

/** GBA BIOS LZ77 (type 0x10) at `src` into dst (at most `cap` bytes); bytes written, 0 if it isn't one. */
static uint32_t lz77(uint32_t src, uint8_t* dst, uint32_t cap) {
    uint32_t hdr = r32(src);
    if ((hdr & 0xFF) != 0x10) return 0;
    uint32_t size = hdr >> 8, n = 0, at = src + 4;
    if (size > cap) size = cap;
    while (n < size) {
        uint32_t flags = r8(at++);
        for (int b = 0; b < 8 && n < size; b++, flags <<= 1) {
            if (!(flags & 0x80)) {
                dst[n++] = (uint8_t) r8(at++);
                continue;
            }
            uint32_t b0 = r8(at), b1 = r8(at + 1);
            at += 2;
            uint32_t disp = ((b0 & 0xF) << 8 | b1) + 1, len = (b0 >> 4) + 3;
            if (disp > n) return n;   // corrupt: stop with what's there
            for (uint32_t k = 0; k < len && n < size; k++, n++) dst[n] = dst[n - disp];
        }
        if (badRead) return n;
    }
    return n;
}

/** A tileset's tiles into tiles[first * 32 ...]: decompressed if it says so, else as many as fit. */
static void loadTiles(uint32_t ts, uint8_t* tiles, int first) {
    static uint8_t buf[LZ77_MAX];
    uint32_t room = (uint32_t) (1024 - first) * 32;
    uint32_t src = r32(ts + 4);
    if (r8(ts)) {
        uint32_t n = lz77(src, buf, LZ77_MAX);
        memcpy(tiles + first * 32, buf, n < room ? n : room);
    } else {
        for (uint32_t k = 0; k < room; k++) tiles[first * 32 + k] = (uint8_t) r8(src + k);
    }
}

/** The connected map's tilesets: NULL when they're the current map's (VRAM has them), else a cached Foreign. */
static struct Foreign* foreignFor(const struct Snap* s, const struct Conn* k) {
    if (k->secondary == s->secondary && k->primary == s->primary) return NULL;
    if (C[PK_WIDE_PRIMARY_OVERRIDE] || C[PK_WIDE_METATILE_SIZE] != 16) return NULL;   // hacks' own layouts: as the game
    struct Foreign* f = NULL;
    for (int i = 0; i < FOREIGN_SLOTS; i++)
        if (foreign[i].t.primary == k->primary && foreign[i].t.secondary == k->secondary && foreign[i].ownPrimary == (k->primary != s->primary)) f = &foreign[i];
    if (!f) {
        for (int i = 0; i < FOREIGN_SLOTS; i++)
            if (!f || foreign[i].used < f->used) f = &foreign[i];
        if (f->used == foreignFrame && f->t.primary) return NULL;   // every slot busy this frame: as the game would
        memset(f->t.done, 0, sizeof(f->t.done));
        memset(f->t.done, 0, sizeof(f->t.done));
        f->t.primary = k->primary;
        f->t.secondary = k->secondary;
        f->ownPrimary = k->primary != s->primary;
        memset(f->tiles, 0, sizeof(f->tiles));
        int nt = C[PK_WIDE_PRIMARY_METATILES], np = C[PK_WIDE_PRIMARY_PALS];   // tiles / palettes in a primary tileset
        if (f->ownPrimary) loadTiles(k->primary, f->tiles, 0);
        loadTiles(k->secondary, f->tiles, nt);
        for (int p = 0; p < 16; p++) {
            uint32_t from = p < np ? k->primary : k->secondary;
            uint32_t pals = r32(from + 8);
            for (int i = 0; i < 16; i++) f->pal[p * 16 + i] = (uint16_t) r16(pals + 32 * (uint32_t) p + 2 * (uint32_t) i);
        }
    }
    f->used = foreignFrame;
    return f;
}

// MapGridGetMetatileIdAt in VMap coordinates. On the real screen exactly as the game: VMap (with its copies of the
// connected maps), the border past it. Off it (`real` false), what's really there: VMap's connection strips belong to
// their maps (*conn: their own tilesets), past VMap the connected maps and theirs, and where no map is, the border of
// the neighbour on that side - so the scenery doesn't change as you cross from one map to the next.
static int borderAt(const struct Snap* s, uint32_t border, int bw, int bh, int x, int y, int ox, int oy) {
    uint32_t mask = (uint32_t) C[PK_WIDE_METATILE_MASK];
    if (!C[PK_WIDE_BORDER_SIZED]) return (int) (r16(border + 2 * (uint32_t) (((x - ox + MAP_OFFSET + 1) & 1) + (((y - oy + MAP_OFFSET + 1) & 1) << 1))) & mask);
    int xp = ((x - ox) % bw + bw) % bw, yp = ((y - oy) % bh + bh) % bh;
    return (int) (r16(border + 2 * (uint32_t) (xp + yp * bw)) & mask);
}

static int blockIn(const struct Snap* s, int x, int y, int* conn, bool real) {
    uint32_t mask = (uint32_t) C[PK_WIDE_METATILE_MASK], b = mask;
    *conn = -1;
    int lx = x - MAP_OFFSET, ly = y - MAP_OFFSET;
    bool outside = lx < 0 || ly < 0 || lx >= s->width || ly >= s->height;
    bool inVmap = x >= 0 && x < s->vw && y >= 0 && y < s->vh;
    if (inVmap) b = s->vmap[x + s->vw * y];
    if (outside && (!inVmap || !real)) {
        // A connected map's cell: beside the current map, then one step further.
        for (int i = 0; i < s->nconn; i++) {
            const struct Conn* k = &s->conn[i];
            bool side = k->degree > 1 || (k->dir == 1 ? ly >= s->height : k->dir == 2 ? ly < 0 : k->dir == 3 ? lx < 0 : lx >= s->width);
            int cx = x - k->ox, cy = y - k->oy;
            if (side && cx >= 0 && cx < k->w && cy >= 0 && cy < k->h) {
                uint32_t v = r16(k->data + 2 * (uint32_t) (cx + k->w * cy));
                if (v != mask) {
                    b = v;
                    *conn = i;
                }
                break;
            }
        }
        if (*conn < 0 && !real) {
            // No map here: the border of the neighbour on this side (south / north first, as the rows run), where
            // the point lies within that neighbour's span - past its end the current map's border goes on, as it
            // does in the game's own stitched strip (Celadon City's trees above Route 16, not Route 16's sea).
            int want = ly >= s->height ? 1 : ly < 0 ? 2 : lx < 0 ? 3 : 4;
            for (int i = 0; i < s->nconn; i++) {
                const struct Conn* k = &s->conn[i];
                if (k->degree != 1 || k->dir != want || !k->border) continue;
                int along = want <= 2 ? x - k->ox : y - k->oy, span = want <= 2 ? k->w : k->h;
                if (along < 0 || along >= span) continue;
                *conn = i;
                return borderAt(s, k->border, k->bw, k->bh, x, y, k->ox, k->oy);
            }
        }
    }
    // MAPGRID_UNDEFINED is the whole cell, collision and elevation bits clear: the game compares the u16 as it is, so a
    // map's own metatile 0x3FF (Unbound's treetop corners, 0x33FF) is drawn, not the border (its water, past the edges).
    if (b != mask) return (int) (b & mask);
    *conn = -1;
    return borderAt(s, s->border, s->bw, s->bh, x, y, MAP_OFFSET, MAP_OFFSET);
}

static int block(const struct Snap* s, int x, int y) {
    int conn;
    return blockIn(s, x, y, &conn, true);
}

