/** a * (256 - t) + b * t, per channel, keeping a's alpha. */
static inline uint32_t lerp(uint32_t a, uint32_t b, int t) {
    if (t <= 0) return a;
    if (t >= 256) return b;
    uint32_t rb = (((a & 0xFF00FF) * (uint32_t) (256 - t) + (b & 0xFF00FF) * (uint32_t) t) >> 8) & 0xFF00FF;
    uint32_t g = (((a & 0x00FF00) * (uint32_t) (256 - t) + (b & 0x00FF00) * (uint32_t) t) >> 8) & 0x00FF00;
    return (a & 0xFF000000) | rb | g;
}

/** BG0 - the field's text boxes, menus, signs - shows something: enough of its visible tilemap isn't tile 0. The
 * map-name popup (the top-left corner, every game) doesn't count: leaving a building, the game locks the controls
 * for the walk out of the door while the popup is up, and the camera pulled in and back out for it. */
static bool textUp(void) {
    if (!(io(0) & 0x100)) return false;
    const uint8_t* vram = (const uint8_t*) G->video.vram;
    uint32_t scr = ((io(0x08) >> 8) & 31) * 0x800u;
    int hofs = io(0x10) & 0x1FF, vofs = io(0x12) & 0x1FF, n = 0;
    for (int ty = 0; ty < 20; ty++)
        for (int tx = 0; tx < 30; tx++) {
            if (ty < POPUP_ROWS && tx < POPUP_COLS) continue;
            int rx = ((hofs >> 3) + tx) & 31, ry = ((vofs >> 3) + ty) & 31;
            if (le16(vram + scr + 2 * (uint32_t) (ry * 32 + rx)) & 0x3FF) n++;
        }
    return n >= 8;
}

/** BG0 is what the frame shows at screen pixel (x, y): it's opaque there and the frame has its colour (BG0 can sit
 * opaque under the map: Unbound's START menu leaves tiles beside its middle windows). Line y's registers. */
static bool barEdge(int x, int y) {
    int pal, ci = (windowLayers(x, y) & 1) ? bgPixel(0, x, y, &pal) : 0;
    if (!ci) return false;
    uint16_t c = P[pal + ci];
    uint32_t v = (uint32_t) (c & 0x1F) << 3 | (uint32_t) ((c >> 5) & 0x1F) << 11 | (uint32_t) ((c >> 10) & 0x1F) << 19;
    v |= (v >> 5) & 0x070707;   // mColorFrom555, untinted: DAY AND NIGHT leaves the text windows' palettes alone
    uint32_t f = realFrame[y * PK_WIDE_W + x] & 0xFFFFFF;
    return f == v || f == (color(c, 0) & 0xFFFFFF);
}

/** BG0 is opaque all the way across line y (a bar, not two windows that each touch an edge: Unbound's POKéDEX label
 * and clock reach the screen's edges with the field between them). Sprites over it (the bar's icons) don't matter. */
static bool bg0Across(int y) {
    for (int x = 1; x < PK_WIDE_W - 1; x++) {
        int pal;
        if (!(windowLayers(x, y) & 1) || !bgPixel(0, x, y, &pal)) return false;
    }
    return true;
}

/** The rows a full-width bar on BG0 crosses: BG0 shows at both of the screen's edges (Unbound's START menu, its quest
 * bar over the field and its icons under it). Past the edges they're holes - the row's own edge pixel goes on, as a
 * battle's text box band does - instead of the map going on beside the bar. Line by line, as the PPU drew them. */
static void markBarRows(int x0, int y0, int w, int h) {
    for (int j = 0; j < h; j++) {
        int y = y0 + j;
        if (y < 0 || y >= PK_WIDE_H) continue;
        useLine(y);
        if (!(io(0) & 0x100) || !barEdge(0, y) || !barEdge(PK_WIDE_W - 1, y) || !bg0Across(y)) continue;
        for (int x = 0; x < w; x++)
            if (!onFrame(x0 + x, y)) holeBuf[j][x] = 1;
    }
    useLive();
}

/** A screen effect is up: lines drawn with their own scroll or windows (a transition's slices, wedges, bands). */
static bool effectsUp(void) {
    const uint16_t* a = lineRegs(0);
    for (int y = 1; y < PK_WIDE_H; y++) {
        const uint16_t* l = lineRegs(y);
        for (int r = 0x14; r <= 0x46; r += 2)
            if ((r <= 0x16 || r >= 0x40) && l[r >> 1] != a[r >> 1]) return true;
    }
    return false;
}

// --- transitions -------------------------------------------------------------------------------------
//
// pk_wide_scene() says what the game is doing a frame early, so ZOOM's pull-in to 1x is one motion started before
// anything shows, not a reaction to what's already on screen:
//   BATTLE_START  battle_transition.c's sTransitionData (PK_WIDE_TRANSITION_PTR) is set: the flashes are starting,
//                 the wipe follows ~50 frames later
//   TEXT          the field with its controls locked and a text box or a line effect up (a sign, a script)
//   OVERLAY       a picture on BG0 over most of the field (FireRed's map preview on entering a forest or a cave;
//                 FireRed-engine games only, never during a battle transition):
//                 the map around it - the frame's own and the margins' - is dimmed while it's up (overlayDim),
//                 so the picture reads as a card over the world instead of a box with the map going on around it
//   OFF           not the map at all: a battle, a menu screen, the title

#define OVERLAY_TILES 300         // BG0 tiles (of 600) a picture over the field covers (a text box ~160 at most)
#define OVERLAY_ROWS 11           // ... in at least this many full-width tile rows (28+ of 30) one after another: a
                                  // picture is one block 14 rows tall; the START menu's SAVE screen covers as many
                                  // tiles, in windows that never make more than a text box's 6 full rows (Gen 3 draws
                                  // window text as unique tiles, so counting distinct tiles can't tell them apart), and
                                  // Unbound's full-screen START menu makes 11 - but as two bars, 6 rows over the field
                                  // and 5 under it, which dimmed the field while the menu was open (GitHub #86)
#define FADE_LEVEL 12             // a frame whose every sampled pixel is this dark (or as near white) is a fade
#define OVERLAY_STEP 24           // the dim's ramp per frame (0..256)
#define OVERLAY_DIM 150           // how dark the map around the picture goes, of 256

static bool transitionRunning(void) {
    return C[PK_WIDE_TRANSITION_PTR] && r32((uint32_t) C[PK_WIDE_TRANSITION_PTR]) != 0;
}

/** FireRed's quest log replaying the field ("Previously on your quest", after Continue): scripted scenes with text
 * boxes coming and going, which zoomed the camera in and out - it stays close until the field is the player's. */
static bool questLogPlaying(void) {
    if (!C[PK_WIDE_QUEST_LOG]) return false;
    uint8_t s = r8((uint32_t) C[PK_WIDE_QUEST_LOG]);
    return s == 2 || s == 3;   // QL_STATE_PLAYBACK / QL_STATE_PLAYBACK_LAST
}

/** BG0 covers most of the screen with a picture: one unbroken block of full-width rows (windows, even a save
 * screen's, never make more than a text box's few; Unbound's START menu bars, top and bottom, aren't one block). */
static bool overlayUp(void) {
    if (!(io(0) & 0x100)) return false;
    const uint8_t* vram = (const uint8_t*) G->video.vram;
    uint32_t scr = ((io(0x08) >> 8) & 31) * 0x800u;
    int hofs = io(0x10) & 0x1FF, vofs = io(0x12) & 0x1FF, n = 0, run = 0, block = 0;
    for (int ty = 0; ty < 20; ty++) {
        int row = 0;
        for (int tx = 0; tx < 30; tx++) {
            int rx = ((hofs >> 3) + tx) & 31, ry = ((vofs >> 3) + ty) & 31;
            if (le16(vram + scr + 2 * (uint32_t) (ry * 32 + rx)) & 0x3FF) row++;
        }
        n += row;
        run = row >= 28 ? run + 1 : 0;
        if (run > block) block = run;
    }
    return n >= OVERLAY_TILES && block >= OVERLAY_ROWS;
}

/** The frame is all black or all white: a fade between two maps (a door, a connection building), not a screen of
 * its own - the camera holds its zoom through it. */
static bool fadedFrame(const uint32_t* frame) {
    int lo = 255, hi = 0;
    for (int y = 2; y < PK_WIDE_H; y += 6)
        for (int x = 3; x < PK_WIDE_W; x += 6) {
            uint32_t p = frame[y * PK_WIDE_W + x];
            int r = p & 0xFF, g = (p >> 8) & 0xFF, b = (p >> 16) & 0xFF;
            int mx = r > g ? (r > b ? r : b) : (g > b ? g : b), mn = r < g ? (r < b ? r : b) : (g < b ? g : b);
            if (mx > hi) hi = mx;
            if (mn < lo) lo = mn;
            if (hi > FADE_LEVEL && lo < 255 - FADE_LEVEL) return false;
        }
    return hi <= FADE_LEVEL || lo >= 255 - FADE_LEVEL;
}

/** mGBA's layer tag on an output pixel (its 32-bit renderer keeps them in the top byte): BG `index`
 * (FLAG_IS_BACKGROUND + index), never the backdrop (every flag set) nor a blended / covered pixel (flags stripped). */
static inline bool fromBg(uint32_t v, int index) {
    return (v & 0x38000000u) == (0x08000000u | (uint32_t) index << 28) && (v & 0xFC000000u) != 0xFC000000u;
}

/** How much of the picture is showing, 0..256: its alpha blend as the game fades it out (map_preview_screen.c: BG0
 * the first target, BLDALPHA from 16 to 0), else all of it. The dim around it follows this, so the map comes back
 * exactly as the card goes - it used to stay dark until the card's tiles were gone, then brighten in a step. */
static int overlayStrength(void) {
    uint16_t cnt = io(0x50);
    if (((cnt >> 6) & 3) == 1 && (cnt & 1)) {
        int eva = io(0x52) & 0x1F;
        return (eva > 16 ? 16 : eva) * 16;
    }
    return 256;
}

static inline uint32_t dimmed(uint32_t c, int dim) {
    int k = 256 - (dim * OVERLAY_DIM >> 8);
    uint32_t rb = (((c & 0xFF00FF) * (uint32_t) k) >> 8) & 0xFF00FF, g = (((c & 0x00FF00) * (uint32_t) k) >> 8) & 0x00FF00;
    return (c & 0xFF000000) | rb | g;
}

int pk_wide_wants_close(void) { return gbGame ? pk_wide_gb_wants_close() : lastClose; }
int pk_wide_scene(void) { return gbGame ? pk_wide_gb_scene() : lastScene; }

int pk_wide_frame(struct mCore* core, const uint32_t* frame, uint32_t* out, int margin, uint32_t* centre) {
    if (margin < 0) margin = 0;
    if (margin > PK_WIDE_MAX_MARGIN) margin = PK_WIDE_MAX_MARGIN;
    struct PkWideView v = { -margin, 0, PK_WIDE_W + 2 * margin, PK_WIDE_H };
    return pk_wide_view(core, frame, out, v, centre);
}

// --- the fault guard ----------------------------------------------------------------------------------
//
// Everything above reads the game's memory through bounds-checked helpers and clamps every index, so a bad pointer
// or a torn snapshot only draws something wrong. As a last resort a fault inside pk_wide_view (SIGSEGV / SIGBUS /
// SIGFPE / SIGILL on this thread, while drawing) doesn't take the app down: the handler jumps back out, WIDE switches
// itself off for the game (pk_wide_fault says why) and the screen shows the plain frame. A fault anywhere else goes
// on to the handler that was there before (the system's crash reporting), as if this one weren't installed.

#ifndef PK_WIDE_NO_GUARD   // mgba_dump's AddressSanitizer build reports faults itself
#include <setjmp.h>
#include <signal.h>

static __thread sigjmp_buf* guardJmp;   // set only while this thread is inside pk_wide_view
static const int GUARDED[4] = { SIGSEGV, SIGBUS, SIGFPE, SIGILL };
static struct sigaction guardOld[4];
static bool guardInstalled;

static void onFault(int sig, siginfo_t* info, void* ctx) {
    sigjmp_buf* j = guardJmp;
    if (j) {
        guardJmp = NULL;
        siglongjmp(*j, sig);
    }
    for (int i = 0; i < 4; i++) {
        if (GUARDED[i] != sig) continue;
        const struct sigaction* old = &guardOld[i];
        if ((old->sa_flags & SA_SIGINFO) && old->sa_sigaction) {
            old->sa_sigaction(sig, info, ctx);
        } else if (old->sa_handler != SIG_DFL && old->sa_handler != SIG_IGN && old->sa_handler) {
            old->sa_handler(sig);
        } else {
            sigaction(sig, old, NULL);   // the default action: put it back; the faulting instruction runs into it again
        }
        return;
    }
}

static void installGuard(void) {
    if (guardInstalled) return;
    guardInstalled = true;
    struct sigaction sa;
    memset(&sa, 0, sizeof(sa));
    sa.sa_sigaction = onFault;
    sa.sa_flags = SA_SIGINFO | SA_ONSTACK;
    sigemptyset(&sa.sa_mask);
    for (int i = 0; i < 4; i++) sigaction(GUARDED[i], &sa, &guardOld[i]);
}
#endif

int pk_wide_fault(void) { return lastFault; }

static int viewInner(struct mCore* core, const uint32_t* frame, uint32_t* out, struct PkWideView v, uint32_t* centre);

int pk_wide_view(struct mCore* core, const uint32_t* frame, uint32_t* out, struct PkWideView v, uint32_t* centre) {
#ifndef PK_WIDE_NO_GUARD
    installGuard();
    sigjmp_buf j;
    int sig = sigsetjmp(j, 1);
    if (sig) {
        guardJmp = NULL;
        lastFault = sig;
        int fw = pk_wide_frame_w(), fh = pk_wide_frame_h();
        configured = false;   // off for this game until it's configured again: never the same fault twice
        gbGame = false;
        lastMode = PK_WIDE_MODE_NONE;
        lastBattleWays = 0;
        lastClose = 1;
        if (v.w > PK_WIDE_MAX_VIEW_W) v.w = PK_WIDE_MAX_VIEW_W;
        if (v.h > PK_WIDE_MAX_VIEW_H) v.h = PK_WIDE_MAX_VIEW_H;
        for (int y = 0; out && y < v.h; y++)
            for (int x = 0; x < v.w; x++) {
                int X = v.x + x, Y = v.y + y;
                out[y * v.w + x] = X >= 0 && X < fw && Y >= 0 && Y < fh ? frame[Y * fw + X] : 0xFF000000u;
            }
        return 0;
    }
    guardJmp = &j;
    int r = viewInner(core, frame, out, v, centre);
    guardJmp = NULL;
    return r;
#else
    return viewInner(core, frame, out, v, centre);
#endif
}

void pk_wide_skip(struct mCore* core, const uint32_t* frame) {
    struct PkWideView v = { 0, 0, 1, 1 };
    pk_wide_view(core, frame, NULL, v, NULL);
}

void pk_wide_probe(struct mCore* core, const uint32_t* frame, int skip) {
    static uint32_t px;
    struct PkWideView v = { 0, 0, 1, 1 };
    if (gbGame) pk_wide_view(core, frame, skip ? NULL : &px, v, NULL);
}

static int viewInner(struct mCore* core, const uint32_t* frame, uint32_t* out, struct PkWideView v, uint32_t* centre) {
    if (gbGame) return pk_wide_gb_view(core, frame, out, v, centre);
    realFrame = frame;
    if (!out) {
        // pk_wide_skip: a frame nobody will see (fast-forward runs several per refresh). Only the RAM after it is
        // kept - what the next frame shows - so the frame that is drawn still has its snapshot from the frame before.
        if (!core || core->platform(core) != mPLATFORM_GBA || !configured) return 0;
        G = (struct GBA*) core->board;
        useLive();
        hookScanlines(G);
        int cur = prev == 0 ? 1 : 0;
        take(&snaps[cur]);
        if (lineIoFrames < 2) lineIoFrames++;
        prev = cur;
        return mix;
    }
    if (v.w > PK_WIDE_MAX_VIEW_W) v.w = PK_WIDE_MAX_VIEW_W;
    if (v.h > PK_WIDE_MAX_VIEW_H) v.h = PK_WIDE_MAX_VIEW_H;
    if (v.w < 1 || v.h < 1) return 0;
    uint32_t alpha = frame[0] & 0xFF000000;
    if (!core || core->platform(core) != mPLATFORM_GBA || !configured) {
        for (int j = 0; j < v.h; j++)
            for (int i = 0; i < v.w; i++) {
                int X = v.x + i, Y = v.y + j;
                out[j * v.w + i] = onFrame(X, Y) ? frame[Y * PK_WIDE_W + X] : alpha;
            }
        lastClose = 1;
        return 0;
    }
    G = (struct GBA*) core->board;
    useLive();
    hookScanlines(G);

    int cur = prev == 0 ? 1 : 0;
    take(&snaps[cur]);

    // The camera: what the frame was scrolled by, anchored on whichever snapshot's ring offsets
    // (and pos +-1 metatile) reproduce the frame's own tilemaps best.
    lastScore = -1;
    lastTorn = 0;
    int best = -1, bestCx = 0, bestCy = 0, bestH = 0, bestV = 0, bestSnap = -1;
    if (fieldDisplay()) {
        readBgs();
        const int tryOrder[2] = { prev, cur };
        for (int t = 0; t < 2 && best < 1000; t++) {
            int si = tryOrder[t];
            if (si < 0 || !snaps[si].ok) continue;
            const struct Snap* s = &snaps[si];
            // The base scroll: as last written (the drawn frame's, unless a transition rewrote it per line - then
            // the last line's), or as the camera in RAM has it (a transition that slides lines both ways).
            for (int b = 0; b < 2 && best < 1000; b++) {
                int hofs = b ? s->href : io(0x14) & 0x1FF, vofs = b ? s->vref : io(0x16) & 0x1FF;
                if (b && hofs == (io(0x14) & 0x1FF) && vofs == (io(0x16) & 0x1FF)) break;
                for (int d = 0; d < 9; d++) {
                    int dx = (int[]) { 0, -1, 1, 0, 0, -1, 1, -1, 1 }[d], dy = (int[]) { 0, 0, 0, -1, 1, -1, -1, 1, 1 }[d];
                    int cx = (s->posX + dx) * 16 + signed8(hofs - s->xTile * 8);
                    int cy = (s->posY + dy) * 16 + signed8(vofs - s->yTile * 8);
                    int sc = score(s, cx, cy, hofs, vofs);
                    if (sc > best) {
                        best = sc; bestCx = cx; bestCy = cy; bestH = hofs; bestV = vofs; bestSnap = si;
                    }
                    if (sc == 1000) break;
                }
            }
        }
        lastScore = best;
    }
    bool valid = best >= MIN_SCORE;
    bool battle = !valid && inBattleScreen();
    bool menu = !valid && !battle && menuScreen();
    // A menu screen opened from a battle (POKéMON, BAG: gMain.inBattle stays set) is part of the battle for the
    // camera: a battle always pulls in to 1x, and its sub-screens used to read as SCENE_MENU, which AUTO ZOOM IN
    // OFF leaves zoomed out - the party / bag screen zoomed out and the battle zoomed back in after it.
    bool inBattle = C[PK_WIDE_GMAIN] && (r8((uint32_t) (C[PK_WIDE_GMAIN] + C[PK_WIDE_INBATTLE_OFF])) & 2);
    lastMode = valid ? PK_WIDE_MODE_MAP : battle ? PK_WIDE_MODE_BATTLE : menu ? PK_WIDE_MODE_MENU : PK_WIDE_MODE_NONE;
    lastBattleWays = 0;
    bool locked = C[PK_WIDE_CONTROLS_LOCKED] && r8((uint32_t) C[PK_WIDE_CONTROLS_LOCKED]);
    bool transition = transitionRunning();
    // Only a FireRed-engine game has the map preview: anywhere else a BG0 that fills the screen is something else -
    // SoulGold's item description over its message box, a trainer's mugshot sliding in (GitHub #100) - and its
    // pixels carry no layer tags there (it keeps the window registers on), so the dim darkened the windows too.
    bool overlay = valid && mapPreviews && !transition && overlayUp();
    lastClose = !valid || transition || overlay || (locked && (textUp() || effectsUp()));
    // Between two maps (a door, a connection building) the screen is black for a few frames with no map to check:
    // the camera holds through it (it used to pull in to 1x and zoom back out on the other side).
    bool fade = !valid && !battle && fadedFrame(frame);   // (a black frame can pass as a menu screen: still a fade)
    bool replay = questLogPlaying();
    lastClose = lastClose || replay;
    lastScene = replay ? PK_WIDE_SCENE_OFF : fade ? PK_WIDE_SCENE_FADE : menu && !inBattle ? PK_WIDE_SCENE_MENU : !valid ? PK_WIDE_SCENE_OFF
              : transition ? PK_WIDE_SCENE_BATTLE_START : overlay ? PK_WIDE_SCENE_OVERLAY
              : lastClose ? PK_WIDE_SCENE_TEXT : PK_WIDE_SCENE_FIELD;
    int dimTarget = overlay ? overlayStrength() : 0;
    if (overlayDim < dimTarget) overlayDim = overlayDim + OVERLAY_STEP > dimTarget ? dimTarget : overlayDim + OVERLAY_STEP;
    else if (overlayDim > dimTarget) overlayDim = overlayDim - OVERLAY_STEP < dimTarget ? dimTarget : overlayDim - OVERLAY_STEP;

    // Sprites: the frame shows the snapshot before it; if its list isn't what the OAM has, the
    // RAM was caught mid-update (a lag frame repeats the last picture) - keep the last good list.
    if (valid && prev >= 0 && snaps[prev].ok) {
        int other = shown ^ 1;
        npieces[other] = buildPieces(&snaps[prev], pieces[other]);
        if (oamAgrees(pieces[other], npieces[other]) || npieces[shown] == 0) shown = other;
        else lastTorn = 1;
    }

    if (valid || battle || menu) {
        if (valid) {
            const struct Snap* s = &snaps[bestSnap];
            drawRegion(s, bestCx, bestCy, bestH, bestV, v.x, v.y, v.x + v.w, v.y + v.h, true, &raw[0][0], BUF_W, alpha);
            if (!overlay) markBarRows(v.x, v.y, v.w, v.h);   // FireRed's map preview keeps its dimmed map around it
        } else if (battle) {
            drawBattleRegion(v.x, v.y, v.x + v.w, v.y + v.h, true, &raw[0][0], BUF_W, alpha);
        } else {
            drawMenuRegion(v.x, v.y, v.x + v.w, v.y + v.h, true, &raw[0][0], BUF_W, alpha, frame);
        }
        for (int j = 0; j < v.h; j++) memcpy(rawHole[j], holeBuf[j], (size_t) v.w);
        rawView = v;
        if (centre) {
            if (valid) drawRegion(&snaps[bestSnap], bestCx, bestCy, bestH, bestV, 0, 0, PK_WIDE_W, PK_WIDE_H, false, centre, PK_WIDE_W, alpha);
            else if (battle) drawBattleRegion(0, 0, PK_WIDE_W, PK_WIDE_H, false, centre, PK_WIDE_W, alpha);   // holes show the backdrop, as the PPU does
            else drawMenuRegion(0, 0, PK_WIDE_W, PK_WIDE_H, false, centre, PK_WIDE_W, alpha, NULL);
        }
        mix = mix + MIX_STEP > 256 ? 256 : mix + MIX_STEP;
    } else {
        mix = mix - MIX_STEP < 0 ? 0 : mix - MIX_STEP;   // the last scene, frozen, dissolves into the glow
    }
    if (!rawView.w) mix = 0;   // nothing drawn yet
    if (mix < 256) ambientPrepare(frame);
    else edgeAccOk = false;    // the glow starts from the edges as they are when it's next needed
    int reach[4] = { -v.x, v.x + v.w - PK_WIDE_W, -v.y, v.y + v.h - PK_WIDE_H };

    for (int j = 0; j < v.h; j++) {
        int Y = v.y + j;
        uint32_t* row = out + j * v.w;
        int ry = Y - rawView.y;
        bool rawRow = ry >= 0 && ry < rawView.h;
        for (int i = 0; i < v.w; i++) {
            int X = v.x + i;
            if (onFrame(X, Y)) {
                // The frame itself: copied a row segment at a time - or, under a BG0 picture, dimmed but for BG0's own
                // pixels (the map showing around and through the picture).
                int n = (PK_WIDE_W - X) < (v.w - i) ? PK_WIDE_W - X : v.w - i;
                if (!overlayDim) {
                    memcpy(row + i, frame + Y * PK_WIDE_W + X, (size_t) n * sizeof(uint32_t));
                } else {
                    for (int k = 0; k < n; k++) {
                        uint32_t p = frame[Y * PK_WIDE_W + X + k];
                        row[i + k] = fromBg(p, 0) ? p : dimmed(p, overlayDim);
                    }
                }
                i += n - 1;
                continue;
            }
            int rx = X - rawView.x, m = mix;
            uint32_t scene = 0;
            if (rawRow && rx >= 0 && rx < rawView.w) {
                // A hole goes on with the frame's nearest edge pixel as the game shows it now (so it follows fades).
                scene = rawHole[ry][rx] ? frame[clampi(Y, 0, PK_WIDE_H - 1) * PK_WIDE_W + clampi(X, 0, PK_WIDE_W - 1)]
                                        : raw[ry][rx];
            } else {
                m = 0;   // the window moved off what was last drawn: the glow
            }
            uint32_t o = m >= 256 ? scene : lerp(glowAt(frame, X, Y, reach, alpha), scene, m);
            row[i] = overlayDim ? dimmed(o, overlayDim) : o;
        }
    }
    if (lineIoFrames < 2) lineIoFrames++;
    prev = cur;
    return mix;
}
