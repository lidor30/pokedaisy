static void drawRegion(const struct Snap* s, int cx, int cy, int href, int vref, int x0, int y0, int x1, int y1,
                       bool skipFrame, uint32_t* dst, int stride, uint32_t alpha) {
    int w = x1 - x0, h = y1 - y0;
    PW_MARK(dr0);
    foreignFrame++;
    for (int i = 0; i < MAX_CONNS; i++) connForeign[i] = i < s->nconn ? foreignFor(s, &s->conn[i]) : NULL;
    PW_MARK(dr1);
    PW_ADD(4, dr0, dr1);
    for (int j = 0; j < h; j++) {
        int y = y0 + j;
        // This line as the PPU drew it: its layers, windows and scroll (a line scrolled apart from the
        // latched value is that much further along the map). Above / below the screen: its edge line's.
        useLine(y);
        int dx = signed9((io(0x14) & 0x1FF) - href), dy = signed9((io(0x16) & 0x1FF) - vref);
        int disp = io(0);
#ifndef PK_WIDE_NOFAST
        // The common row (no brightness fade, the frame's own pixels skipped): each map tile's row at once - where the
        // windows give every pixel of it the same layers; a run they cut through goes pixel by pixel as below.
        if (skipFrame && ((disp >> 8) & 0x0E) && ((io(0x50) >> 6) & 3) < 2 && !tintShown) {
            PW_COUNT(pwFast);
            for (int x = 0; x < w;) {
                int sx = x0 + x;
                if (onFrame(sx, y)) {
                    int n = (PK_WIDE_W - sx) < (w - x) ? PK_WIDE_W - sx : w - x;
                    for (int k = 0; k < n; k++) {
                        holeBuf[j][x + k] = 0;
                        takenBuf[j][x + k] = 1;
                    }
                    x += n;
                    continue;
                }
                int wx = cx + dx + sx, wy = cy + dy + y;
                int n = 8 - (wx & 7);                                  // to the end of this map tile
                if (n > w - x) n = w - x;
                if (y >= 0 && y < PK_WIDE_H && sx < 0 && n > -sx) n = -sx;   // the frame starts at sx = 0
                int wl0 = windowLayers(sx, y), enabled = (disp >> 8) & wl0 & 0x0E;
                bool uniform = enabled != 0;
#ifdef PK_WIDE_CHECK
                bool slowU = enabled != 0;
                for (int k = 1; slowU && k < n; k++)
                    if (((disp >> 8) & windowLayers(sx + k, y) & 0x0E) != enabled) slowU = false;
#endif
                // The layers differ along the run only where a window's edge falls in it.
                if (uniform && !windowsUniform(sx, n)) {
                    for (int k = 1; uniform && k < n; k++)
                        if (((disp >> 8) & windowLayers(sx + k, y) & 0x0E) != enabled) uniform = false;
                }
#ifdef PK_WIDE_CHECK
                if (uniform != slowU) { fprintf(stderr, "windowsUniform MISMATCH sx=%d n=%d y=%d\n", sx, n, y); abort(); }
#endif
                if (uniform) {
                    uint16_t col[8];
                    uint8_t pr[8], ly[8];
                    mapTileRow(s, wx, wy, n, enabled, col, pr, ly);
                    for (int k = 0; k < n; k++) {
                        uint32_t c32 = color(col[k], alpha);
                        holeBuf[j][x + k] = 0;
                        dst[j * stride + x + k] = c32;   // (the brightness fade is off: mode < 2)
                        prioBuf[j][x + k] = pr[k];
                        layerBuf[j][x + k] = ly[k];
                        below[j][x + k] = c32;
                        takenBuf[j][x + k] = 0;
                    }
                } else {
                    for (int k = 0; k < n; k++) {
                        int px = sx + k, wl = windowLayers(px, y), en = (disp >> 8) & wl & 0x0E;
                        int prio = 4, layer = 5, ci = 0;
                        holeBuf[j][x + k] = !en;
                        uint16_t c = en ? mapPixel(s, cx + dx + px, cy + dy + y, en, &prio, &layer, false) : P[ci];
                        uint32_t c32 = color(c, alpha);
                        dst[j * stride + x + k] = wl & 0x20 ? brightness(c32, layer) : c32;
                        prioBuf[j][x + k] = (uint8_t) prio;
                        layerBuf[j][x + k] = (uint8_t) layer;
                        below[j][x + k] = c32;
                        takenBuf[j][x + k] = 0;
                    }
                }
                x += n;
            }
            continue;
        }
#endif
        PW_COUNT(pwSlow);
        PW_COUNT(pwWhy[!skipFrame ? 0 : !((disp >> 8) & 0x0E) ? 1 : ((io(0x50) >> 6) & 3) >= 2 ? 2 : 3]);
        for (int x = 0; x < w; x++) {
            int sx = x0 + x;
            if (skipFrame && onFrame(sx, y)) {
                // A whole row's span at once: byte by byte it took a 3DS a third of the margins' time.
                int n = PK_WIDE_W - sx < w - x ? PK_WIDE_W - sx : w - x;
                memset(&holeBuf[j][x], 0, (size_t) n);
                memset(&takenBuf[j][x], 1, (size_t) n);   // no sprite drawn there either
                x += n - 1;
                continue;
            }
            // Off the real screen a run of pixels in one cell of the map, under one window setting, goes at once.
            int spanWl = onFrame(sx, y) ? 0 : windowLayers(sx, y);
            if ((disp >> 8) & spanWl & 0x0E) {
                int mx = dx + sx, my = dy + y, n = 8 - ((cx + mx) & 7);
                if (n > w - x) n = w - x;
                if (sx < 0 && y >= 0 && y < PK_WIDE_H && sx + n > 0) n = -sx;   // up to the frame's edge
                for (int k = 1; k < n && (disp & 0xE000); k++)
                    if (windowLayers(sx + k, y) != spanWl) n = k;
                uint16_t cs[8];
                uint8_t ps[8], ls[8];
                mapSpan(s, cx + mx, cy + my, n, (disp >> 8) & spanWl & 0x0E, cs, ps, ls);
                for (int k = 0; k < n; k++) {
                    uint32_t c32 = color(cs[k], alpha);
                    holeBuf[j][x + k] = 0;
                    dst[j * stride + x + k] = spanWl & 0x20 ? brightness(c32, ls[k]) : c32;
                    prioBuf[j][x + k] = ps[k];
                    layerBuf[j][x + k] = ls[k];
                    below[j][x + k] = c32;
                    takenBuf[j][x + k] = 0;
                }
                x += n - 1;
                continue;
            }
            int prio = 4, layer = 5, ci = 0;
            int wl = windowLayers(sx, y), enabled = (disp >> 8) & wl & 0x0E;
            // Windowed out (Flash's darkness, a transition's wedge): nothing of the map here. A hole -
            // the strips go on with the game's own edge pixel of that row.
            holeBuf[j][x] = !enabled;
            // On the real screen a line scrolled apart (a transition's slices) shows the 256x256 ring wrapped around:
            // the map where the ring holds the camera's view, past that the ring's leftover tiles - which the game may
            // have redrawn since (VRAM after a frame already has the next one's new row / column), so those pixels are
            // the real frame's own. The margins go on with the map itself, that much further along.
            int mx = dx + sx, my = dy + y;
            if (onFrame(sx, y)) {
                mx = (mx + 256) & 0xFF;
                my = (my + 256) & 0xFF;
                if (enabled && (mx >= PK_WIDE_W || my >= PK_WIDE_H)) {
                    dst[j * stride + x] = below[j][x] = (realFrame[y * PK_WIDE_W + sx] & 0xFFFFFF) | alpha;
                    prioBuf[j][x] = 0;
                    layerBuf[j][x] = 5;
                    takenBuf[j][x] = 0;
                    continue;
                }
            }
            uint16_t c = enabled ? mapPixel(s, cx + mx, cy + my, enabled, &prio, &layer, onFrame(sx, y)) : P[ci];
            uint32_t c32 = color(c, alpha);
            dst[j * stride + x] = wl & 0x20 ? brightness(c32, layer) : c32;
            prioBuf[j][x] = (uint8_t) prio;
            layerBuf[j][x] = (uint8_t) layer;
            below[j][x] = c32;
            takenBuf[j][x] = 0;
        }
    }
    useLive();
    PW_MARK(dr2);
    PW_ADD(5, dr1, dr2);
    frameTaken = skipFrame;
    drawObjects(s, cx, cy, x0, y0, x1, y1, dst, stride, alpha);
}

// The PPU's OBJ layer: per pixel the first opaque piece in OAM order wins among sprites,
// then shows if its priority is <= the front BG's.
static void drawObjects(const struct Snap* s, int cx, int cy, int x0, int y0, int x1, int y1, uint32_t* dst, int stride, uint32_t alpha) {
    PW_MARK(dr2);
    int w = x1 - x0;
    if (!(io(0) & 0x40)) return;   // 2D tile mapping
    const uint8_t* vram = (const uint8_t*) G->video.vram;
    const uint16_t* oam = G->video.oam.raw;
    const struct Piece* p = pieces[shown];
    for (int i = 0; i < npieces[shown]; i++) {
        if (p[i].mode == 2) continue;   // an OBJ window shape, not drawn
        int sw = p[i].w, sh = p[i].h;
        int bw = p[i].rot == 3 ? 2 * sw : sw, bh = p[i].rot == 3 ? 2 * sh : sh;   // the box it covers on screen
        if (p[i].x + bw <= x0 || p[i].x >= x1 || p[i].y + bh <= y0 || p[i].y >= y1) continue;
        // Wholly on the frame: nothing of it reaches the margins (Route 113's ash is dozens of these, a 3DS's whole frame).
        if (frameTaken && p[i].x >= 0 && p[i].y >= 0 && p[i].x + bw <= PK_WIDE_W && p[i].y + bh <= PK_WIDE_H) continue;
        int m = p[i].mat;   // an affine sprite's matrix: the frame's OAM affineParams from entry 4 * m
        int pa = (int16_t) oam[(4 * m) * 4 + 3], pb = (int16_t) oam[(4 * m + 1) * 4 + 3];
        int pc = (int16_t) oam[(4 * m + 2) * 4 + 3], pd = (int16_t) oam[(4 * m + 3) * 4 + 3];
        for (int yy = 0; yy < bh; yy++) {
            int Y = p[i].y + yy, J = Y - y0;
            if (Y < y0 || Y >= y1) continue;
            useLine(Y);
            if (!(io(0) & 0x1000)) continue;   // OBJ off on this line
            for (int xx = x0 > p[i].x ? x0 - p[i].x : 0; xx < bw; xx++) {
                int X = p[i].x + xx - x0;
                if (X >= w) break;
                if (frameTaken && onFrame(p[i].x + xx, Y)) {
                    xx = PK_WIDE_W - p[i].x - 1;   // on past the frame
                    continue;
                }
                int px, py;
                if (p[i].rot & 1) {   // mGBA's: texel = (matrix * (box pixel - box centre) + sprite centre) >> 8
                    px = (pa * (xx - bw / 2) + pb * (yy - bh / 2) + (sw << 7)) >> 8;
                    py = (pc * (xx - bw / 2) + pd * (yy - bh / 2) + (sh << 7)) >> 8;
                    if (px < 0 || px >= sw || py < 0 || py >= sh) continue;
                } else {
                    px = p[i].hflip ? sw - 1 - xx : xx;
                    py = p[i].vflip ? sh - 1 - yy : yy;
                }
                int t = p[i].tile + (py / 8) * (p[i].w / 8) + px / 8;   // 1D mapping
                const uint8_t* line = vram + 0x10000 + ((uint32_t) (t * 32 + (py & 7) * 4) & 0x7FFF);
                if (!(p[i].rot & 1) && !(line[0] | line[1] | line[2] | line[3])) {
                    xx += p[i].hflip ? px & 7 : 7 - (px & 7);   // nothing in this tile's row: Route 113's ash is mostly this
                    continue;
                }
                uint8_t v = line[(px & 7) / 2];
                int ci = px & 1 ? v >> 4 : v & 15;
                if (!ci || takenBuf[J][X]) continue;
                if (p[i].copy && onFrame(p[i].x + xx, Y)) continue;   // the real frame has its own
                int wl = windowLayers(p[i].x + xx, Y);
                if (!(wl & 0x10)) continue;
                takenBuf[J][X] = 1;
                if (p[i].prio > OBJ_PRIO(J, X)) continue;
                uint32_t c = color(P[256 + p[i].pal * 16 + ci], alpha);
                dst[J * stride + X] = p[i].mode == 1 ? blend(c, OBJ_BELOW(J, X), OBJ_LAYER(J, X)) : wl & 0x20 ? brightness(c, 4) : c;
                holeBuf[J][X] = 0;
            }
        }
    }
    PW_MARK(dr3);
    PW_ADD(6, dr2, dr3);
    drawGhosts(s, cx, cy, x0, y0, x1, y1, dst, stride, alpha);
    drawPartner(x0, y0, x1, y1, dst, stride, alpha);
    useLive();
    PW_MARK(dr4);
    PW_ADD(7, dr3, dr4);
}

// --- battles ---------------------------------------------------------------------------------------
//
// The battle background (BG3: battle_bg.c's template - char base 2, screen base 26, a 64x32 tilemap) is 512
// px wide in VRAM, sky / terrain / both platforms all the way across, of which the screen shows 240. So a
// battle's strips are what a wider PPU would draw: BG3 from VRAM with each line's own scroll and windows,
// and the frame's real OAM wherever sprites reach past the edges (healthboxes, trainers sliding in).
// BG0-2 (text, menus, animations) have nothing meaningful past 240 and aren't drawn; where BG3 is
// transparent (the text box rows) the strip is a hole, filled with the game's own edge pixel of that row
// (the dark band the text box and menus sit on), so the band simply goes on to the screen's edges.
//
// Where BG3 alone can't go on, the strips are mirrored in from the edges instead, BG1-3 as the PPU stacks them
// (BG0 is the text), each side on its own (GitHub #114, SoulGold): a background that is one 256 px picture
// repeated (its two screen blocks the same, above the text box) has no scenery past the screen, only the
// picture's other side; BG3 past an edge that doesn't go on from it (Route 29: trees to the edge, bare sky past
// it - battleEdgeBroken); a scene drawn partly on BG1 / BG2 (retail's intro dust and rocks too), which would
// stop dead at the edges with only BG3 past them - but never a BG1 / BG2 window against an edge, its map empty past
// it (the level-up stats, GitHub #245: findBattleBgScenery). Retail's BG3 is scenery all 512 px
// across: drawn as VRAM has it (mirrored, the foe's platform ending at the edge grew a second one). The text box rows
// (from BATTLE_TEXT_TOP) are always holes past the edges, so the dark band goes on even where a hack's BG3 has
// light tiles there.

/** Where the battle's text box / action menu rows start (tile row 14, in every Gen 3 battle layout). */
#define BATTLE_TEXT_TOP 112

/** BG3's 64x32 tilemap at screen base `scr` is one 256 px picture twice over (its rows above the text box). */
static bool battleBgRepeats(const uint8_t* vram, uint32_t scr) {
    if (scr + 0x1000 > 0x10000) return false;
    return memcmp(vram + scr, vram + scr + 0x800, (BATTLE_TEXT_TOP / 8) * 32 * 2) == 0;
}

/** A battle column past the screen's edges, mirrored back into it (again and again, for a window past 240 more). */
static int battleMirrorX(int sx) {
    int m = ((sx % (2 * PK_WIDE_W)) + 2 * PK_WIDE_W) % (2 * PK_WIDE_W);
    return m < PK_WIDE_W ? m : 2 * PK_WIDE_W - 1 - m;
}

/** Text BG `n`'s tilemap entry under screen (x, y), with line y's registers ([useLine] first), any size; *bx / *by
 * get the point in the BG's own map. False past VRAM. */
static bool bgEntry(int n, int x, int y, uint16_t* e, int* bx, int* by) {
    uint16_t cnt = io(0x08 + 2 * n);
    uint32_t scr = ((cnt >> 8) & 31) * 0x800u;
    int wide = (cnt >> 14) & 1, tall = cnt >> 15;
    *bx = (x + (io(0x10 + 4 * n) & 0x1FF)) & (wide ? 511 : 255);
    *by = (y + (io(0x12 + 4 * n) & 0x1FF)) & (tall ? 511 : 255);
    uint32_t at = scr + (uint32_t) ((*bx >> 8) + (*by >> 8) * (wide ? 2 : 1)) * 0x800 + 2 * (uint32_t) (((*by >> 3) & 31) * 32 + ((*bx >> 3) & 31));
    if (at + 2 > 0x10000) return false;
    *e = le16((const uint8_t*) G->video.vram + at);
    return true;
}

/** Text BG `n`'s tile under screen (x, y) has a pixel drawn (line y's registers, [useLine] first). */
static bool bgTileFilled(int n, int x, int y) {
    const uint8_t* vram = (const uint8_t*) G->video.vram;
    uint16_t cnt = io(0x08 + 2 * n), e;
    int bx, by;
    if (!bgEntry(n, x, y, &e, &bx, &by)) return false;
    uint32_t size = cnt & 0x80 ? 64 : 32, off = ((cnt >> 2) & 3) * 0x4000u + (e & 0x3FFu) * size;
    for (uint32_t k = 0; k < size && off + k < 0x10000; k++)
        if (vram[off + k]) return true;
    return false;
}

/** Text BG `n`'s colour index at screen (x, y), with line y's registers ([useLine] first): any size, 4 or 8 bpp;
 * 0 = transparent. *pal gets the palette offset to add (P index). */
static int bgPixel(int n, int x, int y, int* pal) {
    const uint8_t* vram = (const uint8_t*) G->video.vram;
    uint16_t cnt = io(0x08 + 2 * n), e;
    uint32_t chr = ((cnt >> 2) & 3) * 0x4000u;
    int bx, by;
    if (!bgEntry(n, x, y, &e, &bx, &by)) return 0;
    int px = bx & 7, py = by & 7;
    if (e & 0x400) px = 7 - px;
    if (e & 0x800) py = 7 - py;
    if (cnt & 0x80) {   // 256 colours
        uint32_t off = chr + (e & 0x3FFu) * 64 + (uint32_t) (py * 8 + px);
        *pal = 0;
        return off < 0x10000 ? vram[off] : 0;
    }
    uint32_t off = chr + (e & 0x3FFu) * 32 + (uint32_t) (py * 4 + px / 2);
    *pal = (e >> 12) * 16;
    return off < 0x10000 ? (px & 1 ? vram[off] >> 4 : vram[off] & 15) : 0;
}

/** BG3's colour at screen (x, y) as 15-bit BGR (the backdrop where it's transparent); line y's registers. */
static uint16_t bg3Colour(int x, int y) {
    int pal, ci = bgPixel(3, x, y, &pal);
    return P[ci ? pal + ci : 0];
}

static int colourJump(uint16_t a, uint16_t b) {
    int d = 0;
    for (int k = 0; k < 15; k += 5) d += abs(((a >> k) & 31) - ((b >> k) & 31));
    return d;
}

/** BG3 doesn't go on past this edge (side 0 left, 1 right): over the scene rows, the step from the screen's last
 * column to the first one past it is well beyond the steps between the columns inside (retail's scenery goes on
 * with none; Route 29's trees in SoulGold end there, the sky past them). Summed in 5-bit colour steps. */
static bool battleEdgeBroken(int side) {
    int out = side ? PK_WIDE_W : -1, edge = side ? PK_WIDE_W - 1 : 0, in1 = side ? PK_WIDE_W - 2 : 1, in2 = side ? PK_WIDE_W - 3 : 2;
    int seam = 0, a = 0, b = 0;
    for (int y = 0; y < BATTLE_TEXT_TOP; y++) {
        useLine(y);
        if (!(io(0) & 0x0800)) continue;
        uint16_t e = bg3Colour(edge, y), i1 = bg3Colour(in1, y);
        seam += colourJump(bg3Colour(out, y), e);
        a += colourJump(e, i1);
        b += colourJump(i1, bg3Colour(in2, y));
    }
    int inside = a < b ? a : b;
    return seam > 2 * inside + 4 * BATTLE_TEXT_TOP;
}

/** Whether BG1 / BG2 ([n - 1]) can be mirrored in past each edge ([side]: 0 left, 1 right) this frame: it isn't a
 * window against that edge. A window or banner the game put there (the level-up stats and banner, GitHub #245) has
 * tiles in the screen's last tile column, the map empty past them on every line; scenery goes on in VRAM on some line
 * above the text box (retail's intro grass, an animation's backdrop), or stops short of the edge (the intro's rocks).
 * The banner's rows don't count as going on: sliding in or out it has tiles past the edge for a moment, and read as
 * scenery the strip was mirrored in for those frames, a piece of the platform flashing at the side (GitHub #258). */
#define BATTLE_BANNER_ROWS 32   // Unbound's banner when a Pokémon on the bench levels up, across the top
static bool battleBgScenery[2][2];

static void findBattleBgScenery(void) {
    bool touches[2][2] = { { false } }, goesOn[2][2] = { { false } };
    for (int y = 0; y < BATTLE_TEXT_TOP; y++) {
        useLine(y);
        for (int n = 1; n <= 2; n++) {
            if (!(io(0) & (0x100 << n))) continue;
            for (int side = 0; side < 2; side++) {
                if (goesOn[n - 1][side] || !bgTileFilled(n, side ? PK_WIDE_W - 1 : 0, y)) continue;
                touches[n - 1][side] = true;
                goesOn[n - 1][side] = y >= BATTLE_BANNER_ROWS && bgTileFilled(n, side ? PK_WIDE_W : -1, y);
            }
        }
    }
    for (int k = 0; k < 4; k++) battleBgScenery[k / 2][k % 2] = goesOn[k / 2][k % 2] || !touches[k / 2][k % 2];
}

/** BG1 or BG2 draws part of the scene at the screen's edges (above the text box) this frame ([findBattleBgScenery]
 * first). */
static bool battleSceneOffBg3(void) {
    for (int y = 0; y < BATTLE_TEXT_TOP; y++) {
        useLine(y);
        uint16_t disp = io(0);
        for (int n = 1; n <= 2; n++) {
            if (!(disp & (0x100 << n))) continue;
            for (int x = 0; x < PK_WIDE_W; x += PK_WIDE_W - 1) {
                int pal;
                if (battleBgScenery[n - 1][x > 0] && (windowLayers(x, y) & (1 << n)) && bgPixel(n, x, y, &pal)) return true;
            }
        }
    }
    return false;
}

static bool inBattleScreen(void) {
    if (!(r8((uint32_t) (C[PK_WIDE_GMAIN] + C[PK_WIDE_INBATTLE_OFF])) & 2)) return false;   // gMain.inBattle
    uint16_t disp = io(0), cnt = io(0x0E);
    return (disp & 7) == 0 && (disp & 0x0800) && ((cnt >> 2) & 3) == 2 && ((cnt >> 8) & 31) == 26 && (cnt >> 14) == 1;
}

/** Which of the strips' ways the last frame's battle took past the edges (PK_WIDE_BATTLE_*), for mgba_dump's `wideinfo`. */
static int lastBattleWays;

/** The battle screen's rectangle [x0, x1) x [y0, y1) (screen coordinates, past the edges allowed) into dst; `hole`
 * marks pixels with nothing drawn (BG3 transparent or windowed out, no sprite; above and below the screen, all). */
static void drawBattleRegion(int x0, int y0, int x1, int y1, bool skipFrame, uint32_t* dst, int stride, uint32_t alpha) {
    const uint8_t* vram = (const uint8_t*) G->video.vram;
    int w = x1 - x0, h = y1 - y0;
    uint32_t repeatsScr = UINT32_MAX;   // the screen base [repeats] was worked out for
    bool repeats = false;
    if (x0 < 0 || x1 > PK_WIDE_W) findBattleBgScenery();
    bool offBg3 = (x0 < 0 || x1 > PK_WIDE_W) && battleSceneOffBg3();
    bool broken[2] = { x0 < 0 && battleEdgeBroken(0), x1 > PK_WIDE_W && battleEdgeBroken(1) };
    if (x0 < 0 || x1 > PK_WIDE_W)
        lastBattleWays |= PK_WIDE_BATTLE_DRAWN | (offBg3 ? PK_WIDE_BATTLE_OFF_BG3 : 0)
            | (broken[0] ? PK_WIDE_BATTLE_BROKEN_LEFT : 0) | (broken[1] ? PK_WIDE_BATTLE_BROKEN_RIGHT : 0);
    for (int j = 0; j < h; j++) {
        int y = y0 + j;
        if (y < 0 || y >= PK_WIDE_H) {
            for (int x = 0; x < w; x++) {
                dst[j * stride + x] = alpha;
                prioBuf[j][x] = 4;
                layerBuf[j][x] = 5;
                below[j][x] = alpha;
                takenBuf[j][x] = 1;
                holeBuf[j][x] = 1;
            }
            continue;
        }
        useLine(y);
        uint16_t disp = io(0), cnt = io(0x0E);
        uint32_t chr = ((cnt >> 2) & 3) * 0x4000u, scr = ((cnt >> 8) & 31) * 0x800u;
        int hofs = io(0x1C) & 0x1FF, vofs = io(0x1E) & 0x1FF, my = (y + vofs) & 255;
        if (scr != repeatsScr) {
            repeatsScr = scr;
            repeats = battleBgRepeats(vram, scr);
            if (repeats && (x0 < 0 || x1 > PK_WIDE_W)) lastBattleWays |= PK_WIDE_BATTLE_REPEATS;
        }
        for (int x = 0; x < w; x++) {
            int sx = x0 + x, ci = 0;
            if (skipFrame && onFrame(sx, y)) {
                holeBuf[j][x] = 0;
                takenBuf[j][x] = 1;
                continue;
            }
            uint16_t e = 0;
            int wl = windowLayers(sx, y);   // its window's layers, and whether effects apply there (0x20)
            bool outside = sx < 0 || sx >= PK_WIDE_W;
            if (outside && (repeats || offBg3 || broken[sx >= PK_WIDE_W]) && y < BATTLE_TEXT_TOP) {
                // Mirrored in: BG1-3 at the column as far inside the screen, stacked by priority (then BG number);
                // BG1 / BG2 only where they're scenery past that edge, not a window against it.
                int mxs = battleMirrorX(sx), wm = windowLayers(mxs, y), layer = 5, pr = 4, pal = 0, side = sx >= PK_WIDE_W;
                for (int p = 0; p < 4 && !ci; p++)
                    for (int n = 1; n <= 3 && !ci; n++)
                        if ((disp & (0x100 << n)) && (wm & (1 << n)) && (io(0x08 + 2 * n) & 3) == p
                                && (n == 3 || battleBgScenery[n - 1][side]) && (ci = bgPixel(n, mxs, y, &pal)))
                            layer = n, pr = p;
                uint32_t c32 = color(P[ci ? pal + ci : 0], alpha);
                dst[j * stride + x] = wm & 0x20 ? brightness(c32, layer) : c32;
                prioBuf[j][x] = (uint8_t) pr;
                layerBuf[j][x] = (uint8_t) layer;
                below[j][x] = c32;
                takenBuf[j][x] = 0;
                holeBuf[j][x] = !ci;
                continue;
            }
            if ((disp & 0x0800) && (wl & 8) && !(outside && y >= BATTLE_TEXT_TOP)) {
                int mx = (sx + hofs) & 511;
                e = le16(vram + scr + (uint32_t) (mx >> 8) * 0x800 + 2 * (uint32_t) (((my >> 3) & 31) * 32 + ((mx >> 3) & 31)));
                int px = mx & 7, py = my & 7;
                if (e & 0x400) px = 7 - px;
                if (e & 0x800) py = 7 - py;
                uint32_t off = chr + (e & 0x3FFu) * 32 + (uint32_t) (py * 4 + px / 2);
                if (off < 0x10000) ci = px & 1 ? vram[off] >> 4 : vram[off] & 15;
            }
            uint16_t c = P[ci ? (e >> 12) * 16 + ci : 0];
            uint32_t c32 = color(c, alpha);
            dst[j * stride + x] = wl & 0x20 ? brightness(c32, ci ? 3 : 5) : c32;   // a window can leave a fade out
            prioBuf[j][x] = (uint8_t) (ci ? cnt & 3 : 4);
            layerBuf[j][x] = (uint8_t) (ci ? 3 : 5);
            below[j][x] = c32;
            takenBuf[j][x] = 0;
            holeBuf[j][x] = !ci;
        }
    }
    // The frame's own OAM, front first. An OAM x of 9 bits reads as negative near its top (a sprite
    // reaching in from the left), y of 8 bits past the screen's bottom likewise.
    // Each OAM the frame was drawn with draws its own lines (one, unless it changed mid-frame).
    int snaps = lineIoFrames > 1 && lineOamN ? lineOamN : 1;
    for (int snap = 0; snap < snaps && (G->memory.io[0] & 0x1000) && (G->memory.io[0] & 0x40); snap++) {
        const uint16_t* oam = lineIoFrames > 1 && lineOamN ? lineOamBuf[snap] : G->video.oam.raw;
        for (int k = 0; k < 128; k++) {
            uint16_t a0 = oam[k * 4], a1 = oam[k * 4 + 1], a2 = oam[k * 4 + 2];
            int rot = (a0 >> 8) & 3;                         // 0 normal, 1 affine, 2 hidden, 3 affine double-size
            int mode = (a0 >> 10) & 3, shape = a0 >> 14, size = a1 >> 14;
            if (rot == 2 || mode == 2 || shape > 2 || (a0 & 0x2000)) continue;   // hidden, OBJ window, 8bpp
            int sw = OBJ_DIMS[shape][size][0], sh = OBJ_DIMS[shape][size][1];
            int bw = rot == 3 ? 2 * sw : sw, bh = rot == 3 ? 2 * sh : sh;   // the box it covers on screen
            int ox = a1 & 0x1FF, oy = a0 & 0xFF;
            if (ox >= 512 - 128) ox -= 512;
            if (oy >= PK_WIDE_H) oy -= 256;
            if (ox + bw <= x0 || ox >= x1 || oy + bh <= y0 || oy >= y1) continue;
            int tile = a2 & 0x3FF, prio = (a2 >> 10) & 3, pal = a2 >> 12;
            bool hf = !(rot & 1) && (a1 & 0x1000), vf = !(rot & 1) && (a1 & 0x2000);
            int m = (a1 >> 9) & 31;   // an affine sprite's matrix: the 4 OAM entries' affineParams from 4 * m
            int pa = (int16_t) oam[(4 * m) * 4 + 3], pb = (int16_t) oam[(4 * m + 1) * 4 + 3];
            int pc = (int16_t) oam[(4 * m + 2) * 4 + 3], pd = (int16_t) oam[(4 * m + 3) * 4 + 3];
            for (int yy = 0; yy < bh; yy++) {
                int Y = oy + yy, J = Y - y0;
                if (Y < 0 || Y >= PK_WIDE_H || Y < y0 || Y >= y1) continue;
                if (snaps > 1 && lineOamOf[Y] != snap) continue;   // another OAM drew this line
                useLine(Y);
                for (int xx = 0; xx < bw; xx++) {
                    int X = ox + xx - x0;
                    int wl = X < 0 || X >= w || takenBuf[J][X] ? 0 : windowLayers(ox + xx, Y);
                    if (!(wl & 0x10)) continue;
                    int px, py;
                    if (rot & 1) {   // mGBA's: texel = (matrix * (box pixel - box centre) + sprite centre) >> 8
                        px = (pa * (xx - bw / 2) + pb * (yy - bh / 2) + (sw << 7)) >> 8;
                        py = (pc * (xx - bw / 2) + pd * (yy - bh / 2) + (sh << 7)) >> 8;
                        if (px < 0 || px >= sw || py < 0 || py >= sh) continue;
                    } else {
                        px = hf ? sw - 1 - xx : xx;
                        py = vf ? sh - 1 - yy : yy;
                    }
                    int t = tile + (py / 8) * (sw / 8) + px / 8;
                    uint8_t v = vram[0x10000 + ((uint32_t) (t * 32 + (py & 7) * 4 + (px & 7) / 2) & 0x7FFF)];
                    int ci = px & 1 ? v >> 4 : v & 15;
                    if (!ci) continue;
                    takenBuf[J][X] = 1;
                    if (prio > prioBuf[J][X]) continue;
                    uint32_t c = color(P[256 + pal * 16 + ci], alpha);
                    dst[J * stride + X] = !(wl & 0x20) ? c : mode == 1 ? blend(c, below[J][X], layerBuf[J][X]) : brightness(c, 4);
                    holeBuf[J][X] = 0;
                }
            }
        }
    }
    useLive();
}

// --- menu screens ------------------------------------------------------------------------------------
//
// A menu screen (party, bag, Pokédex, summary...) sits on a background layer - stripes, a frame, a pattern - with its
// windows and text on the layers in front. Past the frame's edges only that bottom layer goes on, drawn as a wider
// PPU would (its own scroll, wrapping around its 256 / 512 px), so the screen continues its own backdrop instead of
// repeating any of its text.

static int menuBg = -1;   // the background layer the last menu check picked

/** A menu-like screen: tiled BGs (mode 0, or mode 1's two text ones) - picks the one at the back. */
static bool menuScreen(void) {
    uint16_t disp = io(0);
    int mode = disp & 7, best = -1, bestPrio = -1;
    if (mode > 1) return false;
    for (int b = 0; b < (mode == 0 ? 4 : 2); b++) {
        if (!(disp & (0x100 << b))) continue;
        int prio = io(0x08 + 2 * b) & 3;
        if (prio >= bestPrio) { bestPrio = prio; best = b; }   // ties: the higher BG is drawn behind
    }
    menuBg = best;
    return best >= 0;
}

/** The back layer's pixel at screen (sx, y) - inside the frame - as the PPU draws it: colour (BLDY applied), false if
 * transparent or windowed out. */
static bool menuPixel(int sx, int y, uint32_t alpha, uint32_t* out) {
    const uint8_t* vram = (const uint8_t*) G->video.vram;
    int b = menuBg;
    useLine(y);
    uint16_t disp = io(0), cnt = io(0x08 + 2 * b);
    int wl = windowLayers(sx, y);
    if (!(disp & (0x100 << b)) || !(wl & (1 << b))) return false;
    uint32_t chr = ((cnt >> 2) & 3) * 0x4000u, scr = ((cnt >> 8) & 31) * 0x800u;
    int size = cnt >> 14, bw = size & 1 ? 512 : 256, bh = size & 2 ? 512 : 256;
    int mx = (sx + (io(0x10 + 4 * b) & 0x1FF)) & (bw - 1), my = (y + (io(0x12 + 4 * b) & 0x1FF)) & (bh - 1);
    uint32_t block = (uint32_t) ((mx >> 8) + (bw == 512 ? 2 : 1) * (my >> 8));
    uint32_t off = scr + block * 0x800u + 2 * (uint32_t) (((my >> 3) & 31) * 32 + ((mx >> 3) & 31));
    uint16_t e = off + 1 < 0x10000 ? (uint16_t) le16(vram + off) : 0;
    int px = mx & 7, py = my & 7, ci, palBase = 0;
    if (e & 0x400) px = 7 - px;
    if (e & 0x800) py = 7 - py;
    if (cnt & 0x80) {
        uint32_t t = chr + (e & 0x3FFu) * 64 + (uint32_t) (py * 8 + px);
        ci = t < 0x10000 ? vram[t] : 0;
    } else {
        uint32_t t = chr + (e & 0x3FFu) * 32 + (uint32_t) (py * 4 + px / 2);
        ci = t < 0x10000 ? (px & 1 ? vram[t] >> 4 : vram[t] & 15) : 0;
        palBase = (e >> 12) * 16;
    }
    if (!ci) return false;
    uint32_t c = color(P[palBase + ci], alpha);
    *out = wl & 0x20 ? brightness(c, b) : c;
    return true;
}

/** How many pixels the back layer repeats every, at screen row y, along `from` (a column just inside the frame's
 * edge) going inwards by `dir`: the smallest of 8..32 whose shifted copy matches the next 32 pixels - else 0. */
static int menuPeriod(int y, int from, int dir, uint32_t alpha) {
    uint32_t px[64];
    bool has[64];
    for (int k = 0; k < 64; k++) has[k] = menuPixel(from + dir * k, y, alpha, &px[k]);
    for (int p = 8; p <= 32; p += 8) {
        bool same = true;
        for (int k = 0; k < 32 && same; k++) same = has[k] == has[k + p] && (!has[k] || px[k] == px[k + p]);
        if (same) return p;
    }
    return 0;
}

/** The menu's back layer over [x0, x1) x [y0, y1), past the frame continued from its own edges: each row repeats the
 * pattern found along its edge (menuPeriod), rows above / below the frame its top / bottom row's. No sprites (cursors,
 * icons stay put); transparent = the backdrop colour - unless the back layer is transparent at that row's edge and
 * the [frame] shows something else there (a layer in front covers it): then a hole, and the frame's edge pixel goes
 * on. SoulGold's party screen leaves its back layer bare at the edges, under a panel, and its backdrop is the
 * palette's never-seen magenta: the strips were bright pink (GitHub #116). */
static void drawMenuRegion(int x0, int y0, int x1, int y1, bool skipFrame, uint32_t* dst, int stride, uint32_t alpha, const uint32_t* frame) {
    int w = x1 - x0, h = y1 - y0;
    static bool coveredL[PK_WIDE_H], coveredR[PK_WIDE_H];
    for (int y = 0; y < PK_WIDE_H; y++) {
        uint32_t c;
        coveredL[y] = frame && (frame[y * PK_WIDE_W] & 0xFC000000u) != 0xFC000000u && !menuPixel(0, y, alpha, &c);
        coveredR[y] = frame && (frame[y * PK_WIDE_W + PK_WIDE_W - 1] & 0xFC000000u) != 0xFC000000u && !menuPixel(PK_WIDE_W - 1, y, alpha, &c);
    }
    // Per row and side: the pattern's width, and the row it's taken from - a row whose edge doesn't repeat (a button,
    // a panel's corner reaching it) borrows the nearest one that does, so the backdrop goes on behind it; with none
    // anywhere, the edge tile column itself goes on.
    static int periodL[PK_WIDE_H], periodR[PK_WIDE_H], rowL[PK_WIDE_H], rowR[PK_WIDE_H];
    for (int y = 0; y < PK_WIDE_H; y++) {
        periodL[y] = menuPeriod(y, 0, 1, alpha);
        periodR[y] = menuPeriod(y, PK_WIDE_W - 1, -1, alpha);
    }
    for (int side = 0; side < 2; side++) {
        int* per = side ? periodR : periodL;
        int* row = side ? rowR : rowL;
        for (int y = 0; y < PK_WIDE_H; y++) {
            row[y] = y;
            if (per[y]) continue;
            for (int d = 1; d < PK_WIDE_H; d++) {
                if (y - d >= 0 && per[y - d]) { row[y] = y - d; break; }
                if (y + d < PK_WIDE_H && per[y + d]) { row[y] = y + d; break; }
            }
        }
        for (int y = 0; y < PK_WIDE_H; y++) {
            int p = per[row[y]];
            per[y] = per[y] ? per[y] : p ? -p : -8;   // negative: borrowed (kept apart from the rows found)
        }
    }
    for (int j = 0; j < h; j++) {
        int y = y0 + j, fy = clampi(y, 0, PK_WIDE_H - 1);
        for (int x = 0; x < w; x++) {
            int sx = x0 + x;
            if (skipFrame && onFrame(sx, y)) {
                holeBuf[j][x] = 0;
                continue;
            }
            int fx = sx, ry = fy;
            if (sx < 0) {                                                       // the left edge's pattern
                int pl = abs(periodL[fy]);
                ry = rowL[fy];
                fx = ((sx % pl) + pl) % pl;
            } else if (sx >= PK_WIDE_W) {
                int pr = abs(periodR[fy]);
                ry = rowR[fy];
                fx = PK_WIDE_W - 1 - (((PK_WIDE_W - 1 - sx) % pr) + pr) % pr;
            }
            uint32_t c;
            bool hole = false;
            if (!menuPixel(fx, ry, alpha, &c)) {
                hole = sx < 0 ? coveredL[fy] : sx >= PK_WIDE_W && coveredR[fy];
                useLine(ry);
                c = color(P[0], alpha);
                if (windowLayers(fx, ry) & 0x20) c = brightness(c, 5);
            }
            dst[j * stride + x] = c;
            holeBuf[j][x] = hole;
        }
    }
    useLive();
}

// --- ambient edges -----------------------------------------------------------------------------------

// Off the map (title, menus, battles, transitions) the window around the frame is a glow spread from the game's
// own edge pixels: each pixel takes its colour from the nearest edge band, blurred over more of that edge the
// further out it is and dimmed towards the window's edge, so it follows whatever the game shows (its flames, a
// battle's sky, a flash, a fade) without inventing anything. Past a corner the farther-off side wins.

static int32_t edgeAccH[2][PK_WIDE_H][3];   // the left / right edge band's colour per row, x16, smoothed over frames
static int32_t edgeAccV[2][PK_WIDE_W][3];   // the top / bottom band's per column
static int32_t preH[2][PK_WIDE_H + 1][3], preV[2][PK_WIDE_W + 1][3];   // their running sums (a blur is a difference)
static bool edgeAccOk;

static void ambientPrepare(const uint32_t* frame) {
    for (int side = 0; side < 2; side++) {
        int x0 = side ? PK_WIDE_W - AMBIENT_BAND : 0, y0 = side ? PK_WIDE_H - AMBIENT_BAND : 0;
        for (int c = 0; c < 3; c++) preH[side][0][c] = preV[side][0][c] = 0;
        for (int y = 0; y < PK_WIDE_H; y++) {
            int32_t sum[3] = { 0, 0, 0 };
            for (int x = x0; x < x0 + AMBIENT_BAND; x++) {
                uint32_t v = frame[y * PK_WIDE_W + x];
                for (int c = 0; c < 3; c++) sum[c] += (v >> (8 * c)) & 0xFF;
            }
            for (int c = 0; c < 3; c++) {
                int32_t now = sum[c] * 16 / AMBIENT_BAND;
                // Half the step each frame: text and sprites passing the edge don't flicker the glow.
                edgeAccH[side][y][c] = edgeAccOk ? (edgeAccH[side][y][c] + now) / 2 : now;
                preH[side][y + 1][c] = preH[side][y][c] + edgeAccH[side][y][c];
            }
        }
        for (int x = 0; x < PK_WIDE_W; x++) {
            int32_t sum[3] = { 0, 0, 0 };
            for (int y = y0; y < y0 + AMBIENT_BAND; y++) {
                uint32_t v = frame[y * PK_WIDE_W + x];
                for (int c = 0; c < 3; c++) sum[c] += (v >> (8 * c)) & 0xFF;
            }
            for (int c = 0; c < 3; c++) {
                int32_t now = sum[c] * 16 / AMBIENT_BAND;
                edgeAccV[side][x][c] = edgeAccOk ? (edgeAccV[side][x][c] + now) / 2 : now;
                preV[side][x + 1][c] = preV[side][x][c] + edgeAccV[side][x][c];
            }
        }
    }
    edgeAccOk = true;
}

/** The glow at screen pixel (X, Y), off the frame; `reach` is how far the window goes past each edge (left, right,
 * top, bottom), where it's dimmest. */
static uint32_t glowAt(const uint32_t* frame, int X, int Y, const int reach[4], uint32_t alpha) {
    int ox = X < 0 ? -X : X >= PK_WIDE_W ? X - PK_WIDE_W + 1 : 0;
    int oy = Y < 0 ? -Y : Y >= PK_WIDE_H ? Y - PK_WIDE_H + 1 : 0;
    bool across = ox >= oy;   // from the left / right edge, else the top / bottom one
    int side = across ? X >= PK_WIDE_W : Y >= PK_WIDE_H;
    int d = across ? ox : oy, len = across ? PK_WIDE_H : PK_WIDE_W;
    int at = across ? clampi(Y, 0, PK_WIDE_H - 1) : clampi(X, 0, PK_WIDE_W - 1);
    int32_t (*pre)[3] = across ? preH[side] : preV[side];
    uint32_t exact = across ? frame[at * PK_WIDE_W + (side ? PK_WIDE_W - 1 : 0)] : frame[(side ? PK_WIDE_H - 1 : 0) * PK_WIDE_W + at];
    int far = reach[across ? side : 2 + side];
    int r = 2 + d * 3 / 4;                                            // the glow spreads as it goes out
    int bright = 256 - 136 * (d - 1) / (far > 1 ? far - 1 : 1);       // 1.0 at the game's edge -> ~0.47 at the window's
    if (bright < 120) bright = 120;
    int seam = d >= 4 ? 256 : d * 64;                                 // the first pixels lean on the edge itself
    int lo = at - r < 0 ? 0 : at - r, hi = at + r >= len ? len - 1 : at + r;
    uint32_t v = 0;
    for (int c = 0; c < 3; c++) {
        int32_t blur = (pre[hi + 1][c] - pre[lo][c]) / (hi - lo + 1) / 16;
        int32_t e = (exact >> (8 * c)) & 0xFF;
        int32_t mixd = (e * (256 - seam) + blur * seam) >> 8;
        v |= (uint32_t) ((mixd * bright) >> 8) << (8 * c);
    }
    return v | alpha;
}

