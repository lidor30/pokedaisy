/** a * (256 - t) + b * t, per channel, keeping a's alpha. */
static inline uint32_t lerp(uint32_t a, uint32_t b, int t) {
    if (t <= 0) return a;
    if (t >= 256) return b;
    uint32_t rb = (((a & 0xFF00FF) * (uint32_t) (256 - t) + (b & 0xFF00FF) * (uint32_t) t) >> 8) & 0xFF00FF;
    uint32_t g = (((a & 0x00FF00) * (uint32_t) (256 - t) + (b & 0x00FF00) * (uint32_t) t) >> 8) & 0x00FF00;
    return (a & 0xFF000000) | rb | g;
}

/** BG0 - the field's text boxes, menus, signs - shows something: enough of its visible tilemap isn't tile 0. The
 * map-name popup (the top-left corner, every game) doesn't count: leaving a building, the game locks the controls
 * for the walk out of the door while the popup is up, and the camera pulled in and back out for it. */
static bool textUp(void) {
    if (!(io(0) & 0x100)) return false;
    const uint8_t* vram = (const uint8_t*) G->video.vram;
    uint32_t scr = ((io(0x08) >> 8) & 31) * 0x800u;
    int hofs = io(0x10) & 0x1FF, vofs = io(0x12) & 0x1FF, n = 0;
    for (int ty = 0; ty < 20; ty++)
        for (int tx = 0; tx < 30; tx++) {
            if (ty < POPUP_ROWS && tx < POPUP_COLS) continue;
            int rx = ((hofs >> 3) + tx) & 31, ry = ((vofs >> 3) + ty) & 31;
            if (le16(vram + scr + 2 * (uint32_t) (ry * 32 + rx)) & 0x3FF) n++;
        }
    return n >= 8;
}

/** BG0 is what the frame shows at screen pixel (x, y): it's opaque there and the frame has its colour (BG0 can sit
 * opaque under the map: Unbound's START menu leaves tiles beside its middle windows). Line y's registers. */
static bool barEdge(int x, int y) {
    int pal, ci = (windowLayers(x, y) & 1) ? bgPixel(0, x, y, &pal) : 0;
    if (!ci) return false;
    uint16_t c = P[pal + ci];
    uint32_t v = (uint32_t) (c & 0x1F) << 3 | (uint32_t) ((c >> 5) & 0x1F) << 11 | (uint32_t) ((c >> 10) & 0x1F) << 19;
    v |= (v >> 5) & 0x070707;   // mColorFrom555, untinted: DAY AND NIGHT leaves the text windows' palettes alone
    uint32_t f = realFrame[y * PK_WIDE_W + x] & 0xFFFFFF;
    return f == v || f == (color(c, 0) & 0xFFFFFF);
}

/** BG0 is opaque all the way across line y (a bar, not two windows that each touch an edge: Unbound's POKéDEX label
 * and clock reach the screen's edges with the field between them). Sprites over it (the bar's icons) don't matter. */
static bool bg0Across(int y) {
    for (int x = 1; x < PK_WIDE_W - 1; x++) {
        int pal;
        if (!(windowLayers(x, y) & 1) || !bgPixel(0, x, y, &pal)) return false;
    }
    return true;
}

/** BG0 shows at both of the screen's edges on line y and is opaque all the way across it. Line y's registers. */
static bool barRow(int y) {
    useLine(y);
    return (io(0) & 0x100) && barEdge(0, y) && barEdge(PK_WIDE_W - 1, y) && bg0Across(y);
}

/** The rows a full-width bar on BG0 crosses (Unbound's START menu, its quest bar over the field and its icons under it;
 * FireRed's quest-log recap bars): [barRow]s running from the screen's top or bottom edge. Past the edges they're holes -
 * the row's own edge pixel goes on, as a battle's text box band does - instead of the map going on beside the bar.
 * Unbound's text box is BG0 across too, its white outline at both edges, but the field shows under it (rows 116-157):
 * carried out, it was a white box behind every message (1.4.0, a Discord report), so a band that touches neither edge
 * keeps the map beside it. Line by line, as the PPU drew them. */
static void barRows(uint8_t bars[PK_WIDE_H]) {
    memset(bars, 0, PK_WIDE_H);
    int top = 0;
    while (top < PK_WIDE_H && barRow(top)) bars[top++] = 1;
    for (int y = PK_WIDE_H - 1; y >= top && barRow(y); y--) bars[y] = 1;
    useLive();
}

static void markBarRows(int x0, int y0, int w, int h) {
    uint8_t bars[PK_WIDE_H];
    barRows(bars);
    for (int j = 0; j < h; j++) {
        int y = y0 + j;
        if (y < 0 || y >= PK_WIDE_H || !bars[y]) continue;
        for (int x = 0; x < w; x++)
            if (!onFrame(x0 + x, y)) holeBuf[j][x] = 1;
    }
}

/** A screen effect is up: lines drawn with their own scroll or windows (a transition's slices, wedges, bands). */
static bool effectsUp(void) {
    const uint16_t* a = lineRegs(0);
    for (int y = 1; y < PK_WIDE_H; y++) {
        const uint16_t* l = lineRegs(y);
        for (int r = 0x14; r <= 0x46; r += 2)
            if ((r <= 0x16 || r >= 0x40) && l[r >> 1] != a[r >> 1]) return true;
    }
    return false;
}

// --- transitions -------------------------------------------------------------------------------------
//
// pk_wide_scene() says what the game is doing a frame early, so ZOOM's pull-in to 1x is one motion started before
// anything shows, not a reaction to what's already on screen:
//   BATTLE_START  battle_transition.c's sTransitionData (PK_WIDE_TRANSITION_PTR) is set: the flashes are starting,
//                 the wipe follows ~50 frames later
//   TEXT          the field with its controls locked and a text box or a line effect up (a sign, a script)
//   OVERLAY       a picture on BG0 over most of the field (FireRed's map preview on entering a forest or a cave;
//                 FireRed-engine games only, never during a battle transition):
//                 the map around it - the frame's own and the margins' - is dimmed while it's up (overlayDim),
//                 so the picture reads as a card over the world instead of a box with the map going on around it
//   OFF           not the map at all: a battle, a menu screen, the title

#define OVERLAY_TILES 300         // BG0 tiles (of 600) a picture over the field covers (a text box ~160 at most)
#define OVERLAY_ROWS 11           // ... in at least this many full-width tile rows (28+ of 30) one after another: a
                                  // picture is one block 14 rows tall; the START menu's SAVE screen covers as many
                                  // tiles, in windows that never make more than a text box's 6 full rows (Gen 3 draws
                                  // window text as unique tiles, so counting distinct tiles can't tell them apart), and
                                  // Unbound's full-screen START menu makes 11 - but as two bars, 6 rows over the field
                                  // and 5 under it, which dimmed the field while the menu was open (GitHub #86)
#define FADE_LEVEL 12             // a frame whose every sampled pixel is this dark (or as near white) is a fade
#define OVERLAY_STEP 24           // the dim's ramp per frame (0..256)
#define OVERLAY_DIM 150           // how dark the map around the picture goes, of 256

static bool transitionRunning(void) {
    return C[PK_WIDE_TRANSITION_PTR] && r32((uint32_t) C[PK_WIDE_TRANSITION_PTR]) != 0;
}

/** FireRed's quest log replaying the field ("Previously on your quest", after Continue): scripted scenes with text
 * boxes coming and going, which zoomed the camera in and out - it stays close until the field is the player's. */
static bool questLogPlaying(void) {
    if (!C[PK_WIDE_QUEST_LOG]) return false;
    uint8_t s = r8((uint32_t) C[PK_WIDE_QUEST_LOG]);
    return s == 2 || s == 3;   // QL_STATE_PLAYBACK / QL_STATE_PLAYBACK_LAST
}

/** BG0 covers most of the screen with a picture: one unbroken block of full-width rows (windows, even a save
 * screen's, never make more than a text box's few; Unbound's START menu bars, top and bottom, aren't one block). */
static bool overlayUp(void) {
    if (!(io(0) & 0x100)) return false;
    const uint8_t* vram = (const uint8_t*) G->video.vram;
    uint32_t scr = ((io(0x08) >> 8) & 31) * 0x800u;
    int hofs = io(0x10) & 0x1FF, vofs = io(0x12) & 0x1FF, n = 0, run = 0, block = 0;
    for (int ty = 0; ty < 20; ty++) {
        int row = 0;
        for (int tx = 0; tx < 30; tx++) {
            int rx = ((hofs >> 3) + tx) & 31, ry = ((vofs >> 3) + ty) & 31;
            if (le16(vram + scr + 2 * (uint32_t) (ry * 32 + rx)) & 0x3FF) row++;
        }
        n += row;
        run = row >= 28 ? run + 1 : 0;
        if (run > block) block = run;
    }
    return n >= OVERLAY_TILES && block >= OVERLAY_ROWS;
}

/** The frame is all black or all white: a fade between two maps (a door, a connection building), not a screen of
 * its own - the camera holds its zoom through it. */
static bool fadedFrame(const uint32_t* frame) {
    int lo = 255, hi = 0;
    for (int y = 2; y < PK_WIDE_H; y += 6)
        for (int x = 3; x < PK_WIDE_W; x += 6) {
            uint32_t p = frame[y * PK_WIDE_W + x];
            int r = p & 0xFF, g = (p >> 8) & 0xFF, b = (p >> 16) & 0xFF;
            int mx = r > g ? (r > b ? r : b) : (g > b ? g : b), mn = r < g ? (r < b ? r : b) : (g < b ? g : b);
            if (mx > hi) hi = mx;
            if (mn < lo) lo = mn;
            if (hi > FADE_LEVEL && lo < 255 - FADE_LEVEL) return false;
        }
    return hi <= FADE_LEVEL || lo >= 255 - FADE_LEVEL;
}

/** mGBA's layer tag on an output pixel (its 32-bit renderer keeps them in the top byte): BG `index`
 * (FLAG_IS_BACKGROUND + index), never the backdrop (every flag set) nor a blended / covered pixel (flags stripped). */
static inline bool fromBg(uint32_t v, int index) {
    return (v & 0x38000000u) == (0x08000000u | (uint32_t) index << 28) && (v & 0xFC000000u) != 0xFC000000u;
}

/** How much of the picture is showing, 0..256: its alpha blend as the game fades it out (map_preview_screen.c: BG0
 * the first target, BLDALPHA from 16 to 0), else all of it. The dim around it follows this, so the map comes back
 * exactly as the card goes - it used to stay dark until the card's tiles were gone, then brighten in a step. */
static int overlayStrength(void) {
    uint16_t cnt = io(0x50);
    if (((cnt >> 6) & 3) == 1 && (cnt & 1)) {
        int eva = io(0x52) & 0x1F;
        return (eva > 16 ? 16 : eva) * 16;
    }
    return 256;
}

static inline uint32_t dimmed(uint32_t c, int dim) {
    int k = 256 - (dim * OVERLAY_DIM >> 8);
    uint32_t rb = (((c & 0xFF00FF) * (uint32_t) k) >> 8) & 0xFF00FF, g = (((c & 0x00FF00) * (uint32_t) k) >> 8) & 0x00FF00;
    return (c & 0xFF000000) | rb | g;
}

