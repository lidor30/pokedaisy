static inline uint32_t color(uint16_t c, uint32_t alpha) {
    // DAY AND NIGHT: the margins (the map and its people, from palette RAM) tinted as the renderer's frame is.
    if (tintShown) c = tint555(c);
    uint32_t v = (uint32_t) (c & 0x1F) << 3 | (uint32_t) ((c >> 5) & 0x1F) << 11 | (uint32_t) ((c >> 10) & 0x1F) << 19;
    return v | ((v >> 5) & 0x070707) | alpha;   // mGBA's mColorFrom555
}

// Blending and brightness work on the widened 8-bit colour, as mGBA's 32-bit renderer does
// (mColorMix5Bit, _brighten, _darken), so they round the same way.

/** BLDCNT's brightness effects (fades to white / black done with BLDY rather than the palette), for
 * a pixel whose top layer is `layer` (0-3 BG, 4 OBJ, 5 backdrop) if BLDCNT makes it a first target. */
static uint32_t brightness(uint32_t c, int layer) {
    uint16_t cnt = io(0x50);
    int mode = (cnt >> 6) & 3;
    if (mode < 2 || !(cnt & (1 << layer))) return c;
    unsigned y = io(0x54) & 0x1F;
    if (y > 16) y = 16;
    // As mGBA's 32-bit renderer (_brighten / _darken): each channel in place, so a darkened green or blue also loses
    // the fraction from the channel below (white darkened by 1 is 240, 239, 239).
    uint32_t out = c & 0xFF000000;
    for (int sh = 0; sh <= 16; sh += 8) {
        uint32_t m = 0xFFu << sh, a = c & m;
        out |= (mode == 2 ? a + ((m - a) * y) / 16 : a - (a * y) / 16) & m;
    }
    return out;
}

static struct Foreign* connForeign[MAX_CONNS];   // this frame's: each connection's own tilesets (NULL = the current map's)

/** One map pixel: its colour (BGR555; the backdrop's when nothing's there), the priority of the BG it's
 * from (4 = backdrop) and that BG (5 = backdrop: BLDCNT's bit numbering). */
// The 64 pixels of one 8x8 map tile share its metatile, connection and BG entries: found once per tile in a draw
// (foreignFrame counts the draws), not once per pixel.
static struct { uint32_t epoch; int tx, ty, enabled; bool real, ok; const struct Snap* snap; struct Foreign* f; uint16_t e[3]; } tc;

static void loadTile(const struct Snap* s, int mx, int my, int enabled, bool real) {
    int tx = mx >> 3, ty = my >> 3;
#ifndef PK_WIDE_NOCACHE
    if (tc.ok && tc.epoch == foreignFrame && tc.snap == s && tc.tx == tx && tc.ty == ty && tc.enabled == enabled && tc.real == real) return;
#endif
    int conn;
    int mid = blockIn(s, mx >> 4, my >> 4, &conn, real);
    // On the real screen a connected map's strip is drawn as the game draws it: with the current map's tilesets.
    struct Foreign* f = !real && conn >= 0 && conn < MAX_CONNS ? connForeign[conn] : NULL;
    int q = ((my >> 3) & 1) * 2 + ((mx >> 3) & 1);
    for (int i = 0; i < 3; i++) {
        int b = order3[i];
        tc.e[i] = 0;
        if (!(enabled & (1 << b))) continue;
        if (f) syncSplit(s);
        tc.e[i] = f ? metatileIn(&f->t, mid, b)[q] : metatile(s, mid, b)[q];
    }
    tc.epoch = foreignFrame; tc.snap = s; tc.tx = tx; tc.ty = ty; tc.enabled = enabled; tc.real = real; tc.f = f; tc.ok = true;
}

static uint16_t mapPixel(const struct Snap* s, int mx, int my, int enabled, int* prio, int* layer, bool real) {
    const uint8_t* vram = (const uint8_t*) G->video.vram;
    loadTile(s, mx, my, enabled, real);
    struct Foreign* f = tc.f;
    int nt = C[PK_WIDE_PRIMARY_METATILES], np = C[PK_WIDE_PRIMARY_PALS];
    for (int i = 0; i < 3; i++) {
        int b = order3[i];
        if (!(enabled & (1 << b))) continue;
        uint16_t e = tc.e[i];
        int px = mx & 7, py = my & 7;
        if (e & 0x400) px = 7 - px;
        if (e & 0x800) py = 7 - py;
        int tile = e & 0x3FF, pal = e >> 12, ci;
        if (f && (f->ownPrimary || tile >= nt)) {
            uint8_t v = f->tiles[tile * 32 + py * 4 + px / 2];
            ci = px & 1 ? v >> 4 : v & 15;
        } else {
            uint32_t off = bgChar[b] + (uint32_t) tile * 32 + (uint32_t) (py * 4 + px / 2);
            if (off >= 0x10000) continue;            // BG tiles can't reach OBJ VRAM
            ci = px & 1 ? vram[off] >> 4 : vram[off] & 15;
        }
        if (ci) {
            *prio = bgPrio[b];
            *layer = b;
            if (f && (f->ownPrimary || pal >= np)) return f->pal[pal * 16 + ci];
            return P[pal * 16 + ci];
        }
    }
    *prio = 4;
    *layer = 5;
    return P[0];
}

/** Up to 8 map pixels of one tile row at once ([mx, mx + n) on map row my, all in one 8x8 tile): the same answers as n
 * calls of mapPixel, from the tile row's packed bytes. out[k] = colour (BGR555), outPrio[k], outLayer[k]. */
static void mapTileRow(const struct Snap* s, int mx, int my, int n, int enabled, uint16_t* out, uint8_t* outPrio, uint8_t* outLayer) {
    const uint8_t* vram = (const uint8_t*) G->video.vram;
    loadTile(s, mx, my, enabled, false);
    struct Foreign* f = tc.f;
    int nt = C[PK_WIDE_PRIMARY_METATILES], np = C[PK_WIDE_PRIMARY_PALS];
    uint8_t ci[3][8];
    int pal[3];
    bool ownPal[3], have[3];
    for (int i = 0; i < 3; i++) {
        have[i] = false;
        int b = order3[i];
        if (!(enabled & (1 << b))) continue;
        uint16_t e = tc.e[i];
        int py = my & 7;
        if (e & 0x800) py = 7 - py;
        int tile = e & 0x3FF;
        const uint8_t* src;
        pal[i] = e >> 12;
        if (f && (f->ownPrimary || tile >= nt)) {
            src = f->tiles + tile * 32 + py * 4;
        } else {
            uint32_t off = bgChar[b] + (uint32_t) tile * 32 + (uint32_t) (py * 4);
            if (off + 4 > 0x10000 + 0) { if (off >= 0x10000) continue; }   // BG tiles can't reach OBJ VRAM
            src = vram + off;
        }
        ownPal[i] = f && (f->ownPrimary || pal[i] >= np);
        for (int k = 0; k < 8; k++) {
            int px = e & 0x400 ? 7 - k : k;
            uint8_t v = src[px / 2];
            ci[i][k] = px & 1 ? v >> 4 : v & 15;
        }
        have[i] = true;
    }
    for (int k = 0; k < n; k++) {
        int px = (mx + k) & 7;
        int i = 0;
        for (; i < 3; i++)
            if (have[i] && ci[i][px]) break;
        if (i < 3) {
            int b = order3[i];
            outPrio[k] = (uint8_t) bgPrio[b];
            outLayer[k] = (uint8_t) b;
            out[k] = ownPal[i] ? f->pal[pal[i] * 16 + ci[i][px]] : P[pal[i] * 16 + ci[i][px]];
        } else {
            outPrio[k] = 4;
            outLayer[k] = 5;
            out[k] = P[0];
        }
    }
}

/** [mapPixel] for n pixels of one row off the real screen, inside one 8x8 cell of the map: what the cell holds is looked up
 * once, not per pixel (EXPAND's margins are most of a 3DS's frame at 1x). The same answers, pixel for pixel. */
static void mapSpan(const struct Snap* s, int mx, int my, int n, int enabled, uint16_t* out, uint8_t* prios, uint8_t* layers) {
    const uint8_t* vram = (const uint8_t*) G->video.vram;
    int conn;
    int mid = blockIn(s, mx >> 4, my >> 4, &conn, false);
    struct Foreign* f = conn >= 0 && conn < MAX_CONNS ? connForeign[conn] : NULL;
    int q = ((my >> 3) & 1) * 2 + ((mx >> 3) & 1);
    int nt = C[PK_WIDE_PRIMARY_METATILES], np = C[PK_WIDE_PRIMARY_PALS];
    const uint8_t* rows[3];
    const uint16_t* pals[3];
    bool flip[3];
    int count = 0, bgs[3];
    for (int i = 0; i < 3; i++) {
        int b = order3[i];
        if (!(enabled & (1 << b))) continue;
        if (f) syncSplit(s);
        uint16_t e = f ? metatileIn(&f->t, mid, b)[q] : metatile(s, mid, b)[q];
        int py = my & 7;
        if (e & 0x800) py = 7 - py;
        int tile = e & 0x3FF, pal = e >> 12;
        const uint8_t* row;
        if (f && (f->ownPrimary || tile >= nt)) {
            row = &f->tiles[tile * 32 + py * 4];
        } else {
            uint32_t off = bgChar[b] + (uint32_t) tile * 32 + (uint32_t) (py * 4);
            if (off >= 0x10000) continue;            // BG tiles can't reach OBJ VRAM
            row = vram + off;
        }
        rows[count] = row;
        pals[count] = f && (f->ownPrimary || pal >= np) ? &f->pal[pal * 16] : &P[pal * 16];
        flip[count] = e & 0x400;
        bgs[count++] = b;
    }
    for (int k = 0; k < n; k++) {
        int x = (mx + k) & 7, i;
        for (i = 0; i < count; i++) {
            int px = flip[i] ? 7 - x : x, v = rows[i][px / 2], ci = px & 1 ? v >> 4 : v & 15;
            if (ci) {
                out[k] = pals[i][ci];
                prios[k] = (uint8_t) bgPrio[bgs[i]];
                layers[k] = (uint8_t) bgs[i];
                break;
            }
        }
        if (i == count) {
            out[k] = P[0];
            prios[k] = 4;
            layers[k] = 5;
        }
    }
}

struct Piece {
    int x, y, w, h, tile, prio, pal, mode;   // mode: OAM objMode (0 normal, 1 semi-transparent, 2 OBJ window)
    bool hflip, vflip;
    bool copy;                               // a weather sprite repeated past the screen: margins only
    int rot, mat;                            // OAM affine mode (0 none, 1 affine, 3 double-size) and matrix
};

// Weather (field_weather.h's GFXTAG_*: 0x1201 horizontal fog .. 0x1206 rain) is screen-space sprites the
// game lays only over its own 240 px: fog, ash and sandstorm as 64 px grids, rain and bubbles at random.
// Repeated 256 px either way (a multiple of the grids' 64) they go on seamlessly into the margins.
#define WEATHER_TAG_FIRST 0x1201
#define WEATHER_TAG_LAST 0x1206
#define WEATHER_REPEAT 256

static const uint8_t OBJ_DIMS[3][4][2] = {
    { { 8, 8 }, { 16, 16 }, { 32, 32 }, { 64, 64 } },
    { { 16, 8 }, { 32, 8 }, { 32, 16 }, { 64, 32 } },
    { { 8, 16 }, { 8, 32 }, { 16, 32 }, { 32, 64 } },
};

static struct Piece pieces[2][256];
static int npieces[2] = { 0, 0 };
static int shown = 0;   // pieces[shown]: the list drawn (the last one the frame's OAM agreed with)

/** Where the PPU shows a piece the game put in OAM at a position past its 9 / 8 bits: y wraps at 256 (once
 * the box reaches past 255 it shows at the top), x as a signed 9-bit value - used wherever that puts it on
 * the real screen (Unbound's snow lives in world space and relies on it). */
static void hardwareWrap(struct Piece* p) {
    int bw = p->rot == 3 ? 2 * p->w : p->w, bh = p->rot == 3 ? 2 * p->h : p->h;
    int y = p->y & 0xFF;
    if (y + bh > 255) y -= 256;
    if (y != p->y && y < PK_WIDE_H && y + bh > 0) p->y = y;   // past the screen (ZOOM shows it) it stays where it is
    int x = ((p->x + 256) & 0x1FF) - 256;
    if (x != p->x && x < PK_WIDE_W && x + bw > 0) p->x = x;
}

/** The OAM entries the game would build if the screen were wider, front first (BuildOamBuffer +
 * AddSubspritesToOamBuffer), positions kept as s16 instead of OAM's 9 / 8 bits. */
static int buildPieces(const struct Snap* s, struct Piece* out) {
    int nspr = C[PK_WIDE_MAX_SPRITES];
    bool offscreen[SPRITES_CAP] = { false };   // sprites the game hid only for being off screen
    for (int i = 0; i < 16; i++) {
        const uint8_t* oe = s->objects + 0x24 * i;
        uint32_t flags = (uint32_t) oe[0] | (uint32_t) oe[1] << 8;
        int id = C[PK_WIDE_SPRITE_ID_OFF] >= 0 && C[PK_WIDE_SPRITE_ID_OFF] < 0x24 ? oe[C[PK_WIDE_SPRITE_ID_OFF]] : 0xFF;
        if ((flags & 1) && (flags & (1 << 14)) && !(flags & (1 << 13)) && id < nspr) offscreen[id] = true;
    }
    int n = 0;
    for (int k = 0; k < nspr && n < 256; k++) {
        int id = s->order[k];
        if (id >= nspr) continue;
        const uint8_t* sp = s->sprites + 0x44 * id;
        uint32_t fl = le16(sp + 0x3E);
        if (!(fl & 1) || ((fl & 4) && !offscreen[id])) continue;   // !inUse, or invisible for its own reasons
        uint32_t a0 = le16(sp), a1 = le16(sp + 2), a2 = le16(sp + 4);
        int rot = (a0 >> 8) & 3;                                    // 2: hidden
        if (rot == 2) continue;
        int cvx = (signed char) sp[0x28], cvy = (signed char) sp[0x29];
        int x = (int16_t) le16(sp + 0x20) + (int16_t) le16(sp + 0x24) + cvx;
        int y = (int16_t) le16(sp + 0x22) + (int16_t) le16(sp + 0x26) + cvy;
        bool world = fl & 2;   // coordOffsetEnabled: a sprite in the world, kept where the world puts it
        bool revealed = offscreen[id] && (fl & 4);   // hidden by the game, shown by us: never wrapped
        if (world) {
            x += s->coordX;
            y += s->coordY;
        } else {        // a sprite in screen space (weather, effects) relies on OAM's 9 / 8-bit wrap
            int bh = (a0 >> 14) <= 2 ? OBJ_DIMS[a0 >> 14][a1 >> 14][1] : 8;
            x &= 0x1FF;
            if (x >= 512 - 128) x -= 512;
            y &= 0xFF;
            if (y > 255 - bh) y -= 256;    // reaching past 255 shows at the top, as the hardware wraps it
        }
        struct Piece base = { .tile = (int) (a2 & 0x3FF), .prio = (int) ((a2 >> 10) & 3), .pal = (int) (a2 >> 12),
                              .mode = (int) ((a0 >> 10) & 3), .hflip = !(rot & 1) && (a1 & 0x1000), .vflip = !(rot & 1) && (a1 & 0x2000),
                              .copy = false, .rot = rot, .mat = (int) ((a1 >> 9) & 31) };
        uint32_t tables = (uint32_t) sp[0x18] | (uint32_t) sp[0x19] << 8 | (uint32_t) sp[0x1A] << 16 | (uint32_t) sp[0x1B] << 24;
        int mode = sp[0x42] >> 6;
        uint32_t table = tables && mode ? tables + 8 * (uint32_t) (sp[0x42] & 0x3F) : 0;
        uint32_t subs = table ? r32(table + 4) : 0;
        if (!subs) {
            if ((a0 >> 14) > 2) continue;
            out[n] = base;
            out[n].x = x;
            out[n].y = y;
            out[n].w = OBJ_DIMS[a0 >> 14][a1 >> 14][0];
            out[n].h = OBJ_DIMS[a0 >> 14][a1 >> 14][1];
            if (world && !revealed) hardwareWrap(&out[n]);
            n++;
            uint32_t tmpl = (uint32_t) sp[0x14] | (uint32_t) sp[0x15] << 8 | (uint32_t) sp[0x16] << 16 | (uint32_t) sp[0x17] << 24;
            uint32_t tag = !(fl & 2) && tmpl ? r16(tmpl) : 0;   // struct SpriteTemplate starts with tileTag
            for (int k2 = -1; k2 <= 1 && tag >= WEATHER_TAG_FIRST && tag <= WEATHER_TAG_LAST; k2 += 2) {
                if (n >= 256) break;
                out[n] = out[n - 1 - (k2 > 0)];
                out[n].x = x + k2 * WEATHER_REPEAT;
                out[n].copy = true;
                n++;
            }
            continue;
        }
        int bx = x - cvx, by = y - cvy;
        int cnt = (int) r8(table);
        int ss = C[PK_WIDE_SUBSPRITE_SIZE];   // 4: s8 x, y; 8 (Ruby / Sapphire): u16 x, y, read as s16, + 2 bytes' padding
        for (int j = 0; j < cnt && n < 256; j++) {
            const uint8_t* sub = mem(subs + (uint32_t) (ss * j), (uint32_t) ss);
            if (!sub) break;
            uint32_t v = le16(sub + ss / 2);   // the shape / size / tile / priority bits
            if ((v & 3) > 2) continue;
            int w = OBJ_DIMS[v & 3][(v >> 2) & 3][0], h = OBJ_DIMS[v & 3][(v >> 2) & 3][1];
            int sx = ss == 8 ? (int16_t) le16(sub) : (signed char) sub[0];
            int sy = ss == 8 ? (int16_t) le16(sub + 2) : (signed char) sub[1];
            if (base.hflip) sx = -(sx + w);
            if (base.vflip) sy = -(sy + h);
            out[n] = base;
            out[n].x = bx + sx;
            out[n].y = by + sy;
            out[n].w = w;
            out[n].h = h;
            out[n].tile = base.tile + (int) ((v >> 4) & 0x3FF);
            if (mode != 2) out[n].prio = (int) (v >> 14);
            if (world && !revealed) hardwareWrap(&out[n]);
            n++;
        }
    }
    return n;
}

/** Every piece that lands on the real screen is in the OAM the frame was drawn with. */
static bool oamAgrees(const struct Piece* p, int n) {
    for (int i = 0; i < n; i++) {
        if (p[i].copy) continue;
        if (p[i].x + p[i].w <= 0 || p[i].x >= 240 || p[i].y + p[i].h <= 0 || p[i].y >= 160) continue;
        bool found = false;
        for (int k = 0; k < 128 && !found; k++) {
            uint16_t a0 = G->video.oam.raw[k * 4], a1 = G->video.oam.raw[k * 4 + 1], a2 = G->video.oam.raw[k * 4 + 2];
            if (((a0 >> 8) & 3) == 2) continue;
            found = (a1 & 0x1FF) == (p[i].x & 0x1FF) && (a0 & 0xFF) == (p[i].y & 0xFF) && (int) (a2 & 0x3FF) == p[i].tile;
        }
        if (!found) return false;
    }
    return true;
}

// The rebuild of the screen rectangle [x0, x1) x [y0, y1) (screen coordinates, past the frame's edges allowed) into
// dst (stride `stride`, (x0, y0) at dst[0]). With `skipFrame`, pixels on the real frame are left alone: it's shown there.
#define BUF_W PK_WIDE_MAX_VIEW_W
#define BUF_H PK_WIDE_MAX_VIEW_H
static uint8_t prioBuf[BUF_H][BUF_W];
static uint8_t layerBuf[BUF_H][BUF_W];
static uint32_t below[BUF_H][BUF_W];   // the BG pixel's colour, for blending
static uint8_t takenBuf[BUF_H][BUF_W];

/** A semi-transparent sprite over a BG: BLDALPHA's EVA / EVB, if BLDCNT has that BG as a second target. */
static uint32_t blend(uint32_t top, uint32_t bottom, int layer) {
    uint16_t cnt = io(0x50);
    if (!(cnt & (0x100 << layer))) return top;
    unsigned eva = io(0x52) & 0x1F, evb = (io(0x52) >> 8) & 0x1F;
    if (eva > 16) eva = 16;
    if (evb > 16) evb = 16;
    uint32_t out = top & 0xFF000000;
    for (int sh = 0; sh <= 16; sh += 8) {
        unsigned c = (((top >> sh) & 0xFF) * eva + ((bottom >> sh) & 0xFF) * evb) / 16;
        out |= (uint32_t) (c > 0xFF ? 0xFF : c) << sh;
    }
    return out;
}

