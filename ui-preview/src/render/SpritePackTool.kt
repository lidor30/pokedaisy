/**
 * SPRITE PACK's maker (docs/DEVELOPMENT.md's "Sprite packs"), with the app's own scan code: every ROM under a folder goes
 * through PLAYER LOOK's scan and MonArt's readers, as the app does when it meets one, into a folder of its own.
 *
 * - `pack <roms> <out.zip>`: what they left, checked by [SpritePack.collect] (only graphics the app accepts), zipped with
 *   the manifest - `make sprite-pack`. The pack is the player's own: the repo never holds one.
 * - `sigs <roms> <MonArtSigsGen.kt>`: the follower Pokémon's CRCs, every ROM's (each version of a hack may draw a species
 *   apart) - `make sprite-pack-sigs`. CRCs only.
 */
fun main(args: Array<String>) {
    val mode = args.getOrNull(0)
    val roms = args.getOrNull(1)?.takeIf { it.isNotBlank() }?.let(::File)
    val out = args.getOrNull(2)?.takeIf { it.isNotBlank() }?.let(::File)
    require(mode == "pack" || mode == "sigs") { "usage: pack|sigs <roms folder> <out>" }
    require(roms != null && roms.isDirectory) { "-Proms=<folder of your ROMs> is required (got $roms)" }
    require(out != null) { "-Pout=<file> is required" }

    val work = Files.createTempDirectory("sprite-pack").toFile()
    try {
        val files = roms.walkTopDown().filter { it.isFile && it.extension.equals("gba", true) }.sortedBy { it.name }.toList()
        val perRom = ArrayList<File>()
        for ((i, f) in files.withIndex()) {
            val bytes = f.readBytes()
            val code = if (bytes.size >= 0xB0) String(bytes, 0xAC, 4, Charsets.ISO_8859_1) else ""
            val look = PlayerLook.engineFor(code) != null
            if (!look && !MonArt.find(bytes)) continue
            // A folder per ROM: keep() writes only what's missing, and `sigs` wants every version's files.
            val dir = File(work, "rom$i").apply { mkdirs() }
            val filesDir = dir.toOkioPath()
            val scan = if (look) PlayerLook.scan(bytes, TextBlob.entries) else null
            val heroes = scan?.let { LookArt.keep(filesDir, it) }.orEmpty()
            val text = scan?.let { TextArt.keep(filesDir, it) }.orEmpty()
            val mons = MonArt.keep(filesDir, bytes)
            if (heroes.isNotEmpty() || text.isNotEmpty() || mons > 0) {
                println("${f.name}: heroes $heroes, text looks $text, $mons Pokémon")
                perRom += dir
            }
        }
        if (mode == "sigs") writeSigs(perRom, out) else writePack(perRom, out)
    } finally {
        work.deleteRecursively()
    }
}

private fun lookDir(romDir: File) = File(LookArt.dir(romDir.toOkioPath()).toString())

/** Every ROM's follower files, as CRCs per source. */
private fun writeSigs(perRom: List<File>, out: File) {
    val bySource = MonArt.Source.entries.associateWith { sortedSetOf<Long>() }
    for (dir in perRom) for (s in MonArt.Source.entries) {
        val d = File(lookDir(dir), "mon/${s.tag}")
        for (f in d.listFiles().orEmpty()) {
            val n = f.name.removeSuffix(".bin").toIntOrNull() ?: continue
            val b = f.readBytes()
            if (b.size != MonArt.SIZE) continue
            val crc = CRC32().apply { update(b) }.value
            bySource.getValue(s) += (n.toLong() shl 32) or crc
        }
    }
    val names = mapOf(
        MonArt.Source.HEART_AND_SOUL to "HEART_AND_SOUL", MonArt.Source.ROWE to "ROWE",
        MonArt.Source.RECHARGED_YELLOW to "RECHARGED_YELLOW", MonArt.Source.SEAGLASS to "SEAGLASS",
    )
    val text = buildString {
        append("package com.pokedaisy.app.companion.data\n\n")
        append("// GENERATED by `make sprite-pack-sigs` (ui-preview's SpritePackTool) from the follower hacks' own ROMs - CRCs only,\n")
        append("// no art. Do not hand-edit; rerun it after changing what MonArt.keep writes.\n\n")
        append("/** The [MonArt] files a SPRITE PACK may carry: per source, (national number shl 32) or CRC32 of the file, sorted. */\n")
        append("object MonArtSigs {\n")
        for (s in MonArt.Source.entries) {
            val v = bySource.getValue(s)
            append("    private val ${names.getValue(s)} = longArrayOf(")
            if (v.isNotEmpty()) {
                append("\n")
                v.chunked(4).forEach { row -> append("        ").append(row.joinToString(", ") { "0x%011XL".format(it) }).append(",\n") }
                append("    ")
            }
            append(")\n")
        }
        append(
            """
            |
            |    private fun table(source: MonArt.Source) = when (source) {
            |        MonArt.Source.HEART_AND_SOUL -> HEART_AND_SOUL
            |        MonArt.Source.ROWE -> ROWE
            |        MonArt.Source.RECHARGED_YELLOW -> RECHARGED_YELLOW
            |        MonArt.Source.SEAGLASS -> SEAGLASS
            |    }
            |
            |    fun knows(source: MonArt.Source, national: Int, crc: Long): Boolean {
            |        // By hand: LongArray.binarySearch is the JVM's alone (this file builds for iOS too).
            |        val t = table(source)
            |        val key = (national.toLong() shl 32) or (crc and 0xFFFFFFFFL)
            |        var lo = 0
            |        var hi = t.size - 1
            |        while (lo <= hi) {
            |            val mid = (lo + hi) ushr 1
            |            when {
            |                t[mid] < key -> lo = mid + 1
            |                t[mid] > key -> hi = mid - 1
            |                else -> return true
            |            }
            |        }
            |        return false
            |    }
            |}
            |""".trimMargin(),
        )
    }
    out.writeText(text)
    println("wrote $out: " + bySource.entries.joinToString { "${it.key.tag} ${it.value.size}" })
}

/** What every ROM left, the first ROM's copy of each path (they're the same graphic: [SpritePack.collect] checks it). */
private fun writePack(perRom: List<File>, out: File) {
    val files = sortedMapOf<String, ByteArray>()
    var found = 0
    for (dir in perRom) {
        val all = lookDir(dir).walkTopDown().count { it.isFile && it.extension == "bin" }
        val accepted = SpritePack.collect(dir.toOkioPath())
        found += all
        accepted.forEach { (p, b) -> files.putIfAbsent(p, b) }
        if (accepted.size < all) println("${dir.name}: ${all - accepted.size} of $all files aren't ones the app knows (left out)")
    }
    require(files.isNotEmpty()) { "no makeover graphics in those ROMs" }
    val made = LocalDate.now().toString()
    out.absoluteFile.parentFile?.mkdirs()
    ZipOutputStream(out.outputStream().buffered()).use { z ->
        fun put(name: String, b: ByteArray) {
            z.putNextEntry(ZipEntry(name))
            z.write(b)
            z.closeEntry()
        }
        put(SpritePack.MANIFEST, SpritePack.manifest(files, made).toByteArray())
        put("README.txt", readme(files, made).toByteArray())
        files.forEach { (p, b) -> put(p, b) }
    }
    val heroes = LookChar.entries.filter { c -> files.keys.any { it.startsWith("${c.name.lowercase()}/") } }
    val text = TextLook.STYLES.filter { s -> files.keys.any { it.startsWith("text/${s.name.lowercase()}/") } }
    val mons = files.keys.count { it.startsWith("mon/") }
    println("wrote $out (${out.length() / 1024} KB): heroes $heroes, text looks $text, $mons Pokémon files")
    if (mons == 0 && files.isNotEmpty()) println("no Pokémon: run `make sprite-pack-sigs` first (and rebuild the app with its table)")
}

private fun readme(files: Map<String, ByteArray>, made: String) = """
    PokeDaisy sprite pack ($made)

    The makeover's graphics (PLAYER LOOK's heroes, TEXT LOOK, the FOLLOWER's Pokemon), made from ROMs by
    `make sprite-pack`. Load it in PokeDaisy: the library's TOOLS > SPRITE PACK, then pick this file.

    ${files.size} files; ${SpritePack.MANIFEST} lists them with their sizes and CRC32s. The app takes only graphics it
    already knows, so a changed file is left out.
""".trimIndent() + "\n"
