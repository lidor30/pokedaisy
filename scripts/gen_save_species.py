#!/usr/bin/env python3
"""Generates companion/data/save/SaveSpeciesGen.kt - what the save editor's Pokémon page needs about each
species and isn't in a save: base stats (for a party Pokémon's stats), its two abilities (the ability bit picks
one), its gender ratio (the personality's low byte against it) and the abilities' English names. Read from the
pret decomps under $DECOMPS (pokeruby's base_stats.h, pokeemerald / pokefirered's species_info.h), which agree
on every value here - the script checks that, so one table serves Ruby / Sapphire, Emerald and FireRed / LeafGreen.

Numbers and names only, like SaveTablesGen.kt.

Usage: scripts/gen_save_species.py
"""
import os
import re
import sys

from decomps import decomp

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "../app/src/main/kotlin/com/pokedaisy/app/companion/data/save/SaveSpeciesGen.kt")
NUM_SPECIES = 412   # SPECIES_EGG: species 0..411
STATS = ["baseHP", "baseAttack", "baseDefense", "baseSpeed", "baseSpAttack", "baseSpDefense"]


def strip_comments(text):
    return re.sub(r"//[^\n]*|/\*.*?\*/", "", text, flags=re.S)


def read(game, rel):
    with open(decomp(game, rel), encoding="latin-1") as f:
        return strip_comments(f.read())


def defines(game, rel, prefix):
    return {k: int(v, 0) for k, v in re.findall(r"#define (" + prefix + r"\w+)\s+(\d+|0x[0-9A-Fa-f]+)\b", read(game, rel))}


def gender(v):
    v = v.strip()
    if v == "MON_GENDERLESS":
        return 255
    if v == "MON_FEMALE":
        return 254
    if v == "MON_MALE":
        return 0
    m = re.fullmatch(r"PERCENT_FEMALE\(([\d.]+)\)", v)
    if m:
        return min(254, int(float(m.group(1)) * 255 / 100))
    return int(v, 0)


def species_table(game, rel, table):
    text = read(game, rel)
    species = defines(game, "include/constants/species.h", "SPECIES_")
    abilities = defines(game, "include/constants/abilities.h", "ABILITY_")
    macros = {}
    for name, body in re.findall(r"#define (\w+)\s*\\\n((?:.*\\\n)+)", text):
        macros[name] = body.replace("\\\n", "\n")
    body = text[text.index(table):]
    out = {}
    for name, entry in re.findall(r"\[(SPECIES_\w+)\]\s*=\s*(\{0\}|\{.*?\n    \}|\w+)", body, flags=re.S):
        entry = macros.get(entry.strip(), entry)
        fields = dict(re.findall(r"\.(\w+)\s*=\s*([^,\n{}]+|\{[^}]*\})", entry))
        if not fields:
            continue
        stats = [int(fields[s]) for s in STATS]
        if "abilities" in fields:
            ab = [a.strip() for a in fields["abilities"].strip("{} ").split(",") if a.strip()]
        else:
            ab = [fields["ability1"].strip(), fields["ability2"].strip()]
        out[species[name]] = (stats, [abilities[a] for a in ab], gender(fields["genderRatio"]))
    return out


def ability_names(game):
    text = read(game, "src/data/text/abilities.h")
    abilities = defines(game, "include/constants/abilities.h", "ABILITY_")
    names = dict(re.findall(r"\[(ABILITY_\w+)\]\s*=\s*_\(\"([^\"]*)\"\)", text))
    out = ["" for _ in range(max(abilities.values()) + 1)]
    for k, v in names.items():
        out[abilities[k]] = v
    return out


def main():
    e = species_table("pokeemerald", "src/data/pokemon/species_info.h", "gSpeciesInfo")
    for game, rel, table in [("pokefirered", "src/data/pokemon/species_info.h", "gSpeciesInfo"),
                             ("pokeruby", "src/data/pokemon/base_stats.h", "gBaseStats")]:
        other = species_table(game, rel, table)
        for s in range(1, NUM_SPECIES):
            if other.get(s) != e.get(s):
                sys.exit(f"{game} species {s}: {other.get(s)} != pokeemerald's {e.get(s)}")
    names = ability_names("pokeemerald")
    if names != ability_names("pokefirered"):
        sys.exit("ability names differ between pokeemerald and pokefirered")

    def rows(values, per=24):
        return "\n".join("    " + ", ".join(str(v) for v in values[i:i + per]) + "," for i in range(0, len(values), per))

    stats, abil, ratios = [], [], []
    for s in range(NUM_SPECIES):
        st, ab, g = e.get(s, ([0] * 6, [0, 0], 255))
        stats += st
        abil += (ab + [0, 0])[:2]
        ratios.append(g)
    with open(OUT, "w") as f:
        f.write("package com.pokedaisy.app.companion.data.save\n\n")
        f.write("// GENERATED by scripts/gen_save_species.py from pokeemerald (checked equal in pokefirered / pokeruby) - do not hand-edit.\n")
        f.write("// Species are internal indexes (Treecko = 277).\n\n")
        f.write("/** gSpeciesInfo's base stats, six a species in the game's order: HP, Attack, Defense, Speed, Sp. Atk, Sp. Def. */\n")
        f.write("internal val saveBaseStats = intArrayOf(\n" + rows(stats) + "\n)\n\n")
        f.write("/** gSpeciesInfo.abilities: two a species (the second 0 when it has one). */\n")
        f.write("internal val saveAbilities = intArrayOf(\n" + rows(abil) + "\n)\n\n")
        f.write("/** gSpeciesInfo.genderRatio: 0 always male, 254 always female, 255 genderless, else the female threshold. */\n")
        f.write("internal val saveGenderRatios = intArrayOf(\n" + rows(ratios) + "\n)\n\n")
        f.write("/** gAbilityNames (English), by ability id. */\n")
        f.write("internal val saveAbilityNames = arrayOf(\n" + "\n".join(
            "    " + ", ".join('"' + n + '"' for n in names[i:i + 8]) + "," for i in range(0, len(names), 8)) + "\n)\n")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
