#!/usr/bin/env python3
"""The Gen 3 games' move data beyond type and power - accuracy, PP, the battle
effect, its chance, priority - for the companion's move advice (PARTY > CAN
LEARN, a TM's ABLE / NOT ABLE row on ITEMS).

Read from the pinned pokefirered's src/data/battle_moves.h (gBattleMoves).
FireRed / LeafGreen / Ruby / Sapphire / Emerald share the table: pokeemerald's
differs only in flags and NATURE POWER's accuracy (0 here, 95 there - it calls
another move, so the advice never reads it).

Also the EFFECT_* names by id (`vanillaMoveEffectNames`), for a randomized ROM's gBattleMoves read
from the ROM (RandomizedRetail.kt): its effects are the same ids, their names these.

Usage: DECOMPS=... scripts/gen_move_stats.py   (re-run only if the pin changes)
"""
import os
import re

from decomps import decomp

HERE = os.path.dirname(os.path.abspath(__file__))
KOTLIN = os.path.join(HERE, "../app/src/main/kotlin/com/pokedaisy/app/companion/data/MoveStatsGen.kt")


def defines(path, prefix):
    out = {}
    for m in re.finditer(r"^#define\s+(%s\w*)\s+(\d+)\s*$" % prefix, open(path).read(), re.M):
        out[m.group(1)] = int(m.group(2))
    return out


def main():
    root = decomp("pokefirered")
    moves = defines(os.path.join(root, "include/constants/moves.h"), "MOVE_")
    count = defines(os.path.join(root, "include/constants/moves.h"), "MOVES_COUNT")["MOVES_COUNT"]
    src = open(os.path.join(root, "src/data/battle_moves.h")).read()
    table = {}
    for m in re.finditer(r"\[(MOVE_\w+)\]\s*=\s*\{(.*?)\}", src, re.S):
        fields = dict(re.findall(r"\.(\w+)\s*=\s*([^,\n]+)", m.group(2)))
        table[moves[m.group(1)]] = fields
    assert sorted(table) == list(range(count)), "every move id once"

    effects = {}
    for m in re.finditer(r"^#define\s+EFFECT_(\w+)\s+(\d+)\b",
                         open(os.path.join(root, "include/constants/battle_move_effects.h")).read(), re.M):
        effects[int(m.group(2))] = m.group(1)
    assert sorted(effects) == list(range(len(effects))), "every effect id once"

    lines = []
    for i in range(count):
        f = table[i]
        effect = f["effect"].strip()
        assert effect.startswith("EFFECT_"), effect
        lines.append('    MoveStats("%s", %d, %d, %d, %d),' % (
            effect[len("EFFECT_"):], int(f["accuracy"]), int(f["pp"]),
            int(f["secondaryEffectChance"]), int(f["priority"])))
    with open(KOTLIN, "w") as out:
        out.write("package com.pokedaisy.app.companion.data\n\n")
        out.write("// GENERATED by scripts/gen_move_stats.py from the pinned pokefirered's gBattleMoves -\n")
        out.write("// do not hand-edit; rerun the script instead. Index = move id (FireRed / LeafGreen /\n")
        out.write("// Ruby / Sapphire / Emerald share it).\n\n")
        out.write("internal val vanillaMoveStats: List<MoveStats> = listOf(\n")
        out.write("\n".join(lines) + "\n)\n")
        out.write("\n// gBattleMoves' effect ids -> the names above (include/constants/battle_move_effects.h).\n")
        out.write("internal val vanillaMoveEffectNames: List<String> = listOf(\n")
        out.write("".join('    "%s",\n' % effects[i] for i in range(len(effects))) + ")\n")
    print("wrote %d moves to %s" % (count, os.path.relpath(KOTLIN)))


if __name__ == "__main__":
    main()
