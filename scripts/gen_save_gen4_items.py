#!/usr/bin/env python3
"""Generates companion/data/save/SaveGen4ItemsGen.kt, what the SAVE EDITOR needs to put an item taken from a Pokémon
back in its bag pocket:
- HeartGold / SoulSilver: item id -> item data record (pret/pokeheartgold's src/item.c, sItemNarcIds' ITEMNARC_PARAM);
  the editor reads the record's fieldPocket from the player's own cart (a/0/1/7: its records aren't in item id order).
- Platinum: each item id's field pocket (pret/pokeplatinum's res/items/data/*.json, ids from generated/items.txt).
Numbers only.

Usage: scripts/gen_save_gen4_items.py   ($DECOMPS/pokeheartgold, $DECOMPS/pokeplatinum)
"""
import json
import os
import re

from decomps import decomp

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "../app/src/main/kotlin/com/pokedaisy/app/companion/data/save/SaveGen4ItemsGen.kt")


def main():
    with open(decomp("pokeheartgold", "src/item.c")) as f:
        text = f.read()
    body = text[text.index("sItemNarcIds[ITEMS_COUNT][4] = {"):]
    body = body[:body.index("\n};")]
    rows = re.findall(r"\{\s*NARC_item_data_(\d+)_bin\s*,", body)
    ids = [int(r) for r in rows]
    if len(ids) < 500:
        raise SystemExit(f"only {len(ids)} items found")
    lines = ["    " + ", ".join(str(v) for v in ids[i:i + 24]) + "," for i in range(0, len(ids), 24)]
    pockets = {"POCKET_ITEMS": 0, "POCKET_MEDICINE": 1, "POCKET_BALLS": 2, "POCKET_TMHMS": 3, "POCKET_BERRIES": 4,
               "POCKET_MAIL": 5, "POCKET_BATTLE_ITEMS": 6, "POCKET_KEY_ITEMS": 7}
    with open(decomp("pokeplatinum", "generated/items.txt")) as f:
        names = [l.strip() for l in f if l.strip() and l.strip() != "MAX_ITEMS"]
    pt = []
    for n in names:
        path = decomp("pokeplatinum", "res/items/data", n.replace("ITEM_", "").lower() + ".json")
        pt.append(pockets[json.load(open(path))["fieldPocket"]] if os.path.exists(path) else -1)
    pt_lines = ["    " + ", ".join(str(v) for v in pt[i:i + 24]) + "," for i in range(0, len(pt), 24)]
    with open(OUT, "w") as f:
        f.write("package com.pokedaisy.app.companion.data.save\n\n")
        f.write("// GENERATED by scripts/gen_save_gen4_items.py from pokeheartgold's src/item.c - do not hand-edit.\n\n")
        f.write("/** HeartGold / SoulSilver: each item id's record in the cart's item data (sItemNarcIds' ITEMNARC_PARAM). */\n")
        f.write("internal val gen4ItemDataIndexHeartGold = intArrayOf(\n" + "\n".join(lines) + "\n)\n\n")
        f.write("/** Platinum: each item id's field pocket (POCKET_ITEMS 0 .. POCKET_KEY_ITEMS 7; -1 an unused id). */\n")
        f.write("internal val gen4ItemPocketsPlatinum = intArrayOf(\n" + "\n".join(pt_lines) + "\n)\n")
    print(f"wrote {OUT}: {len(ids)} items")


if __name__ == "__main__":
    main()
