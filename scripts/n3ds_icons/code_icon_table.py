#!/usr/bin/env python3
"""The party icon table a 3DS Pokemon game keeps in its own code (ExeFS `.code`), as a TSV - and that TSV as Kotlin.

Every Gen 6 / 7 cart has one 16-byte record per species (0..721 / 0..802) in its code (Gen 6's `.code` is BLZ-compressed,
exheader +0xD bit 0; Gen 7's is plain; the code loads at 0x100000):
  +0 u16 icon (form 0, male or genderless)   +2 u16 female icon (form 0; +0's when there's none)
  +4 u32 pointer to a u16 icon per form, form 0 first   +0xC u16 form count
  +8 u32 pointer to the mirrored icons per form          +0xE u16 mirrored count
It's found by its first icons at a 16-byte stride. On Pokemon X it agrees with the table read off the game's own party
screen (pokemon_x_icons.tsv) on 1481 of 1486 rows: four are Genesect's drives (identical pictures), one Keldeo's forms.
Icons themselves stay in the player's cart (n3ds/Gen6Icons.kt).

    python3 -I code_icon_table.py tsv CART.3ds SPECIES_MAX FIRST_ICONS... > game_icons_code.tsv
    python3 -I code_icon_table.py kotlin game_icons_code.tsv ObjectName "what it is" > ObjectName.kt

FIRST_ICONS: species 1..10's icons, e.g. ORAS 1 2 4 5 6 9 10 11 13 14, Sun / Moon 1 2 3 5 6 7 10 11 12 14.
"""
import re, struct, sys


def blz(data):
    data = bytearray(data)
    enc_off = struct.unpack_from('<I', data, len(data) - 8)[0]
    inc = struct.unpack_from('<I', data, len(data) - 4)[0]
    top, bot = enc_off >> 24, enc_off & 0xFFFFFF
    out = bytearray(len(data) + inc)
    out[:len(data)] = data
    src, dst, end = len(data) - top, len(out), len(data) - bot
    while src > end:
        src -= 1
        flags = data[src]
        for _ in range(8):
            if src <= end:
                break
            if flags & 0x80:
                src -= 2
                v = data[src] | data[src + 1] << 8
                n, disp = (v >> 12) + 3, (v & 0xFFF) + 3
                for _ in range(n):
                    dst -= 1
                    out[dst] = out[dst + disp]
            else:
                src -= 1
                dst -= 1
                out[dst] = data[src]
            flags <<= 1
    return bytes(out)


def code(cart):
    with open(cart, 'rb') as f:
        h = f.read(0x200)
        part0 = struct.unpack_from('<I', h, 0x120)[0] * 0x200
        f.seek(part0)
        n = f.read(0x200)
        exefs = part0 + struct.unpack_from('<I', n, 0x1A0)[0] * 0x200
        f.seek(part0 + 0x200)
        compressed = f.read(0x400)[0xD] & 1
        f.seek(exefs)
        eh = f.read(0x200)
        for i in range(10):
            name = eh[i * 16:i * 16 + 8].rstrip(b'\0')
            off, size = struct.unpack_from('<II', eh, i * 16 + 8)
            if name == b'.code':
                f.seek(exefs + 0x200 + off)
                c = f.read(size)
                return blz(c) if compressed else c
    sys.exit('no .code')


def tsv(cart, species_max, first):
    d = code(cart)
    pat = re.compile(b'.{14}'.join(re.escape(struct.pack('<H', v)) for v in first), re.S)
    hits = [m.start() for m in pat.finditer(d)]
    if len(hits) != 1:
        sys.exit('table found %d times' % len(hits))
    base = hits[0] - 16

    def lst(ptr, n):
        return list(struct.unpack_from('<%dH' % n, d, ptr - 0x100000)) if ptr and n else []

    print('species\tform\tfemale\ticon_index\tmirrored_icon')
    for sp in range(1, species_max + 1):
        a, b, fp, ap, fn, an = struct.unpack_from('<HHIIHH', d, base + 16 * sp)
        forms, mirrored = lst(fp, fn), lst(ap, an)
        for f in range(max(1, len(forms))):
            mir = mirrored[f] if f < len(mirrored) else ''
            print('%d\t%d\t0\t%d\t%s' % (sp, f, forms[f] if f and forms else a, mir))
            if f == 0 and b != a:
                print('%d\t%d\t1\t%d\t%s' % (sp, f, b, mir))


def kotlin(path, name, what):
    plain, female, forms = {}, {}, {}
    for line in open(path):
        a = line.rstrip('\n').split('\t')
        if a[0] == 'species':
            continue
        s, f, fem, k = int(a[0]), int(a[1]), int(a[2]), int(a[3])
        if f == 0 and not fem:
            plain[s] = k
        elif f == 0:
            female[s] = k
        else:
            forms[(s, f)] = k
    top = max(plain)
    w = print
    w('package com.pokedaisy.app.n3ds')
    w('')
    w('// Generated by scripts/n3ds_icons/code_icon_table.py from the game\'s own code (docs/3DS_GAMES_PLAN.md). Do not edit.')
    w('')
    w('/** Which icon of %s\'s icon archive ([Gen6Icons]) the game draws for a species, form and gender. */' % what)
    w('object %s {' % name)
    w('    /** Each species\' icon (form 0, male or its only gender), by species 0..%d. */' % top)
    w('    private val PLAIN = intArrayOf(')
    vals = [plain.get(s, 0) for s in range(top + 1)]
    for i in range(0, len(vals), 20):
        w('        ' + ', '.join(str(v) for v in vals[i:i + 20]) + ',')
    w('    )')
    w('')
    w('    /** Species whose females have an icon of their own. */')
    w('    private val FEMALE = mapOf(' + ', '.join('%d to %d' % kv for kv in sorted(female.items())) + ')')
    w('')
    w('    /** Forms with an icon of their own: species shl 8 or form. */')
    w('    private val FORMS = mapOf(')
    items = ['%d to %d' % ((s << 8) | f, k) for (s, f), k in sorted(forms.items()) if k != plain.get(s)]
    for i in range(0, len(items), 8):
        w('        ' + ', '.join(items[i:i + 8]) + ',')
    w('    )')
    w('')
    w('    /** The icon\'s index for [species] in [form]; null for a species past the table. */')
    w('    fun index(species: Int, form: Int, female: Boolean): Int? {')
    w('        if (species <= 0 || species >= PLAIN.size) return null')
    w('        if (form > 0) FORMS[(species shl 8) or form]?.let { return it }')
    w('        if (female) FEMALE[species]?.let { return it }')
    w('        return PLAIN[species]')
    w('    }')
    w('}')


if __name__ == '__main__':
    if sys.argv[1] == 'tsv':
        tsv(sys.argv[2], int(sys.argv[3]), [int(x) for x in sys.argv[4:]])
    else:
        kotlin(sys.argv[2], sys.argv[3], sys.argv[4])
