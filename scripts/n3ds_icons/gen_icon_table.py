#!/usr/bin/env python3
"""Pokemon X / Y's party icon table (n3ds/Gen6IconTable.kt) from a run of read_icons.py: which entry of the cart's
icon archive (RomFS a/0/9/3) the game's own party screen draws for each species, form and gender.

    python3 scripts/n3ds_icons/gen_icon_table.py scripts/n3ds_icons/pokemon_x_icons.tsv > app/src/main/kotlin/com/pokedaisy/app/n3ds/Gen6IconTable.kt

The TSV's lines: species, form, gender (m / f / n), icon index, match error, runner-up error, runner-up index. Only
numbers go into the table: the pictures stay in the player's cart (Gen6Icons rebuilds them).
"""
import sys

def main(path):
    rows = {}
    for line in open(path):
        a = line.rstrip('\n').split('\t')
        s, f, g, k, e, e2 = int(a[0]), int(a[1]), a[2], int(a[3]), float(a[4]), float(a[5])
        # The slots' own background shows through an icon's soft edges, so a few points of error are normal (the
        # worst, ~12, still well apart from the runner-up or a copy of the same picture: Zygarde's two).
        if e > 15:
            sys.exit('species %d form %d %s matched badly (%.1f): read it again' % (s, f, g, e))
        rows[(s, f, g)] = k
    plain, female, forms = [0] * 722, {}, {}
    for s in range(1, 722):
        base = rows.get((s, 0, 'm')) or rows.get((s, 0, 'n')) or rows.get((s, 0, 'f'))
        if base is None: sys.exit('species %d missing' % s)
        plain[s] = base
        fem = rows.get((s, 0, 'f'))
        if fem is not None and fem != base: female[s] = fem
    for (s, f, g), k in sorted(rows.items()):
        if f > 0 and k != plain[s]: forms[(s, f)] = k
    out = []
    w = out.append
    w('package com.pokedaisy.app.n3ds')
    w('')
    w('// Generated by scripts/n3ds_icons/gen_icon_table.py from the game\'s own party screen (docs/3DS_GAMES_PLAN.md). Do not edit.')
    w('')
    w('/** Which icon of Pokemon X / Y\'s icon archive ([Gen6Icons]) the game draws for a species, form and gender. */')
    w('object Gen6IconTable {')
    w('    /** Each species\' icon (form 0, male or its only gender), by species 0..721. */')
    w('    private val PLAIN = intArrayOf(')
    for i in range(0, 722, 20):
        w('        ' + ', '.join(str(v) for v in plain[i:i + 20]) + ',')
    w('    )')
    w('')
    w('    /** Species whose females have an icon of their own. */')
    w('    private val FEMALE = mapOf(' + ', '.join('%d to %d' % kv for kv in sorted(female.items())) + ')')
    w('')
    w('    /** Forms with an icon of their own: species shl 8 or form. */')
    w('    private val FORMS = mapOf(')
    items = ['%d to %d' % ((s << 8) | f, k) for (s, f), k in sorted(forms.items())]
    for i in range(0, len(items), 8):
        w('        ' + ', '.join(items[i:i + 8]) + ',')
    w('    )')
    w('')
    w('    /** The icon\'s index for [species] in [form]; null for a species past the table. */')
    w('    fun index(species: Int, form: Int, female: Boolean): Int? {')
    w('        if (species <= 0 || species >= PLAIN.size) return null')
    w('        if (form > 0) FORMS[(species shl 8) or form]?.let { return it }')
    w('        if (female) FEMALE[species]?.let { return it }')
    w('        return PLAIN[species]')
    w('    }')
    w('}')
    print('\n'.join(out))

if __name__ == '__main__':
    main(sys.argv[1])
