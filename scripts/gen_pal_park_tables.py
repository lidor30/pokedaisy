#!/usr/bin/env python3
"""Generates companion/data/save/PalParkTablesGen.kt: what the SAVE EDITOR's PAL PARK needs to bring a GBA Pokémon into
HeartGold / SoulSilver / Platinum the way the DS games' own migration does (pret/pokeplatinum's
src/main_menu/gba_migrator.c, gba_pokemon.c, gba_convert_string.c and src/item.c):
- each Gen 3 item id's Gen 4 id (Item_FromGBAID over res/items/data/*.json's gbaID, ids from generated/items.txt);
- the Gen 3 items a Pokémon can't migrate holding (sInvalidGBAItems), and the HMs it can't know (sGBAHMMoves);
- the species that gained a second ability in Gen 4, which always arrive with their first (sSpeciesWithNewAbilities);
- GBA text bytes -> DS character codes, Japanese and international (sGBACharToDSChars), with the codes that
  GBA_ConvertStringToDS picks by language (space, double quotes).
Numbers only.

Usage: scripts/gen_pal_park_tables.py [--check]   ($DECOMPS/pokeplatinum)
"""
import json
import os
import re
import sys

from decomps import decomp

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "../app/src/main/kotlin/com/pokedaisy/app/companion/data/save/PalParkTablesGen.kt")


def read(*parts):
    with open(decomp("pokeplatinum", *parts), encoding="utf-8") as f:
        return f.read()


def enum_values(text, name):
    """The members of C enum [name] (implicit members count up from the last), as {member: value}."""
    m = re.search(r"enum\s+" + name + r"\s*\{(.*?)\};", text, re.S)
    if not m:
        sys.exit(f"enum {name} not found")
    out, value = {}, -1
    for line in m.group(1).split("\n"):
        line = re.sub(r"//.*", "", line).strip().rstrip(",")
        if not line:
            continue
        if "=" in line:
            k, v = (s.strip() for s in line.split("=", 1))
            value = int(v, 0) if re.fullmatch(r"(0x[0-9A-Fa-f]+|\d+)", v) else out[v]
        else:
            k = line
            value += 1
        out[k] = value
    return out


def array_body(text, decl):
    i = text.index(decl)
    body = text[text.index("{", i) + 1:]
    depth, end = 1, 0
    for end, ch in enumerate(body):
        depth += ch == "{"
        depth -= ch == "}"
        if depth == 0:
            break
    return body[:end]


def ids_file(name):
    names = [l.strip() for l in read("generated", name).split("\n") if l.strip()]
    return {n: i for i, n in enumerate(names)}


def rows(values, per=24):
    return ["    " + ", ".join(str(v) for v in values[i:i + per]) + "," for i in range(0, len(values), per)]


def main():
    gba_items = enum_values(read("include/constants/gba/items.h"), "GbaItem")
    items = ids_file("items.txt")
    # Item_FromGBAID: the first Gen 4 item (by id) whose gbaID is the Gen 3 one; 0 when none is.
    gen3_to_gen4 = [0] * (max(gba_items.values()) + 1)
    for name, gen4 in sorted(items.items(), key=lambda kv: kv[1]):
        path = decomp("pokeplatinum", "res/items/data", name.replace("ITEM_", "").lower() + ".json")
        if gen4 == 0 or not os.path.exists(path):
            continue
        gba = json.load(open(path, encoding="utf-8")).get("gbaID")
        if not gba or gba == "GBA_ITEM_NONE":
            continue
        g3 = gba_items[gba]
        if gen3_to_gen4[g3] == 0:
            gen3_to_gen4[g3] = gen4
    if gen3_to_gen4[gba_items["GBA_ITEM_MASTER_BALL"]] != items["ITEM_MASTER_BALL"]:
        sys.exit("the item map doesn't start where it should")

    migrator = read("src/main_menu/gba_migrator.c")
    invalid = [gba_items[n] for n in re.findall(r"GBA_ITEM_\w+", array_body(migrator, "sInvalidGBAItems[] ="))]
    moves = ids_file("moves.txt")
    hms = [moves[n] for n in re.findall(r"MOVE_\w+", array_body(migrator, "sGBAHMMoves[] ="))]
    if len(hms) != 8:
        sys.exit(f"{len(hms)} HMs")

    species = ids_file("species.txt")
    pokemon = read("src/main_menu/gba_pokemon.c")
    new_abilities = [species[n] for n in re.findall(r"SPECIES_\w+", array_body(pokemon, "sSpeciesWithNewAbilities[] ="))]

    chars = enum_values(read("include/constants/charcode.h"), "CharCode")
    conv = read("src/main_menu/gba_convert_string.c")
    pairs = re.findall(r"\{\s*(CHAR_\w+)\s*,\s*(CHAR_\w+)\s*\}", array_body(conv, "sGBACharToDSChars[][2] ="))
    if len(pairs) < 200:
        sys.exit(f"only {len(pairs)} GBA characters")
    ja = [chars[a] for a, _ in pairs]
    intl = [chars[b] for _, b in pairs]
    named = {k: chars[k] for k in (
        "CHAR_WIDE_SPACE", "CHAR_SPACE", "CHAR_JP_DOUBLE_QUOTE_OPEN", "CHAR_JP_DOUBLE_QUOTE_CLOSE", "CHAR_DOUBLE_QUOTE_OPEN",
        "CHAR_DOUBLE_QUOTE_CLOSE", "CHAR_DOUBLE_PAREN_OPEN", "CHAR_DOUBLE_PAREN_CLOSE", "CHAR_DOUBLE_QUOTE_CLOSE_INVERTED",
        "CHAR_QUESTION", "CHAR_EOS",
    )}

    out = [
        "package com.pokedaisy.app.companion.data.save",
        "",
        "// GENERATED by scripts/gen_pal_park_tables.py from pokeplatinum's GBA migration (gba_migrator.c, gba_pokemon.c,",
        "// gba_convert_string.c, item.c) - do not hand-edit.",
        "",
        "/** Item_FromGBAID: each Gen 3 item id's Gen 4 id (0: none). */",
        "internal val palParkItems = intArrayOf(",
        *rows(gen3_to_gen4),
        ")",
        "",
        "/** sInvalidGBAItems: a Pokémon holding one of these Gen 3 items can't migrate (mail, key items, HMs, unused ids). */",
        "internal val palParkRefusedItems: Set<Int> = setOf(",
        *rows(invalid),
        ")",
        "",
        "/** sGBAHMMoves: a Pokémon that knows one of these can't migrate. */",
        "internal val palParkHms: Set<Int> = setOf(" + ", ".join(str(v) for v in hms) + ")",
        "",
        "/** sSpeciesWithNewAbilities: species that got a second ability in Gen 4 arrive with their first. */",
        "internal val palParkNewAbilitySpecies: Set<Int> = setOf(",
        *rows(new_abilities),
        ")",
        "",
        "/** sGBACharToDSChars: a GBA text byte's DS character code, for Japanese text and for every other language. */",
        "internal val palParkCharsJapanese = intArrayOf(",
        *rows(ja, 16),
        ")",
        "",
        "internal val palParkCharsInternational = intArrayOf(",
        *rows(intl, 16),
        ")",
        "",
        "/** The DS character codes GBA_ConvertStringToDS picks by language. */",
        "internal object PalParkChars {",
        *[f"    const val {k.removeprefix('CHAR_')} = 0x{v:X}" for k, v in named.items()],
        "}",
        "",
    ]
    text = "\n".join(out)
    if "--check" in sys.argv:
        if not os.path.exists(OUT) or open(OUT, encoding="utf-8").read() != text:
            sys.exit(f"{OUT} is stale: rerun scripts/gen_pal_park_tables.py")
        return
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(text)
    print(f"wrote {OUT}: {sum(1 for v in gen3_to_gen4 if v)} items, {len(invalid)} refused, {len(new_abilities)} species, {len(pairs)} characters")


if __name__ == "__main__":
    main()
