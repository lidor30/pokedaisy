#!/usr/bin/env python3
"""Writes the DS language ports' tables from gamedata/nds/ports.toml (see its header).

    python3 scripts/gen_nds_ports.py           # write
    python3 scripts/gen_nds_ports.py --check   # exit 1 if a written file is stale (CI, make check)

Out:
  - app/src/main/cpp/nds/pk_nds_ports_gen.h: PK_NDS_PORTS4 (HeartGold / SoulSilver builds), PK_NDS_PORTS4P (Platinum builds)
    and PK_NDS_PORTS5 (Black / White and their sequels), which pk_nds_field.cpp and pk_nds_call.cpp turn into full tables
    from the base cart's;
  - the app's NdsPortsGen.kt: NDS_PORTS, what the Kotlin side reads (DsPorts.kt builds the configs).
"""
import os
import sys
import tomllib

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
SRC = os.path.join(ROOT, "gamedata", "nds", "ports.toml")
C_OUT = os.path.join(ROOT, "app", "src", "main", "cpp", "nds", "pk_nds_ports_gen.h")
KT_OUT = os.path.join(ROOT, "app", "src", "main", "kotlin", "com", "pokedaisy", "app", "companion", "data", "NdsPortsGen.kt")

# Each base's words, in the C struct's order: (TOML name, C field, required).
GEN4 = [
    ("sFieldSysPtr", "fieldSystemPtr", True), ("gOverlayTemplate_Battle", "battleTemplate", True),
    ("sSoundWork", "soundWork", True), ("sSeqPlayer", "seqPlayer", True), ("sSaveDataPtr", "saveDataPtr", True),
    ("FieldMap_Main", "fieldMapMain", True),
    ("Task_StartMenu", "startMenu", False), ("PartyMenuApp_Init", "partyInit", False),
    ("OptionsApp_Init", "optionsInit", False), ("Pokedex_Init", "dexInit", False),
    ("ScriptJump", "scriptJump", True), ("MessageFormat_New_Custom", "messageFormatNew", True),
    ("String_New", "stringNew", True), ("FieldMove_InitCheckData", "fieldMoveInit", True),
    ("FieldMove_CheckFly", "fieldMoveCheckFly", True), ("SaveArray_Party_Get", "partyGet", True),
    ("Party_GetMonByIndex", "partyGetMon", True), ("sub_02067BF8", "flyNew", True), ("sub_02067C30", "flyTask", True),
    ("FieldSystem_CreateTask", "createTask", True), ("ScriptEnvironment_New", "scriptEnvNew", True),
    ("CreateScriptContext", "createScriptContext", True), ("Task_RunScripts", "taskRunScripts", True),
]
# Platinum's: pk_nds_field.cpp's PLATINUM_US_REV1 and pk_nds_call.cpp's PLATINUM (port_nds_fns_known.txt's names).
GEN4P = [
    ("sFieldSystem", "fieldSystemPtr", True), ("gBattleApplicationTemplate", "battleTemplate", True),
    ("sSoundSystem", "soundSystem", True), ("sSeqPlayer", "seqPlayer", True), ("sSaveDataPtr", "saveDataPtr", True),
    ("FieldMap_Main", "fieldMapMain", True),
    ("PartyMenu_Init", "partyInit", False), ("OptionsMenu_Init", "optionsInit", False),
    ("ScriptManager_Set", "scriptManagerSet", True), ("FieldTask_GetEnv", "fieldTaskGetEnv", True),
    ("ScriptContext_CreateAndStart", "scriptContextCreateAndStart", True), ("ScriptContext_Jump", "scriptContextJump", True),
    ("StringTemplate_New", "stringTemplateNew", True), ("String_Init", "stringInit", True),
    ("ScriptManager_GetMemberPtr", "scriptManagerGetMemberPtr", True),
    ("FieldMoves_SetUsableMoves", "fieldMovesSetUsableMoves", True), ("FieldMoves_CheckFly", "fieldMovesCheckFly", True),
    ("CheckFlyLocationUnlocked", "checkFlyLocationUnlocked", True), ("SaveData_GetParty", "saveDataGetParty", True),
    ("Party_GetPokemonBySlotIndex", "partyGetPokemonBySlotIndex", True), ("FlyContext_New", "flyContextNew", True),
    ("FieldMoves_FlyTask", "fieldMovesFlyTask", True), ("FieldSystem_CreateTask", "fieldSystemCreateTask", True),
    ("Journal_CreateEventUsedMove", "journalCreateEventUsedMove", True), ("Journal_SaveData", "journalSaveData", True),
]
GEN5 = [
    ("GameSystem", "gameSystem", True), ("BgmStack", "bgmStack", True), ("sSeqPlayer", "seqPlayer", True),
    ("SaveControl", "saveControl", True), ("StartMenuEvent", "startMenuEvent", False),
    ("FieldEventCheck", "eventCheck", True), ("ReturnZero", "returnZero", True),
    ("GameSystem_SetEvent", "setEvent", True), ("ScriptEvent", "scriptEvent", True),
    ("ScriptEventCheck", "scriptEventCheck", True), ("FldSkill_InitCheck", "skillInitCheck", True),
    ("FldSkill_CanUse", "skillCanUse", True), ("FldSkill_Use", "skillUse", True),
]
# base -> (its table group: one C array each, its words).
BASES = {"heartgold": ("4", GEN4), "platinum": ("4p", GEN4P), "black": ("5", GEN5), "black2": ("5", GEN5)}
KINDS = {"heartgold": {"HEARTGOLD", "SOULSILVER"}, "platinum": {"PLATINUM"}, "black": {"BLACK", "WHITE"},
         "black2": {"BLACK2", "WHITE2"}}
META = {"code", "rev", "kind", "base", "name", "title", "sha1", "cart"}
HEADER = "Generated by scripts/gen_nds_ports.py from gamedata/nds/ports.toml - don't edit by hand."


def load():
    with open(SRC, "rb") as f:
        ports = tomllib.load(f).get("port", [])
    seen = set()
    for p in ports:
        where = f"{p.get('code')} rev {p.get('rev')}"
        for k in META:
            if k not in p:
                sys.exit(f"{where}: no {k}")
        if (p["code"], p["rev"]) in seen:
            sys.exit(f"{where}: listed twice")
        seen.add((p["code"], p["rev"]))
        if p["base"] not in BASES:
            sys.exit(f"{where}: base {p['base']} isn't one of {sorted(BASES)}")
        if p["kind"] not in KINDS[p["base"]]:
            sys.exit(f"{where}: kind {p['kind']} doesn't run on base {p['base']}")
        if len(p["code"]) != 4 or len(p["sha1"]) != 40:
            sys.exit(f"{where}: a code is 4 letters, a SHA-1 40 hex digits")
        words = BASES[p["base"]][1]
        names = {w[0] for w in words}
        for k in p:
            if k not in META and k not in names:
                sys.exit(f"{where}: unknown word {k}")
        for name, _, required in words:
            if required and not p.get(name):
                sys.exit(f"{where}: no {name}")
    return ports


def followed(p):
    """The cart's touch-screen moments are followed: every menu function it needs is known."""
    if BASES[p["base"]][0] == "4":
        return all(p.get(k) for k in ("Task_StartMenu", "PartyMenuApp_Init", "OptionsApp_Init", "Pokedex_Init"))
    if BASES[p["base"]][0] == "4p":
        return all(p.get(k) for k in ("PartyMenu_Init", "OptionsMenu_Init"))
    return bool(p.get("StartMenuEvent"))


def c_text(ports):
    out = [f"// {HEADER}", "#pragma once", "", "#include <stdint.h>", ""]
    out.append("// A HeartGold / SoulSilver build: the US tables (pk_nds_field.cpp's HEARTGOLD_US, pk_nds_call.cpp's HEARTGOLD) with")
    out.append("// these words. A menu function of 0 = that touch-screen moment isn't followed.")
    out.append("struct PkNdsPort4 {")
    out.append("    char code[5];")
    out.append("    int revision;")
    out.append("    const char* name;")
    out.append("    uint32_t " + ", ".join(w[1] for w in GEN4) + ";")
    out.append("};")
    out.append("")
    out.append("// A Platinum build: the US rev 1 tables (pk_nds_field.cpp's PLATINUM_US_REV1, pk_nds_call.cpp's PLATINUM) with")
    out.append("// these words. partyInit / optionsInit 0 = those top-screen pages aren't followed.")
    out.append("struct PkNdsPort4P {")
    out.append("    char code[5];")
    out.append("    int revision;")
    out.append("    const char* name;")
    out.append("    uint32_t " + ", ".join(w[1] for w in GEN4P) + ";")
    out.append("};")
    out.append("")
    out.append("// A Black / White build (sequel 0) or Black 2 / White 2 (sequel 1): the US tables with these words; the BGM stack's")
    out.append("// depth is bgmStack - 0xC. startMenuEvent 0 = the touch-screen moments aren't followed.")
    out.append("struct PkNdsPort5 {")
    out.append("    char code[5];")
    out.append("    int revision;")
    out.append("    const char* name;")
    out.append("    int sequel;")
    out.append("    uint32_t " + ", ".join(w[1] for w in GEN5) + ";")
    out.append("};")
    for gen, typ, arr in (("4", "PkNdsPort4", "PK_NDS_PORTS4"), ("4p", "PkNdsPort4P", "PK_NDS_PORTS4P"),
                          ("5", "PkNdsPort5", "PK_NDS_PORTS5")):
        rows = [p for p in ports if BASES[p["base"]][0] == gen]
        out.append("")
        out.append(f"static const {typ} {arr}[] = {{")
        for p in rows:
            words = BASES[p["base"]][1]
            head = f'"{p["code"]}", {p["rev"]}, "{p["name"]}"'
            if gen == "5":
                head += f", {1 if p['base'] == 'black2' else 0}"
            vals = ", ".join(f"0x{p.get(w[0], 0):08X}" for w in words)
            out.append(f"    {{ {head},")
            out.append(f"      {vals} }},")
        out.append("};")
        out.append(f"static const int {arr}_COUNT = (int) (sizeof {arr} / sizeof {arr}[0]);")
    return "\n".join(out) + "\n"


def kt_text(ports):
    out = [f"// {HEADER}", "package com.pokedaisy.app.companion.data", ""]
    out.append("/** The DS language ports (gamedata/nds/ports.toml): what the Kotlin side reads of each, [DsPorts] builds the configs. */")
    out.append("val NDS_PORTS: List<NdsPort> = listOf(")
    for p in ports:
        gen = BASES[p["base"]][0]
        save, system, battle = {"4": ("sSaveDataPtr", "sFieldSysPtr", "gOverlayTemplate_Battle"),
                                "4p": ("sSaveDataPtr", "sFieldSystem", "gBattleApplicationTemplate"),
                                "5": ("SaveControl", "GameSystem", None)}[gen]
        args = [f'"{p["code"]}"', str(p["rev"]), f"GameKind.{p['kind']}", f'"{p["title"]}"', f'"{p["sha1"]}"',
                f"saveData = 0x{p[save]:08X}", f"system = 0x{p[system]:08X}"]
        if battle:
            args.append(f"battleTemplate = 0x{p[battle]:08X}")
        args.append(f"followed = {'true' if followed(p) else 'false'}")
        out.append(f"    NdsPort({', '.join(args)}),")
    out.append(")")
    return "\n".join(out) + "\n"


def main():
    ports = load()
    files = {C_OUT: c_text(ports), KT_OUT: kt_text(ports)}
    if "--check" in sys.argv:
        stale = [p for p, t in files.items() if not os.path.exists(p) or open(p, encoding="utf-8").read() != t]
        if stale:
            sys.exit("stale (run make gamedata): " + ", ".join(os.path.relpath(p, ROOT) for p in stale))
        return
    for path, text in files.items():
        with open(path, "w", encoding="utf-8") as f:
            f.write(text)
    print(f"{len(ports)} ports -> {os.path.relpath(C_OUT, ROOT)}, {os.path.relpath(KT_OUT, ROOT)}")


if __name__ == "__main__":
    main()
