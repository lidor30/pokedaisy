#!/usr/bin/env python3
"""The DS games' physical / special / status split, for the move category icon (`moveKind`, MoveCategoriesGen.kt).

Gen 4 and 5 keep a category on each move; Gen 1 to 3 go by type, so they need no table. Numbers only. Reads
$DECOMPS/pokeplatinum's res/moves/*/data.json and Black's move records (/a/0/2/1, category at +2), and fails where the
two disagree on a move they share.

    DECOMPS=... python3 scripts/gen_move_categories.py "<Black's .nds>"
"""
import json
import os
import sys

sys.path.insert(0, os.path.dirname(__file__))
from gen_gen5_tables import Rom  # noqa: E402

OUT = os.path.join(os.path.dirname(__file__), "..", "app/src/main/kotlin/com/pokedaisy/app/companion/data/MoveCategoriesGen.kt")
PHYSICAL, SPECIAL, STATUS = "PHYSICAL", "SPECIAL", "STATUS"


def platinum(dec):
    out = {}
    with open(os.path.join(dec, "generated/moves.txt")) as f:
        syms = [line.strip() for line in f if line.strip()]
    for i, sym in enumerate(syms):
        path = os.path.join(dec, "res/moves", sym[len("MOVE_"):].lower(), "data.json")
        if i and os.path.exists(path):
            with open(path) as j:
                out[i] = json.load(j)["class"][len("CLASS_"):]
    return out


def black(path):
    records = Rom(path).narc("/a/0/2/1")
    # Which byte value is which, from moves that can't be anything else: POUND, THUNDERBOLT, GROWL.
    names = {records[1][2]: PHYSICAL, records[85][2]: SPECIAL, records[45][2]: STATUS}
    assert len(names) == 3, names
    return {i: names[records[i][2]] for i in range(1, 560)}


def ints(ids):
    ids = sorted(ids)
    lines = [", ".join(str(i) for i in ids[n:n + 20]) for n in range(0, len(ids), 20)]
    return "\n".join("    " + line + "," for line in lines)


def main():
    pt = platinum(os.path.join(os.environ["DECOMPS"], "pokeplatinum"))
    bw = black(sys.argv[1])
    differ = {i: (pt[i], bw[i]) for i in pt if bw[i] != pt[i]}
    assert not differ, differ
    assert len(pt) >= 460, len(pt)
    with open(OUT, "w") as f:
        f.write("// Generated by scripts/gen_move_categories.py. Do not edit.\n")
        f.write("package com.pokedaisy.app.companion.data\n\n")
        f.write("/** The DS games' special moves, by move id (Platinum, HeartGold / SoulSilver, Black to White 2). */\n")
        f.write("internal val dsSpecialMoves: Set<Int> = hashSetOf(\n" + ints(i for i, c in bw.items() if c == SPECIAL) + "\n)\n\n")
        f.write("/** Their status moves; any other is physical. */\n")
        f.write("internal val dsStatusMoves: Set<Int> = hashSetOf(\n" + ints(i for i, c in bw.items() if c == STATUS) + "\n)\n")
    print(len(bw), "moves,", sum(c == SPECIAL for c in bw.values()), "special,", sum(c == STATUS for c in bw.values()), "status")


if __name__ == "__main__":
    main()
