"""Generate verified normal-3.2.3 Bag / field observations; no ROM bytes or guessed offsets.
Input: official polishedcrystal-3.2.3.sym release asset. App-owned fields are
cross-checked against Gen2Reader.kt; ROM identity comes from the app's table.
"""
from pathlib import Path
import argparse, hashlib, re
p=argparse.ArgumentParser();p.add_argument('symbols',type=Path);p.add_argument('--check',action='store_true');a=p.parse_args()
raw=a.symbols.read_bytes()
digest=hashlib.sha256(raw).hexdigest()
if digest!='be1ca87ad487ade20701ed71fcae4e99bf16b908af727b84575c862b73ea2955':raise SystemExit('Wrong release symbols; review new versions explicitly')
symbols={n:(int(b,16)<<16)|int(v,16) for b,v,n in re.findall(r'^([0-9a-fA-F]+):([0-9a-fA-F]+) (\S+)$',raw.decode(),re.M)}
base=Path(__file__).resolve().parents[1]/'app/src/main/kotlin/com/pokedaisy/app/companion/data'
reader=(base/'Gen2Reader.kt').read_text().split('val GEN2_POLISHED_CRYSTAL = GEN2_CRYSTAL.copy(',1)[1].split('\n)',1)[0]
app={k:(int(b)<<16)|int(v,16) for k,b,v in re.findall(r'(\w+) = wramx\((\d+), (0x[0-9A-Fa-f]+)\)',reader)}
app.update({k:int(v,16) for k,v in re.findall(r'(\w+) = (0x[0-9A-Fa-f]+)L',reader)})
for field,sym in [('battleMode','wBattleMode'),('menuCursor','wMenuCursorY'),('menu2D','w2DMenuCursorInitY'),('tileMap','wTilemap'),('partyMons','wPartyMon1'),('battleMon','wBattleMon'),('partyMenuAction','wPartyMenuActionText'),('curBattleMon','wCurBattleMon'),('moveMenuType','wMoveSelectionMenuType'),('numKeyItems','wKeyItems')]:
 if app[field]!=symbols[sym]:raise SystemExit('App / release observation mismatch: '+field)
ids=(base/'Gen2PolishedCrystalGen.kt').read_text()
sha=re.search(r'"([0-9a-f]{40})" to intArrayOf\([^\n]+// polishedcrystal-3\.2\.3\s*$',ids,re.M)
if not sha:raise SystemExit('App ROM identity changed')
fields={'STATE':'wStateFlags','SCRIPT':'wScriptMode','MAP':'wMapStatus','BATTLE':'wBattleMode','LIST':'wMenuItemsList','POINTER':'wMenuDataPointer','CURSOR':'wMenuCursorY','POCKET':'wCurPocket','SCROLL':'wMenuScrollPosition','ITEM':'wCurItem','MENU2D':'w2DMenuCursorInitY','TILEMAP':'wTilemap','PACK_STATE':'wJumptableIndex','IN_MENU':'hInMenu','QUEUE':'wMapReentryScriptQueueFlag','SCRIPT_RUNNING':'wScriptRunning','MAP_EVENTS':'wMapEventStatus','PARTY_COUNT':'wPartyCount','WILD_COOLDOWN':'wWildEncounterCooldown','PARTY_MON':'wPartyMon1','PARTY_MENU':'wPartyMenuActionText','KEYS':'wKeyItems','PLAYER_STATE':'wPlayerState','REPEL_STEPS':'wRepelEffect','BADGES':'wJohtoBadges','CUR_PARTY':'wCurPartyMon','MON_COUNT':'wBuffer1','MON_LIST':'wBuffer2',}
out=['/* Generated by gen_polished_actions.py. GPL-3.0. No ROM bytes. */','/* Official v3.2.3 symbols SHA256 '+digest+' */','#ifndef PD_POLISHED_ACTION_DATA_H','#define PD_POLISHED_ACTION_DATA_H','#define PD_PC_ACTION_SHA "'+sha[1]+'"']
cursor_tile=re.search(r'\bcursorTile = (0x[0-9A-Fa-f]+|[0-9]+)',reader)
if not cursor_tile:raise SystemExit('Missing Polished cursor tile')
out.append('#define PD_PC_CURSOR_TILE '+cursor_tile[1]+'u')
for key,sym in fields.items():out.append('#define PD_PC_'+key+' '+hex(symbols[sym]&65535 if symbols[sym]&65535>=0xff00 else symbols[sym])+'u /* '+sym+' */')
for key,end,start in [('PARTY_SIZE','wPartyMon2','wPartyMon1'),('PARTY_MOVES_OFFSET','wPartyMon1Moves','wPartyMon1'),('PARTY_EGG_OFFSET','wPartyMon1IsEgg','wPartyMon1'),]:
 out.append('#define PD_PC_'+key+' '+str(symbols[end]-symbols[start])+'u')
egg=re.search(r'val egg = form and (0x[0-9A-Fa-f]+) != 0',(base/'Gen2Reader.kt').read_text())
if not egg:raise SystemExit('Missing app Polished egg flag')
out.append('#define PD_PC_PARTY_EGG_MASK '+egg[1]+'u')
move_data=(base/'MoveDataPolishedCrystal.kt').read_text()
fly=re.search(r'(\d+) to MoveInfo\("Fly",',move_data)
if not fly:raise SystemExit('Missing app Fly move')
out.append('#define PD_PC_FLY_MOVE '+fly[1]+'u')
out.append('#define PD_PC_MON_OPTIONS '+hex(symbols['MonMenuOptions'])+'u')
assert symbols['wMapReentryScriptBank']==symbols['wMapReentryScriptQueueFlag']+1
assert symbols['wMapReentryScriptAddress']==symbols['wMapReentryScriptQueueFlag']+2
# The first two script commands are readvar (2 bytes) and ifnotequal (4 bytes).
# Start at opentext so the shortcut skips the physical PC tile's facing rule.
out.append('#define PD_PC_PC_OPEN '+hex(symbols['PCScript']+2+4)+"u /* PCScript's opentext */")
keymax=re.search(r'\bkeyItemsMax = (\d+)',reader)
if not keymax:raise SystemExit('Missing key item capacity')
out.append('#define PD_PC_KEY_MAX '+keymax[1]+'u')
out.append('#define PD_PC_KEY_USE_SEL_MENU '+hex(symbols['MenuDataHeader_UseSel.MenuData2']&65535)+'u')
item_names=(base/'ItemNamesPolishedCrystal.kt').read_text().split('val itemNamesPolishedCrystalFaithfulChanges',1)[0]
app_items={name:int(key,0) for key,name in re.findall(r'(0x[0-9A-Fa-f]+|[0-9]+) to "([^\"]+)"',item_names)}
if any(name not in app_items for name in ['Bicycle','Repel','Super Repel','Max Repel']):raise SystemExit('Missing app field items')
keyids=sorted(v-0x200 for v in app_items.values() if 0x200<v<0x300)
assert keyids==list(range(1,max(keyids)+1)), 'Review sparse key item IDs'
out.append('#define PD_PC_KEY_ID_MAX '+str(max(keyids))+'u')
out.append('#define PD_PC_POTION '+str(app_items['Potion'])+'u')
out.append('#define PD_PC_HP_OFFSET '+str(symbols['wPartyMon1HP']-symbols['wPartyMon1'])+'u')
out.append('#define PD_PC_BICYCLE '+hex(app_items['Bicycle'])+'u')
out.append('static const struct {unsigned id;const char *name;} pd_pc_repels[]={'+','.join('{'+str(app_items[n])+',"'+n+'"}' for n in ['Repel','Super Repel','Max Repel'])+'};')
out.append('#define PD_PC_START_MENU '+hex(symbols['StartMenu.MenuData']&65535)+'u')
pockets=['Items','Medicine','Balls','Berries','KeyItems']
out.append('static const unsigned pd_pc_pack_menus[]={'+','.join(hex(symbols[x+'PocketMenuDataHeader.MenuData2']&65535) for x in pockets)+'};')
out.append('static const unsigned pd_pc_item_submenus[]={'+','.join(hex(symbols[x+'.MenuData2']&65535) for x in ['MenuDataHeader_UseGiveToss','MenuDataHeader_GiveToss','MenuDataHeader_Use'])+'};')
out.append('static const struct {unsigned addr, max, pocket, menu;} pd_pc_item_pockets[]={')
# Game pocket enum order (item_data_constants.asm), not a memory-address table.
for field,cap,pocket,menu,sym in [('numItems','itemsMax',0,0,'wNumItems'),('numMedicine','medicineMax',1,1,'wNumMedicine'),('numBalls','ballsMax',2,2,'wNumBalls'),('numBerries','berriesMax',4,3,'wNumBerries')]:
 if app[field]!=symbols[sym]:raise SystemExit('App / symbol bag mismatch: '+field)
 limit=re.search(r'\b'+cap+r' = (\d+)',reader)
 if not limit:raise SystemExit('Missing bag capacity: '+cap)
 out.append('{'+','.join([hex(app[field]),limit[1],str(pocket),str(menu)])+'},')
out.append('};')
out+=['#endif',''];text='\n'.join(out);dest=Path(__file__).resolve().parents[1]/'3ds/core/polished_action_data.h'
if a.check:
 if not dest.exists() or dest.read_text()!=text:raise SystemExit('Regenerate polished_action_data.h')
else:dest.write_text(text)
