"""Original GB diagnostic ROM. No commercial game code, art, or party data.
Displays stripes, advances a WRAM counter, writes a battery-save marker.
Only the four-byte format signature used by mGBA is included.
"""
from pathlib import Path
r=bytearray(32768);r[0x100:0x104]=bytes([0,0xc3,0x50,1]);r[0x104:0x108]=bytes([0xce,0xed,0x66,0x66]);r[0x134:0x13e]=b'PD-TEST-GB';r[0x147]=3;r[0x149]=2
code=[];labels={};fix=[]
def emit(*b):code.extend(b)
def label(n):labels[n]=len(code)
def jr(op,n):emit(op,0);fix.append((len(code)-1,n))
emit(0xf3,0x31,0xfe,0xff,0xaf,0xe0,0x40) # DI, stack, LCD off
emit(0x21,0,0x80,0x01,0,0x20) # HL=VRAM, BC=8192
label('clear');emit(0xaf,0x22,0x0b,0x78,0xb1);jr(0x20,'clear')
emit(0x21,0,0x80,0x06,8);label('tile');emit(0x3e,0xaa,0x22,0x3e,0x55,0x22,0x05);jr(0x20,'tile')
emit(0x3e,0xe4,0xe0,0x47,0x3e,0x91,0xe0,0x40)
emit(0x3e,0x0a,0xea,0,0,0x3e,0x5a,0xea,0,0xa0)
# Start a square-wave tone to exercise the real audio queue.
emit(0x3e,0x80,0xe0,0x26,0x3e,0x77,0xe0,0x24,0x3e,0x11,0xe0,0x25,0x3e,0x80,0xe0,0x11,0x3e,0xf0,0xe0,0x12,0x3e,0,0xe0,0x13,0x3e,0x87,0xe0,0x14)
label('loop');emit(0xf0,0x44,0xfe,144);jr(0x20,'loop');emit(0x21,0,0xc0,0x34)
label('wait');emit(0xf0,0x44,0xfe,144);jr(0x28,'wait');jr(0x18,'loop')
for p,n in fix:code[p]=(labels[n]-p-1)&255
r[0x150:0x150+len(code)]=bytes(code);r[0x14d]=(-sum(r[0x134:0x14d])-25)&255
Path('diagnostic.gb').write_bytes(r)

# Original ARM7TDMI diagnostic. Mode 3 one-pixel stripes, then an idle loop.
# Format fields are enough for mGBA; no commercial logo or ROM code included.
import struct
r=bytearray(32768)
r[0:4]=struct.pack('<I',0xea00002e)
r[0xa0:0xac]=b'PD TEST GBA '
r[0xac:0xb0]=b'BPRE';r[0xb2]=0x96;r[0xbc]=1
ops=[
    0xe59f0024,0xe59f1024,0xe1c010b0, # Set mode 3 with BG2 enabled.
    0xe59f0020,0xe59f1020,0xe59f2020, # Load VRAM, the first color, and pixel count.
    0xe0c010b2,0xe2211901,0xe2522001,0x1afffffb, # Store a pixel, toggle bit 14, and loop.
    0xeafffffe,0x04000000,0x403,0x06000000,0x4a52,38400,
]
r[0xc0:0xc0+4*len(ops)]=struct.pack('<'+'I'*len(ops),*ops)
r[0xbd]=(-sum(r[0xa0:0xbd])-0x19)&255
Path('diagnostic.gba').write_bytes(r)
