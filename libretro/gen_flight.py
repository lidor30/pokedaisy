"""Emit the retail pilot's shared flight records from Android's game data.

python3 libretro/gen_flight.py > libretro/pd_flight_gen.h writes the header; --check exits 1 while the committed one is stale.
Each profile carries pk_flight_configure's words (FlightFns.words) and what FLIGHT AREA reads (pd_flight_area.h: the
flight record's map groups / heal locations / save blocks, its FLY record's towns, the HealWarp's home town)."""
from pathlib import Path
import sys
import tomllib

root = Path(__file__).resolve().parents[1]
header = root / "libretro/pd_flight_gen.h"
keys = """
objectEvents playerAvatar sprites vmap connectionFlags saveBlock2Ptr main cb2Overworld
lockByte paletteFade lockControls unlockControls createSprite destroySprite startSpriteAnim birdTemplate
behaviorAt collisionAt elevationAt objectAt playSe seFly seFailure walkFast walkFaster spriteOffset
walkCurrent walkSlide mapHeader mapGroups drawMetatileAt riderTemplate riderGfx spriteDummy riderAnim
scratch drawView spriteOffsetY mapGroupsXor birdPalette birdPaletteTag objSpriteId followerRemove followerUpdate
mapGridUndefined vehicle
""".split()
# (flight record, FLY record, ROM SHA-1): FireRed rev 0's FLY is its port table's (ported.toml).
profiles = (
    ("FLIGHT_FIRERED_REV0", "FIELD_ITEMS_PORTS_BPRE0_FLY", "41cb23d8dccc8ebd7c649cd8fbb58eeace6e2fdc"),
    ("FLIGHT_FIRERED_REV1", "FLY_FIRERED_REV1", "dd5945db9b930750cb39d00c84da8571feebf417"),
    ("FLIGHT_EMERALD", "FLY_EMERALD", "f3ae088181bf583e55daf962a92bb46f4f1d07b7"),
)
GROUPS = 64  # pd_flight_area.h's PD_FLIGHT_AREA_GROUPS

records = {}
for path in sorted((root / "gamedata/gen3/records").glob("*.toml")):
    records |= tomllib.loads(path.read_text()).get("record", {})
defaults = {}
for schema in ("gen3_flight", "gen3_fly", "gen3_heal_warp"):
    fields = tomllib.loads((root / f"gamedata/schema/{schema}.toml").read_text())["field"]
    defaults[schema] = {k: v["default"] for k, v in fields.items() if "default" in v and v["default"] != "none"}


def resolve(name):
    rec = records[name]
    got = (resolve(rec["base"]) if "base" in rec else {}) | rec
    return defaults.get(got.get("schema"), {}) | got


def padded(values, n, fill):
    values = list(values)
    assert len(values) <= n, values
    return values + [fill] * (n - len(values))


def ints(values):
    return "{" + ", ".join(str(v) for v in values) + "}"


def emit():
    out = ["/* Generated by libretro/gen_flight.py from gamedata/gen3/records. */",
           '#include "pd_flight_area.h"',
           "static const struct { const char *sha1; uint32_t words[PK_FLIGHT_WORDS]; struct pd_flight_area_cfg area; } flight_profiles[] = {"]
    for name, fly_name, sha in profiles:
        rec = resolve(name)
        no_fly = (rec["noFly"] + [0xffff] * 4)[:4]
        land = [0] * 8
        for tile in set(rec["landOk"]):
            land[tile // 32] |= 1 << (tile % 32)
        words = [rec.get(key, 0) for key in keys]
        words += [no_fly[i] | (no_fly[i+1] << 16) for i in (0, 2)] + land
        out.append(f'  {{"{sha}", {{')
        for i in range(0, len(words), 6):
            out.append("    " + ", ".join(f"0x{word:X}u" for word in words[i:i+6]) + ",")
        fly = resolve(fly_name)
        hw = resolve(fly["healWarp"]) if "healWarp" in fly else None
        sizes = rec["mapGroupSizes"]
        special = sorted(hw["special"]) if hw else []
        out.append("  }, {")
        out.append(f"    .mapGroups = 0x{rec['mapGroups']:X}u, .mapGroupsXor = 0x{rec['mapGroupsXor']:X}u, .mapGroupCount = {len(sizes)},")
        out.append(f"    .mapGroupSizes = {ints(sizes)},")
        out.append(f"    .healLocations = 0x{rec['healLocations']:X}u, .healLocationSize = {rec['healLocationSize']}, "
                   f".healLocationCount = {rec['healLocationCount']},")
        out.append(f"    .saveBlock1Ptr = 0x{rec['saveBlock1Ptr']:X}u, .saveBlock2Ptr = 0x{rec['saveBlock2Ptr']:X}u, "
                   f".saveBlock1PosOff = {rec['saveBlock1PosOff']}, .saveBlockStatic = {int(rec['saveBlockStatic'])},")
        out.append(f"    .noFly = {ints(no_fly)},")
        out.append(f"    .flagGet = 0x{fly['flagGet']:X}u, .getMapsecType = 0x{fly['getMapsecType']:X}u, "
                   f".destinations = 0x{fly['destinations']:X}u, .firstMapsec = {fly['firstMapsec']}, .count = {fly['count']},")
        out.append(f"    .flyTypes = {ints(padded(sorted(set(fly['flyTypes'])), 4, -1))}, "
                   f".extraMapsecs = {ints(padded(fly['extraMapsecs'], 4, -1))},")
        if hw:
            out.append(f"    .healWarp = 1, .hwSaveBlock2Ptr = 0x{hw['saveBlock2Ptr']:X}u, .hwSaveBlock2Static = {int(hw['saveBlock2Static'])}, "
                       f".genderMapsec = {hw['genderMapsec']}, .maleHeal = {hw['maleHeal']}, .femaleHeal = {hw['femaleHeal']},")
            out.append(f"    .special = {{{', '.join(ints(p) for p in padded(special, 4, (-1, -1)))}}},")
        else:
            out.append("    .healWarp = 0, .special = {{-1, -1}, {-1, -1}, {-1, -1}, {-1, -1}},")
        assert len(sizes) <= GROUPS
        out.append("  }},")
    out.append("};")
    return "\n".join(out) + "\n"


text = emit()
if "--check" in sys.argv[1:]:
    if header.read_text() != text:
        sys.exit(f"{header.relative_to(root)} is stale: run python3 libretro/gen_flight.py > {header.relative_to(root)}")
    print(f"{header.relative_to(root)} is up to date")
else:
    sys.stdout.write(text)
